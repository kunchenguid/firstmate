// Live OpenCode 2 regression for location-scoped event handling, run by
// tests/fm-opencode-primary-live-e2e.test.sh against a real `opencode serve`.
// Every scenario starts its own private server with an isolated OS home, XDG
// directories, database, and loopback model provider, on scratch Firstmate
// homes under the system temporary directory, so no live home, lock, shared
// service, or credential is touched. It proves at the real event boundary:
//   a) two locations on one server: a turn on A never runs B's guard into A's
//      session nor changes B's busy record, while B's own turn still does both;
//   b) a marked secondmate home completes two consecutive cycles of watcher
//      notification, model-handled drain, generation-bound acknowledgement,
//      and a live successor watcher whose identity matches the cycle ledger;
//   c) a primary whose session lock names a foreign live process is refused
//      arming and is warned, and arms once its own server owns the lock.
// BUSY_PLUGIN names an OpenCode 2 busy-state plugin generated by the real
// bin/fm-spawn.sh, recording into BUSY_STATE for task BUSY_ID.
import { execFileSync, spawn } from "node:child_process";
import {
  appendFileSync,
  cpSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  openSync,
  readFileSync,
  realpathSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { createServer } from "node:http";
import { createServer as createNetServer } from "node:net";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repo = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const { BUSY_PLUGIN, BUSY_STATE, BUSY_ID } = process.env;
if (!BUSY_PLUGIN || !BUSY_STATE || !BUSY_ID) throw new Error("BUSY_PLUGIN, BUSY_STATE and BUSY_ID are required");

const sleep = (ms) => new Promise((done) => setTimeout(done, ms));
const ACK = /WAKE_ACK_REQUIRED: after handling completes run (bin\/fm-wake-drain\.sh --ack-through [0-9]+ --recovery-generation [A-Za-z0-9._-]+)/;

async function until(check, label, ms = 60000) {
  const deadline = Date.now() + ms;
  while (Date.now() < deadline) {
    const value = await check();
    if (value) return value;
    await sleep(100);
  }
  throw new Error(`timed out: ${label}`);
}

function check(condition, message) {
  if (!condition) throw new Error(message);
}

// A deterministic OpenAI-compatible model. A watcher notification is handled
// the way the supervision protocol asks: drain with the real script, then run
// exactly the acknowledgement command the drain printed, then end the turn.
function startProvider() {
  const handled = [];
  const server = createServer((req, res) => {
    let raw = "";
    req.on("data", (chunk) => (raw += chunk));
    req.on("end", () => {
      const messages = JSON.parse(raw).messages ?? [];
      let lastUser = 0;
      messages.forEach((message, index) => {
        if (message.role === "user") lastUser = index;
      });
      const prompt = JSON.stringify(messages[lastUser]?.content ?? "");
      const tools = messages.slice(lastUser + 1).filter((message) => message.role === "tool");
      const lastTool = tools.length ? JSON.stringify(tools[tools.length - 1].content ?? "") : "";
      let command = "";
      let text = "ACK";
      if (prompt.includes("WATCHER FIRED")) {
        if (tools.length === 0) {
          command = "bin/fm-wake-drain.sh";
        } else if (tools.length === 1) {
          const ack = lastTool.match(ACK);
          if (ack) command = ack[1];
          else text = "UNHANDLED: the drain printed no acknowledgement command";
        } else {
          handled.push(lastTool);
          text = "HANDLED";
        }
      }
      res.writeHead(200, { "Content-Type": "text/event-stream" });
      const delta = command
        ? { role: "assistant", tool_calls: [{ index: 0, id: `call_${Date.now()}`, type: "function", function: { name: "shell", arguments: JSON.stringify({ command, description: "Handle the watcher notification" }) } }] }
        : { role: "assistant", content: text };
      const chunk = { id: "chatcmpl-scope", object: "chat.completion.chunk", created: 1, model: "fixture", choices: [{ index: 0, delta, finish_reason: null }] };
      res.write(`data: ${JSON.stringify(chunk)}\n\n`);
      chunk.choices[0] = { index: 0, delta: {}, finish_reason: command ? "tool_calls" : "stop" };
      res.write(`data: ${JSON.stringify(chunk)}\n\ndata: [DONE]\n\n`);
      res.end();
    });
  });
  return new Promise((ready) => server.listen(0, "127.0.0.1", () => ready({ server, handled, port: server.address().port })));
}

function freePort() {
  return new Promise((ready) => {
    const probe = createNetServer();
    probe.listen(0, "127.0.0.1", () => {
      const { port } = probe.address();
      probe.close(() => ready(port));
    });
  });
}

// A scratch Firstmate home whose code root is <dir>, carrying this checkout's
// tracked bin/ and primary plugins (never a generated busy plugin), with its
// own state and config and the provider configured for its location.
function makeHome(dir, providerPort, { init = true } = {}) {
  mkdirSync(dir, { recursive: true });
  if (init) execFileSync("git", ["init", "-q", dir]);
  cpSync(join(repo, "bin"), join(dir, "bin"), { recursive: true });
  cpSync(join(repo, ".opencode/plugins"), join(dir, ".opencode/plugins"), {
    recursive: true,
    filter: (source) => !source.endsWith("fm-busy-state.js"),
  });
  writeFileSync(join(dir, "AGENTS.md"), "# Isolated location-scope fixture\n");
  mkdirSync(join(dir, "state"), { recursive: true });
  mkdirSync(join(dir, "config"), { recursive: true });
  writeFileSync(join(dir, "state/task.meta"), "project=fixture\n");
  writeFileSync(join(dir, "opencode.json"), JSON.stringify({
    model: "fixture/native",
    snapshots: false,
    permissions: [{ action: "*", resource: "*", effect: "allow" }],
    providers: { fixture: { package: "@opencode/ai/providers/openai-compatible", settings: { baseURL: `http://127.0.0.1:${providerPort}/v1`, apiKey: "isolated-test-not-a-secret" }, models: { native: { capabilities: { tools: true, input: ["text"], output: ["text"] }, limit: { context: 100000, output: 1000 } } } } },
  }));
  return dir;
}

// The server is registered for cleanup the moment it is spawned, before any
// readiness wait can throw: its arguments carry no lab path, so the lab reaper
// would never find a server whose startup failed.
async function startServer(lab, cwd, cleanups) {
  const home = join(lab, "os-home");
  mkdirSync(home, { recursive: true });
  const env = {};
  for (const [key, value] of Object.entries(process.env)) {
    if (/^(OPENCODE_|FM_|XDG_)/.test(key) || ["TMUX", "HERDR_ENV", "NO_MISTAKES_GATE"].includes(key)) continue;
    env[key] = value;
  }
  Object.assign(env, {
    HOME: home,
    TMPDIR: lab,
    TMUX_TMPDIR: lab,
    FM_BACKEND: "tmux",
    FM_POLL: "1",
    FM_SIGNAL_GRACE: "0",
    FM_HEARTBEAT: "600",
    OPENCODE_DB: join(lab, "opencode.db"),
    OPENCODE_DISABLE_MODELS_FETCH: "1",
    OPENCODE_DISABLE_AUTOUPDATE: "1",
    OPENCODE_DISABLE_LSP_DOWNLOAD: "1",
  });
  for (const kind of ["CONFIG", "DATA", "CACHE", "STATE"]) {
    const path = join(home, kind.toLowerCase());
    mkdirSync(path, { recursive: true });
    env[`XDG_${kind}_HOME`] = path;
  }
  const port = await freePort();
  const logPath = join(lab, "server.log");
  const log = openSync(logPath, "w");
  const child = spawn("opencode", ["serve", "--hostname", "127.0.0.1", "--port", String(port)], { cwd, env, stdio: ["ignore", log, log] });
  const exited = () => child.exitCode !== null || child.signalCode !== null;
  const exit = new Promise((done) => {
    child.once("exit", done);
    child.once("error", done);
  });
  const stop = async () => {
    if (exited() || !child.pid) return;
    child.kill("SIGTERM");
    await Promise.race([exit, sleep(15000)]);
    if (!exited()) child.kill("SIGKILL");
  };
  cleanups.push(stop);
  let auth = "";
  const api = async (path, body, method) => {
    const response = await fetch(`http://127.0.0.1:${port}${path}`, {
      method: method ?? (body === undefined ? "GET" : "POST"),
      headers: { Authorization: auth, "Content-Type": "application/json" },
      body: body === undefined ? undefined : JSON.stringify(body),
    });
    const text = await response.text();
    if (!response.ok) throw new Error(`API ${path} returned ${response.status}: ${text}`);
    return text ? JSON.parse(text) : null;
  };
  const password = await until(() => {
    const match = existsSync(logPath) && readFileSync(logPath, "utf8").match(/^server password (.+)$/m);
    return match && match[1];
  }, "server readiness", 30000);
  auth = `Basic ${Buffer.from(`opencode:${password}`).toString("base64")}`;
  const plugins = async (directory) =>
    (await api(`/api/plugin?${new URLSearchParams({ "location[directory]": directory })}`)).data
      .filter((plugin) => plugin.state?.status === "active")
      .map((plugin) => plugin.id);
  const ready = (directory, expected) =>
    until(async () => {
      const active = await plugins(directory);
      return expected.every((id) => active.includes(id)) && active;
    }, `plugin readiness in ${directory}`, 30000);
  const session = async (directory) => (await api("/api/session", { location: { directory } })).data.id;
  const info = async (id) => (await api(`/api/session/${id}`)).data;
  const context = async (id) => (await api(`/api/session/${id}/context`)).data;
  const userTexts = async (id) => (await context(id)).filter((m) => m.type === "user").map((m) => m.text ?? "");
  const count = async (id, needle) => (await userTexts(id)).filter((text) => text.includes(needle)).length;
  const settled = async (id) => {
    const time = (await info(id)).time ?? {};
    return Boolean(time.idle && (!time.busy || time.idle >= time.busy));
  };
  // Prompt one turn and wait for it, and any follow-up it causes, to settle.
  const turn = async (id, text) => {
    const before = (await info(id)).time?.busy ?? 0;
    await api(`/api/session/${id}/prompt`, { text });
    await until(async () => ((await info(id)).time?.busy ?? 0) > before, `turn start in ${id}`);
    await until(() => settled(id), `turn settle in ${id}`);
  };
  return { pid: child.pid, ready, session, context, count, settled, turn, stop };
}

const watcherPid = (dir) => {
  try {
    return readFileSync(join(dir, "state/.watch.lock/pid"), "utf8").trim();
  } catch {
    return "";
  }
};
const alive = (pid) => {
  try {
    process.kill(Number(pid), 0);
    return true;
  } catch {
    return false;
  }
};
const stopWatcher = (dir) => {
  try {
    execFileSync(join(dir, "bin/fm-watch-arm.sh"), ["--stop"], { cwd: dir, stdio: "ignore", timeout: 15000, env: { ...process.env, FM_HOME: dir, FM_ROOT_OVERRIDE: dir } });
  } catch {}
};
const busyRecord = () =>
  execFileSync("bash", ["-c", '. "$1/bin/fm-busy-lib.sh" && fm_busy_record_read "$2" "$3"', "busy-read", repo, BUSY_STATE, BUSY_ID], { encoding: "utf8" }).trim();
const primaryPlugins = ["fm.primary.turnend-guard", "fm.primary.watch-arm"];
const BLIND = "TURN WOULD END BLIND";

// Every process still running from this scenario's own lab, matched only by
// the lab's unique temporary path: an arm child the server spawned outlives the
// server and can restart a watcher after a graceful stop.
function labProcesses(lab) {
  const paths = [lab, realpathSync(lab)];
  return execFileSync("ps", ["-axo", "pid=,command="], { encoding: "utf8" })
    .split("\n")
    .filter((line) => paths.some((path) => line.includes(`${path}/`)))
    .map((line) => Number(line.trim().split(/\s+/)[0]))
    .filter((pid) => pid && pid !== process.pid);
}

async function reapLab(lab) {
  for (const signal of ["SIGTERM", "SIGKILL"]) {
    for (const pid of labProcesses(lab)) {
      try {
        process.kill(pid, signal);
      } catch {}
    }
    await sleep(500);
  }
}

// Cleanups run in reverse registration order. Register a home's watcher stop
// before its server stop, so the server and its arm plugin are gone before the
// watcher is stopped; whatever the lab still runs afterwards is reaped. A
// cleanup failure never masks the scenario's own failure.
async function scenario(name, body) {
  const lab = mkdtempSync(join(tmpdir(), `fm-opencode-scope-${name}-`));
  const cleanups = [];
  let failure = null;
  try {
    await body(lab, cleanups);
  } catch (error) {
    failure = error;
  }
  for (const cleanup of cleanups.reverse()) {
    try {
      await cleanup();
    } catch {}
  }
  await reapLab(lab);
  for (let attempt = 1; ; attempt += 1) {
    try {
      rmSync(lab, { recursive: true, force: true });
      break;
    } catch (error) {
      if (attempt >= 20) {
        failure ??= new Error(`scenario ${name} left ${lab} behind: ${error.message}`);
        break;
      }
      await sleep(250);
    }
  }
  if (failure) throw failure;
}

const provider = await startProvider();
try {
  await scenario("two-locations", async (lab, cleanups) => {
    const a = makeHome(join(lab, "home-a"), provider.port);
    const b = makeHome(join(lab, "home-b"), provider.port);
    cpSync(BUSY_PLUGIN, join(b, ".opencode/plugins/fm-busy-state.js"));
    cleanups.push(() => stopWatcher(a));
    const server = await startServer(lab, a, cleanups);
    writeFileSync(join(a, "state/.lock"), `${server.pid}\n`);
    await server.ready(a, primaryPlugins);
    await server.ready(b, [...primaryPlugins, "fm.busy-state"]);
    const busyBefore = busyRecord();

    const sessionA = await server.session(a);
    await server.turn(sessionA, "A turn on location A.");
    await until(() => watcherPid(a), "location A arming its own watcher");
    await sleep(3000);
    check(await server.count(sessionA, BLIND) === 0, "a turn on location A received a turn-end warning");
    const startupNudge = "Run `bin/fm-session-start.sh` now";
    check(await server.count(sessionA, startupNudge) === 0, "location B nudged startup in A's already-owned session");
    check(busyRecord() === busyBefore, `a turn on location A changed location B's busy record: ${busyBefore} -> ${busyRecord()}`);

    const sessionB = await server.session(b);
    await until(async () => (await server.count(sessionB, startupNudge)) === 1, "location B's own startup nudge");
    await until(() => server.settled(sessionB), "location B settling after its startup nudge");
    await server.turn(sessionB, "A turn on location B.");
    await until(async () => (await server.count(sessionB, BLIND)) > 0, "location B's own turn-end warning");
    await until(() => server.settled(sessionB), "location B settling after its warning");
    check(busyRecord() !== busyBefore && busyRecord().includes("opencode-plugin"), `location B's own turn did not drive its busy record: ${busyRecord()}`);
    check(await server.count(sessionA, BLIND) === 0, "location B's warning reached location A's session");
    check(await server.count(sessionA, startupNudge) === 0, "location B's startup nudge reached location A's session");
    console.log("ok - two locations on one server: A receives neither B's warning nor startup nudge and leaves B's busy record untouched; B's own session drives all three");
  });

  await scenario("secondmate", async (lab, cleanups) => {
    const base = join(lab, "base");
    execFileSync("git", ["init", "-q", base]);
    execFileSync("git", ["-C", base, "-c", "user.name=t", "-c", "user.email=t@example.invalid", "commit", "-q", "--allow-empty", "-m", "base"]);
    const mate = join(lab, "secondmate");
    execFileSync("git", ["-C", base, "worktree", "add", "-q", "--detach", mate]);
    makeHome(mate, provider.port, { init: false });
    writeFileSync(join(mate, ".fm-secondmate-home"), "sm-lab\n");
    cleanups.push(() => stopWatcher(mate));
    const server = await startServer(lab, mate, cleanups);
    writeFileSync(join(mate, "state/.lock"), `${server.pid}\n`);
    await server.ready(mate, primaryPlugins);
    const session = await server.session(mate);
    await server.turn(session, "Start the secondmate session.");
    let previous = await until(() => watcherPid(mate), "secondmate arming its own watcher");
    check(alive(previous), "the secondmate's first watcher is not alive");
    for (let cycle = 1; cycle <= 2; cycle += 1) {
      const notified = await server.count(session, "WATCHER FIRED");
      const handled = provider.handled.length;
      appendFileSync(join(mate, "state/task.status"), `working: scope fixture cycle ${cycle}\n`);
      await until(async () => (await server.count(session, "WATCHER FIRED")) > notified, `cycle ${cycle} notification`);
      await until(() => provider.handled.length > handled, `cycle ${cycle} model handling`);
      await until(() => server.settled(session), `cycle ${cycle} settle`);
      // A clean acknowledgement prints nothing; every refusal or partial
      // consumption the drain reports starts with "wake drain:".
      const ack = provider.handled[provider.handled.length - 1];
      check(!ack.includes("wake drain:"), `cycle ${cycle} acknowledgement was refused or partial: ${ack}`);
      const successor = await until(() => {
        const pid = watcherPid(mate);
        return pid && pid !== previous && alive(pid) && pid;
      }, `cycle ${cycle} live successor watcher`);
      const ledger = await until(() => {
        const log = join(mate, "state/.watch-cycle-exits.log");
        const rows = existsSync(log) ? readFileSync(log, "utf8").split("\n") : [];
        return rows.find((row) => row.includes(`\twatcher_pid=${previous}\t`) && row.endsWith(`\tsuccessor=started:${successor}`));
      }, `cycle ${cycle} ledger naming successor ${successor}`);
      check(/\texit_code=0\t/.test(ledger), `cycle ${cycle} watcher did not exit cleanly: ${ledger}`);
      const redrain = execFileSync("bash", ["-c", 'bin/fm-wake-drain.sh 2>&1 || true'], { cwd: mate, encoding: "utf8", env: { ...process.env, FM_HOME: mate, FM_ROOT_OVERRIDE: mate } });
      check(!redrain.includes("WAKE_ACK_REQUIRED"), `cycle ${cycle} left an unacknowledged wake: ${redrain}`);
      previous = successor;
    }
    check(await server.count(session, BLIND) === 0, "the secondmate session received a turn-end warning");
    console.log("ok - a marked secondmate home completes two notified, handled, acknowledged cycles with a live identity-matched successor");
  });

  await scenario("foreign-lock", async (lab, cleanups) => {
    const primary = makeHome(join(lab, "primary"), provider.port);
    const foreign = spawn("sleep", ["300"], { stdio: "ignore" });
    cleanups.push(() => foreign.kill("SIGKILL"));
    writeFileSync(join(primary, "state/.lock"), `${foreign.pid}\n`);
    cleanups.push(() => stopWatcher(primary));
    const server = await startServer(lab, primary, cleanups);
    await server.ready(primary, primaryPlugins);
    const session = await server.session(primary);
    await server.turn(session, "A turn under a foreign lock owner.");
    await until(async () => (await server.count(session, BLIND)) > 0, "the refused primary's turn-end warning");
    await until(() => server.settled(session), "the refused primary settling");
    await sleep(2000);
    check(!watcherPid(primary), "a primary armed although its lock names a foreign live process");
    writeFileSync(join(primary, "state/.lock"), `${server.pid}\n`);
    await server.turn(session, "A turn once this server owns the lock.");
    await until(() => watcherPid(primary), "arming after the lock names this server");
    console.log("ok - a primary under a foreign lock owner is refused arming and warned, and arms once it owns the lock");
  });
} finally {
  provider.server.close();
}
