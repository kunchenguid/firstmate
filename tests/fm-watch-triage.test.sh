  ack_stopped_cycle "$state" || fail "could not acknowledge the intentional paused phase-A stop"

  # Phase B: age the pause past the (now normal) threshold by backdating its
  # status file, re-prime .seen-* to the new signature so the signal scan stays
  # quiet, and confirm it re-surfaces as a paused recheck - never a wedge.
  back=$(( $(date +%s) - 500 ))
  if [ "$(uname)" = Darwin ]; then touch -mt "$(date -r "$back" '+%Y%m%d%H%M.%S')" "$statusf"
  else touch -m -d "@$back" "$statusf"; fi
  sig=$(seen_sig "$statusf"); printf '%s' "$sig" > "$state/.seen-held_status"
  : > "$out"
  printf 'idle, holding for upstream (token 2)' > "$capture_file"
  PATH="$fakebin:$PATH" FM_FAKE_TMUX_WINDOW="$window" FM_FAKE_TMUX_CAPTURE="$capture_file" \
    FM_FAKE_TMUX_CURRENT_COMMAND=grok \
    FM_STATE_OVERRIDE="$state" FM_CREW_STATE_BIN="$fakebin/fm-crew-state.sh" FM_PAUSE_RESURFACE_SECS=240 FM_POLL=1 FM_SIGNAL_GRACE=1 \
    FM_CHECK_INTERVAL=999999 FM_HEARTBEAT=999999 "$WATCH" > "$out" &
  pid=$!
  wait_for_exit "$pid" 100 || fail "watcher did not re-surface a declared pause past the threshold"
  grep -F "stale: $window" "$out" >/dev/null || fail "re-surface did not print a stale wake"
  grep -F "awaiting external" "$out" >/dev/null || fail "re-surface was not labeled a paused/awaiting-external recheck"
  grep -F "possible wedge" "$out" >/dev/null && fail "a declared pause was mislabeled a possible wedge"
  [ -e "$state/.paused-resurfaced-$key" ] || fail "the paused re-surface throttle marker was not recorded"
  [ ! -e "$state/.stale-since-$key" ] || fail "a paused re-surface must not use the wedge timer"
  FM_STATE_OVERRIDE="$state" "$DRAIN" > "$drain_out" 2>/dev/null || fail "drain after the paused re-surface failed"
  grep "$(printf '\tstale\t')" "$drain_out" | grep -F "$window" >/dev/null || fail "paused re-surface was not queued"
  pass "a declared pause is absorbed on first sight, then re-surfaced as a recheck past the threshold, never wedge-escalated"
}

# Wait until the watcher completes a poll for <key>, evidenced by its recorded pane
# hash advancing past <before>. A churning pane rewrites that hash every poll, so this
# returns as soon as one poll is done instead of burning a fixed liveness budget, and
# it proves a poll actually happened rather than only that the process is still alive.
wait_poll_after() {  # <state> <key> <before-hash> [<ticks>]
  local state=$1 key=$2 before=$3 limit=${4:-100} i=0
  while [ "$i" -lt "$limit" ]; do
    [ "$(cat "$state/.hash-$key" 2>/dev/null || true)" != "$before" ] && return 0
    sleep 0.1
    i=$((i + 1))
  done
  return 1
}

# Count queued stale wakes for <window>. An absorbed cycle never creates the queue
# file at all, so an absent queue counts as zero rather than an awk error.
queued_stale_wakes() {  # <state> <window>
  local state=$1 window=$2
  [ -e "$state/.wake-queue" ] || { printf '0\n'; return 0; }
  awk -F '\t' -v w="$window" '$3 == "stale" && $4 == w { n++ } END { print n + 0 }' "$state/.wake-queue"
}

# Wait until a live watcher records one more copy of <verdict> than <baseline>.
# The declared-pause preflight performs liveness and authoritative-state reads
# before capture or busy triage, so a fixed sleep can reap a healthy watcher
# before that poll finishes on a loaded host.
triage_verdict_count() {  # <state> <verdict>
  local state=$1 verdict=$2
  [ -e "$state/.watch-triage.log" ] || { printf '0\n'; return 0; }
  grep -F -c "$verdict" "$state/.watch-triage.log" 2>/dev/null || true
}

wait_for_live_triage_verdict() {  # <pid> <state> <verdict> <baseline> [limit]
  local pid=$1 state=$2 verdict=$3 baseline=$4 limit=${5:-100} i=0 count
  while [ "$i" -lt "$limit" ]; do
    kill -0 "$pid" 2>/dev/null || return 1
    count=$(triage_verdict_count "$state" "$verdict")
    [ "$count" -gt "$baseline" ] && return 0
    sleep 0.1
    i=$((i + 1))
  done
  return 1
}

wait_for_live_file_change() {  # <pid> <file> <prior> [limit]
  local pid=$1 file=$2 prior=$3 limit=${4:-100} i=0 value
  while [ "$i" -lt "$limit" ]; do
    kill -0 "$pid" 2>/dev/null || return 1
    value=$(cat "$file" 2>/dev/null || true)
    [ "$value" != "$prior" ] && return 0
    sleep 0.1
    i=$((i + 1))
  done
  return 1
}

