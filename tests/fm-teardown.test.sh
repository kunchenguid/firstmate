  assert_grep "no-mistakes run 01KRUNLIVE0001 is still running" "$case_dir/stderr" \
    "nm-recorded-live: the refusal did not name the run and its status"
  assert_grep "axi abort --run 01KRUNLIVE0001" "$case_dir/stderr" \
