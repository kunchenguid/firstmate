#!/usr/bin/env bash
# Tests for bin/fm-teardown.sh's landed-work safety and stale-lock recovery.
#
# The check refuses to tear down a worktree whose work has not LANDED, because
# treehouse return hard-resets the worktree. "Landed" means reachable from a remote
# OR - for a normal ship task whose commits are not so reachable - its PR/MR is
# merged and the provider reports a head that contains the current local work,
# or its content is already in the up-to-date default branch.
#
# Covers three fixes:
#   - local-only fork-remote: a fork IS a remote, so fork-pushed upstream-
#     contribution PRs are teardown-eligible (the pre-fix code false-refused them).
#   - squash-merge-then-delete-branch: the branch's own commits live nowhere on a
#     remote after a squash merge deletes the head branch, yet the change is fully in
#     main. Reachability alone false-refused this common GitHub flow; the check now
#     recognizes a merged PR head containing the local work (or the content already
#     in main) as landed.
#   - teardown-lock-race: a killed crew process can leave a transient worktree
#     git index.lock that blocks teardown. The return path retries on the lock
#     error signature (even if the lock self-clears mid-check), then only removes a
#     provably stale lock before re-running safety checks.
#
# Matrix:
#   (a) local-only + HEAD on a fork remote-tracking branch     -> ALLOW  (fork fix)
#   (b) local-only + truly unpushed work (no remote, not main) -> REFUSE (safety)
#   (c) local-only + merged into local main, no remote         -> ALLOW  (no regression)
#   (d) no-mistakes + HEAD on origin remote-tracking branch    -> ALLOW  (no regression)
#   (e) no-mistakes + unpushed, no PR, content not in default  -> REFUSE (safety)
#   (f) local-only + truly unpushed + --force                  -> ALLOW  (escape hatch)
#   (g) no-mistakes + squash-merged PR, exact PR head          -> ALLOW  (squash fix)
#   (h) no-mistakes + no PR but content already in default     -> ALLOW  (content fallback)
#   (i) no-mistakes + dirty worktree, even when work landed     -> REFUSE (dirty wins)
#   (j) no-mistakes + GitHub lookup errors + content absent     -> REFUSE (fail-safe)
#   (k) no-mistakes + merged PR but HEAD moved afterward        -> REFUSE (stale PR)
#   (l) no-mistakes + stale origin/main but fetched content     -> ALLOW  (fresh fetch)
#   (m) no-mistakes + local HEAD ancestor of merged PR head     -> ALLOW  (lagging local)
#   (n) no-mistakes + replayed unpushed patch in merged PR head -> ALLOW  (replayed local)
#   (o) fm-pr-check rerun after HEAD moved                      -> no stale pr_head
#   (p) fm-pr-check when local HEAD lags                        -> record remote PR head
#   (q) no-mistakes + NO pr= recorded, PR discovered by branch  -> ALLOW  (yolo/no-CI merge)
#   (q2) Codebase MR merged and contains local work             -> ALLOW
#   (q3) Codebase remote + NO pr= discovers merged MR by branch -> ALLOW
#   (q4) Codebase lookup error + content absent                 -> REFUSE (fail-safe)
#   (q5) Codebase lookup error + content already in default     -> ALLOW  (quiet fallback)
#
# Also covers the backlog write teardown owns (bin/fm-teardown.sh's backlog_refresh),
# which used to be a printed reminder the agent dropped four times, leaving merged
# tasks under `## In flight`:
#   (z1) PR-based ship task     -> row actually moves to Done, PR link recorded
#   (z2) Codebase MR ship task  -> link lands via --note, never the rejected --pr
#   (z3) backlog write fails    -> loud banner, never swallowed
#
# Also covers teardown-lock-race: a git index.lock left in the worktree by a
# killed crew process (bin/fm-teardown.sh's teardown_treehouse_return).
#   (r) provably-stale index.lock (old mtime, no live holder) -> lock removed, ALLOW
#   (s) index.lock with a live holder, any age                -> lock kept, REFUSE
#   (t) lsof error while checking index.lock                  -> lock kept, REFUSE
#   (u) dirty worktree after stale lock cleanup               -> lock removed, REFUSE
#   (v) non-linked repo index.lock                            -> lock removed, ALLOW
#   (w) index.lock mtime read failure                         -> lock kept, REFUSE
#   (x) transient lock cleared after first failed return      -> retry ALLOW
#   (y) persistent lock (never clears, not provably stale)    -> REFUSE loudly
#
# Also covers the live no-mistakes run teardown must not orphan: deleting the
# meta deletes nm_watch_run=, the only record attributing a run to a task, so a
# run left alive at teardown has no owner and keeps re-notifying forever.
#   (n1) recorded nm_watch_run= still running        -> REFUSE, meta preserved
#   (n2) active run on the task's own branch         -> REFUSE
#   (n3) active run on ANOTHER branch of same repo   -> ALLOW, never inspected
#   (n4) same, under --force                         -> never aborted
#   (n5) recorded run already completed              -> ALLOW, never aborted
#   (n6) run state undeterminable                    -> WARN with the id, ALLOW
#   (n7) live own run under --force                  -> aborted, then ALLOW
