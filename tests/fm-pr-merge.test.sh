test_missing_meta_refuses_before_merge() {
  local case_dir rc
  case_dir=$(make_released_case missing-meta)
  # Nothing local and nothing at the forge: no meta, no landing record, and a PR
  # URL that resolves to nothing. This is the one case that must still refuse.
  add_gh_mocks_forge_unreachable "$case_dir"
  : > "$case_dir/gh-axi.log"

  set +e
  run_pr_merge "$case_dir" missing-x1 https://github.com/example/repo/pull/21 \
    > "$case_dir/stdout" 2> "$case_dir/stderr"
  rc=$?
  set -e

  expect_code 1 "$rc" "missing-meta: fm-pr-merge should refuse"
  assert_grep 'error: task metadata is unavailable' "$case_dir/stderr" \
    "missing-meta: refusal did not explain the missing record"
  assert_grep 'could not be resolved at its forge' "$case_dir/stderr" \
    "missing-meta: refusal did not name the unresolvable pull request"
  [ ! -s "$case_dir/gh-axi.log" ] || fail "missing-meta: gh-axi pr merge was invoked"
  assert_absent "$case_dir/state/missing-x1.check.sh" \
    "missing-meta: fm-pr-check should not arm a poll for an unknown task"
  assert_absent "$case_dir/state/missing-x1.landing" \
    "missing-meta: an unresolvable pull request must not leave a landing record"
  pass "fm-pr-merge refuses when neither a task record nor a resolvable PR exists"
}

test_landing_record_lands_released_task() {
  local case_dir rc
  case_dir=$(make_released_case landing-record)
  write_landing_record "$case_dir" task-x1 https://github.com/example/repo/pull/20 \
    aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa
  add_gh_mocks_forge_state "$case_dir" bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb OPEN
  : > "$case_dir/gh-axi.log"

  set +e
  run_pr_merge "$case_dir" task-x1 https://github.com/example/repo/pull/20 \
    > "$case_dir/stdout" 2> "$case_dir/stderr"
  rc=$?
  set -e

  expect_code 0 "$rc" "landing-record: fm-pr-merge should land a released task's PR"
  grep -qxF 'pr merge 20 --repo example/repo --squash' "$case_dir/gh-axi.log" \
    || fail "landing-record: gh-axi pr merge was not invoked for the released task"
  assert_absent "$case_dir/state/task-x1.check.sh" \
    "landing-record: a released task has nothing to watch, so no poll should be armed"
  assert_absent "$case_dir/state/task-x1.landing" \
    "landing-record: the spent landing record should be removed once the PR landed"
  pass "fm-pr-merge lands a released task's PR through its durable landing record"
}

test_landing_record_refuses_when_pr_is_not_open() {
  local case_dir rc
  case_dir=$(make_released_case landing-record-merged)
  write_landing_record "$case_dir" task-x1 https://github.com/example/repo/pull/20 \
    aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa
  # Same record as the case above; only the forge's answer differs, so the local
  # record alone can never authorize the merge.
  add_gh_mocks_forge_state "$case_dir" bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb MERGED
  : > "$case_dir/gh-axi.log"

  set +e
  run_pr_merge "$case_dir" task-x1 https://github.com/example/repo/pull/20 \
    > "$case_dir/stdout" 2> "$case_dir/stderr"
  rc=$?
  set -e

  expect_code 1 "$rc" "landing-record-merged: fm-pr-merge should refuse a PR that is not open"
  assert_grep 'is merged at its forge' "$case_dir/stderr" \
    "landing-record-merged: refusal did not report the forge's own state"
  assert_no_grep 'pr merge' "$case_dir/gh-axi.log" \
    "landing-record-merged: gh-axi pr merge was invoked for a PR that is not open"
  assert_present "$case_dir/state/task-x1.landing" \
    "landing-record-merged: a refused merge must not discard the landing record"
  pass "fm-pr-merge re-reads the forge and refuses a landing record whose PR is not open"
}

test_reconstructs_landing_record_from_pr_url() {
  local case_dir rc
  case_dir=$(make_released_case reconstruct-from-url)
  # Released before landing records existed: no meta and no landing record, so
  # the PR itself is the only authority for its own identity.
  add_gh_mocks_forge_state "$case_dir" cccccccccccccccccccccccccccccccccccccccc OPEN
  : > "$case_dir/gh-axi.log"

  set +e
  run_pr_merge "$case_dir" task-x1 https://github.com/example/repo/pull/13 \
    > "$case_dir/stdout" 2> "$case_dir/stderr"
  rc=$?
  set -e

  expect_code 0 "$rc" "reconstruct-from-url: fm-pr-merge should rebuild the record and land the PR"
  assert_grep 'rebuilt: state/task-x1.landing' "$case_dir/stdout" \
    "reconstruct-from-url: the rebuild was not reported"
  grep -qxF 'pr merge 13 --repo example/repo --squash' "$case_dir/gh-axi.log" \
    || fail "reconstruct-from-url: gh-axi pr merge was not invoked"
  assert_absent "$case_dir/state/task-x1.check.sh" \
    "reconstruct-from-url: no poll should be armed for a released task"
  pass "fm-pr-merge rebuilds a released task's landing record from the PR itself"
}

