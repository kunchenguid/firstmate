package fm_firstmate

import (
	"fmt"

	sdk "github.com/MichaelKinsy/PiG/extensions/sdk"
)

func Extension() *sdk.Extension {
	e := sdk.New("fm-firstmate")
	e.Command("ahoy", "Recap this session and surface unanswered decisions.", func(ctx sdk.Context, args string) error {
		return invokeSkill(ctx, "ahoy", args)
	})
	e.Command("bearings", "Generate a current Firstmate fleet digest.", func(ctx sdk.Context, args string) error {
		return invokeSkill(ctx, "bearings", args)
	})
	return e
}

func invokeSkill(ctx sdk.Context, skill, args string) error {
	message := fmt.Sprintf(
		"Firstmate command invoked: /%s\nFollow the loaded %s skill exactly. This synthesized handoff is generated by the slash command, not a separate user request.\nArguments (verbatim):\n%s",
		skill,
		skill,
		args,
	)
	return ctx.SendUserMessage(message, "followUp")
}
