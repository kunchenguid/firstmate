// Queue rows the classifier already passed to main, durable across a module
// reload or a session restart: while such a row is still queued it goes back
// to main unclassified, because its lines are HISTORY to the classifier now.
async function readPassedSeqs($: any): Promise<Set<string>> {
  try {
    const j = JSON.parse(await $.fs.read(`${state}/.branch-mod-passed`))
    return new Set(Array.isArray(j) ? j.map(String) : [])
  } catch {
    return new Set()
  }
}
async function writePassedSeqs($: any, seqs: Set<string>): Promise<void> {
  try {
    await $.fs.write(`${state}/.branch-mod-passed`, JSON.stringify([...seqs]))
  } catch {}
}
async function readLockPid($: any): Promise<string> {
  try {
    const raw = (await $.fs.read(`${state}/.lock`)).split('\n')[0].trim()
    return /^[0-9]+$/.test(raw) ? raw : ''
  } catch {
    return ''
  }
}

// Session counters survive a module reload (/reload-plugins): the file is
// bound to the session lock pid, so a genuinely new session starts at zero.
// The record shape and the same-lock rule are the settlement module's; this
// binding assembles the fields from the machines that own them.
async function saveCounters($: any): Promise<void> {
  try {
    const d = delivery.snapshot()
    const m = monitorGuard.snapshot()
    await $.fs.write(
      `${state}/.branch-mod-counters`,
      buildCountersText({
        lockPid: lockPid || (await readLockPid($)),
        wakeCounter,
        spawnCount: d.spawnCount,
        sendCount: d.sendCount,
        generation,
        branchGeneration: d.branchGeneration,
        branchRef: d.branchRef,
        branchAgentId: d.branchAgentId,
        monitorTaskId: m.monitorTaskId,
        monitorArmedAt: m.monitorArmedAt,
      }),
    )
  } catch {}
}
async function restoreCounters($: any): Promise<void> {
  try {
    const j = parseCountersRecord(await $.fs.read(`${state}/.branch-mod-counters`))
    const pid = await readLockPid($)
    if (j && countersApplyVerdict(j, pid)) {
      wakeCounter = j.wakeCounter ?? 0
      delivery.restoreFromCounters(j)
      if (j.generation) generation = j.generation
      monitorGuard.restoreFromCounters(j.monitorTaskId, j.monitorArmedAt, Number(await $.clock.now()))
      log($, 'counters.restored', { ...j, reason: 'same session lock pid (module reloaded)' })
    }
  } catch {}
}

async function grant($: any, args: string[], timeoutMs = 5000): Promise<number> {
  const r = await $.process.run(['bash', `${bin}/fm-wake-grant.sh`, ...args], { cwd, env: scriptEnv(), timeoutMs })
  return r.exitCode
}
async function ensureActivated($: any): Promise<boolean> {
  if (activated) return true
  lockPid = await readLockPid($)
  if (!lockPid) return false
  const rc = await grant($, ['activate', lockPid, generation])
  activated = rc === 0
  log($, 'grant.activate', { lockPid, generation, rc })
  return activated
}

