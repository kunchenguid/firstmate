function appendLine($: any, path: string, line: string, cap: number): Promise<unknown> {
  // One shell append per record, rotated once past the cap so the log cannot grow without bound.
  const script = 'f=$1; cap=$2; if [ -f "$f" ] && [ "$(wc -c < "$f")" -gt "$cap" ]; then mv -f "$f" "$f.1"; fi; cat >> "$f"'
  return $.process.run(['sh', '-c', script, '_', path, String(cap)], { stdin: line, timeoutMs: 3000 })
}

// Append-only event log: the evidence source for every count the live test asserts.
function log($: any, kind: string, data: unknown): void {
  if (!state) return
  const line = JSON.stringify({ t: new Date().toISOString(), kind, data }) + '\n'
  void appendLine($, `${state}/branch-mod-events.jsonl`, line, EVENT_LOG_CAP_BYTES).catch(() => {})
}

function parentDirectory(path: string): string {
  const cut = path.replace(/\/+$/, '').lastIndexOf('/')
  return cut > 0 ? path.slice(0, cut) : '/'
}

// Home and script resolution follow bin/ exactly: FM_HOME, then FM_ROOT_OVERRIDE,
// then the tracked code root three levels above the plugin folder; state and
// config honour their own overrides; scripts always come from the code root.
export async function bind($: any, sessionCwd: string): Promise<void> {
  if (bound) return
  bound = true
  cwd = sessionCwd
  pluginRoot = $.plugin.root
  const codeRoot = parentDirectory(parentDirectory(parentDirectory(pluginRoot)))
  // Literal names only: strict validation lists the variables a module reads.
  const text = (v: unknown) => String(v ?? '')
  let fmHome = ''
  let fmRoot = ''
  let fmState = ''
  let fmConfig = ''
  try {
    fmHome = text(await $.env.get('FM_HOME'))
    fmRoot = text(await $.env.get('FM_ROOT_OVERRIDE'))
    fmState = text(await $.env.get('FM_STATE_OVERRIDE'))
    fmConfig = text(await $.env.get('FM_CONFIG_OVERRIDE'))
  } catch {}
  home = fmHome || fmRoot || codeRoot
  state = fmState || `${home}/state`
  config = fmConfig || `${home}/config`
  bin = `${codeRoot}/bin`
  if (!generation) generation = `cc${Date.now()}`
}
async function ensureBound($: any): Promise<void> {
  if (bound) return
  await bind($, await $.session.cwd())
  log($, 'rebound', { cwd, generation })
}

