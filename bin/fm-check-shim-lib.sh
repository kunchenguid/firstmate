# shellcheck shell=bash
# Shared arm and disarm for a home's trusted watcher check shims.
#
# The single owner of how a standing check is published: state/<id>.check.sh is
# a mode-0700 regular file whose bytes the watcher validates against the trust
# binding fm-check-register.sh writes, and whose only job is to re-enter the
# generating script's `check` action with this home's resolved FM_HOME.
#
# Usage:
#   . bin/fm-check-shim-lib.sh
#   fm_check_shim_arm <state> <id> <generator-path> <description> <home>
#   fm_check_shim_disarm <state> <id> [extra-file...]
#
# The caller owns its own preconditions (its configuration, its plane) and runs
# them before arming; this library owns only the publication and its rollback.
# Requires fm-pr-lib.sh and fm-check-lib.sh to be sourced first.

FM_CHECK_SHIM_TMP=
FM_CHECK_SHIM_BACKUP=

# The home is embedded already resolved, because the watcher runs the shim from
# its own working directory and a relative spelling would send the check to a
# different home, or to none at all.
fm_check_shim_content() {  # <generator-path> <description> <resolved-home>
  local generator=$1 description=$2 home=$3
  [ -n "$generator" ] && [ -n "$description" ] || return 1
  case "$home" in /*) ;; *) return 1 ;; esac
  printf '%s\n' \
    '#!/usr/bin/env bash' \
    "# Auto-generated by $(basename "$generator") - $description." \
    '# The watcher validates these bytes, then dispatches the trusted check script.' \
    "export FM_HOME=$(printf '%q' "$home")" \
    "exec $(printf '%q' "$generator") check"
}

# Write the shim so a symlink at its path is refused instead of followed, and
# the bytes arrive by rename so the watcher never reads a half-written shim and
# rejects it as unauthenticated.
fm_check_shim_write() {  # <state> <shim-path> <label> <wanted-bytes>
  local state=$1 shim=$2 label=$3 want=$4 device tmp
  [ -d "$state" ] && [ ! -L "$state" ] || return 1
  device=$(fm_pr_file_device "$state") || return 1
  [ -n "$device" ] || return 1
  fm_pr_regular_destination_on_device_or_absent "$shim" "$device" || return 1
  if [ -e "$shim" ] && [ "$(fm_pr_file_mode "$shim")" = 700 ] \
    && [ "$(cat "$shim" 2>/dev/null)" = "$want" ]; then
    return 0
  fi
  tmp=$(umask 077; mktemp "$state/.$label.XXXXXX" 2>/dev/null) || return 1
  FM_CHECK_SHIM_TMP=$tmp
  if ! printf '%s\n' "$want" > "$tmp" \
    || ! chmod 0700 "$tmp" \
    || ! fm_pr_private_file_valid "$tmp" 700 "$device"; then
    rm -f -- "$tmp"
    FM_CHECK_SHIM_TMP=
    return 1
  fi
  if ! fm_pr_regular_destination_on_device_or_absent "$shim" "$device" \
    || ! mv -f -- "$tmp" "$shim"; then
    rm -f -- "$tmp"
    FM_CHECK_SHIM_TMP=
    return 1
  fi
  FM_CHECK_SHIM_TMP=
  fm_pr_private_file_valid "$shim" 700 "$device"
}

# Keep a byte copy of a shim that is already in place, so a failed arm can put
# back the shim a working home was already using rather than an equivalent
# rewrite. The trust binding is over the bytes, so a rewrite would satisfy it
# too, but a home that was armed stays armed with what it had.
fm_check_shim_backup() {  # <state> <shim-path> <label>
  local state=$1 shim=$2 label=$3 device tmp
  device=$(fm_pr_file_device "$state") || return 1
  [ -n "$device" ] || return 1
  tmp=$(umask 077; mktemp "$state/.$label.XXXXXX" 2>/dev/null) || return 1
  if ! cat "$shim" > "$tmp" 2>/dev/null \
    || ! chmod 0700 "$tmp" \
    || ! fm_pr_private_file_valid "$tmp" 700 "$device"; then
    rm -f -- "$tmp"
    return 1
  fi
  printf '%s\n' "$tmp"
}

# An unregistered shim is not inert: the watcher rejects it on every cycle and
# wakes firstmate about unauthenticated state checks. So the one rule after a
# failed or interrupted arm is that the home never holds a shim without a
# matching trust binding. The shim a working home had is put back and kept only
# when it is still bound; otherwise the shim goes, so the home is plainly not
# armed and the failure is the only thing the operator has to act on.
fm_check_shim_rollback() {  # <state> <id> <shim-path>
  local state=$1 id=$2 shim=$3
  [ -z "$FM_CHECK_SHIM_TMP" ] || rm -f -- "$FM_CHECK_SHIM_TMP"
  FM_CHECK_SHIM_TMP=
  if [ -n "$FM_CHECK_SHIM_BACKUP" ]; then
    mv -f -- "$FM_CHECK_SHIM_BACKUP" "$shim" 2>/dev/null || rm -f -- "$FM_CHECK_SHIM_BACKUP"
    FM_CHECK_SHIM_BACKUP=
    if fm_custom_check_registered "$state" "$id"; then
      return 0
    fi
  fi
  rm -f -- "$shim"
}

# Signal handlers take no arguments, so the interrupt path reads the arm in
# progress from these module-level fields rather than from its own parameters.
FM_CHECK_SHIM_STATE=
FM_CHECK_SHIM_ID=
FM_CHECK_SHIM_PATH=
FM_CHECK_SHIM_LABEL=

# shellcheck disable=SC2329  # Registered by fm_check_shim_arm's signal trap.
fm_check_shim_interrupted() {
  fm_check_shim_rollback "$FM_CHECK_SHIM_STATE" "$FM_CHECK_SHIM_ID" "$FM_CHECK_SHIM_PATH"
  printf '%s: arming was interrupted, so state/%s.check.sh is not armed\n' \
    "$FM_CHECK_SHIM_LABEL" "$FM_CHECK_SHIM_ID" >&2
  exit 1
}

# Publish state/<id>.check.sh and bind its bytes. The shim exists unbound from
# the rename until the register returns, so a signal in that window rolls back
# exactly the way a failure does.
fm_check_shim_arm() {  # <state> <id> <generator-path> <description> <home>
  local state=$1 id=$2 generator=$3 description=$4 home=$5
  local register want
  [ -n "$state" ] && [ -n "$description" ] && [ -n "$home" ] || return 1
  fm_pr_task_id_valid "$id" || return 1
  [ -f "$generator" ] && [ -x "$generator" ] || return 1
  FM_CHECK_SHIM_LABEL=$(basename "$generator" .sh)
  FM_CHECK_SHIM_STATE=$state
  FM_CHECK_SHIM_ID=$id
  FM_CHECK_SHIM_PATH="$state/$id.check.sh"
  register="$(dirname "$generator")/fm-check-register.sh"
  mkdir -p "$state" || return 1
  case "$home" in
    /*) ;;
    *)
      home=$(CDPATH='' cd -- "$home" 2>/dev/null && pwd -P) || {
        printf '%s: cannot resolve FM_HOME %s\n' "$FM_CHECK_SHIM_LABEL" "$5" >&2
        return 1
      }
      ;;
  esac
  want=$(fm_check_shim_content "$generator" "$description" "$home") || return 1
  FM_CHECK_SHIM_BACKUP=
  if [ -f "$FM_CHECK_SHIM_PATH" ] && [ ! -L "$FM_CHECK_SHIM_PATH" ]; then
    FM_CHECK_SHIM_BACKUP=$(fm_check_shim_backup "$state" "$FM_CHECK_SHIM_PATH" "$FM_CHECK_SHIM_LABEL") || {
      printf '%s: could not save the existing %s\n' "$FM_CHECK_SHIM_LABEL" "$FM_CHECK_SHIM_PATH" >&2
      return 1
    }
  fi
  trap fm_check_shim_interrupted HUP INT TERM
  if ! fm_check_shim_write "$state" "$FM_CHECK_SHIM_PATH" "$FM_CHECK_SHIM_LABEL" "$want"; then
    trap - HUP INT TERM
    fm_check_shim_rollback "$state" "$id" "$FM_CHECK_SHIM_PATH"
    printf '%s: could not write %s\n' "$FM_CHECK_SHIM_LABEL" "$FM_CHECK_SHIM_PATH" >&2
    return 1
  fi
  if ! FM_HOME="$home" "$register" "$id" >/dev/null; then
    trap - HUP INT TERM
    fm_check_shim_rollback "$state" "$id" "$FM_CHECK_SHIM_PATH"
    printf '%s: could not register %s\n' "$FM_CHECK_SHIM_LABEL" "$FM_CHECK_SHIM_PATH" >&2
    return 1
  fi
  trap - HUP INT TERM
  [ -z "$FM_CHECK_SHIM_BACKUP" ] || rm -f -- "$FM_CHECK_SHIM_BACKUP"
  FM_CHECK_SHIM_BACKUP=
  printf 'armed: state/%s.check.sh\n' "$id"
}

# Retire the shim and its trust binding, plus any report records the caller
# names, so a disarmed home carries no trace the next poll could act on.
fm_check_shim_disarm() {  # <state> <id> [extra-file...]
  local state=$1 id=$2
  [ -n "$state" ] || return 1
  fm_pr_task_id_valid "$id" || return 1
  shift 2
  rm -f -- "$state/$id.check.sh" "$state/$id.check-trust" "$@"
  printf 'disarmed: state/%s.check.sh\n' "$id"
}
