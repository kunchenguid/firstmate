# shellcheck shell=bash
# Shared write/arm/disarm mechanics for a firstmate-owned repeating check shim.
# Usage: . bin/fm-check-shim-lib.sh   (after STATE and SCRIPT_DIR are set)
#
# A check shim is the one way a firstmate feature gets a repeating poll without
# a daemon or a schedule of its own: the watcher already runs every registered
# state/<id>.check.sh on its FM_CHECK_INTERVAL cadence, validates the bytes
# against a trust binding written by bin/fm-check-register.sh, and turns any
# line the shim prints into a `check:` wake. The shim itself only execs a
# trusted repository script, so the feature's real work stays in that script.
#
# This library exists because that arm/disarm sequence is subtle and was already
# written three times: an unregistered shim is NOT inert, because the watcher
# rejects it on every cycle and wakes firstmate about unauthenticated state
# checks. So a failed or interrupted arm must never leave a shim behind without
# a matching trust binding, and the rollback has to put an already-bound shim
# back rather than simply deleting whatever is there.
#
# Callers set FM_CHECK_SHIM_ID and FM_CHECK_SHIM_LABEL, then call
# fm_check_shim_arm with the command line the shim should exec.
# bin/fm-usage-warner.sh and bin/fm-seat.sh are its consumers;
# bin/fm-mail-check.sh and bin/fm-tool-update-check.sh keep their own older
# copies of this sequence until they are separately migrated and re-tested.
#
# Requires bin/fm-pr-lib.sh (file-device and private-file guards) and
# bin/fm-check-lib.sh (fm_custom_check_registered) to be sourced by the caller.

FM_CHECK_SHIM_ID=
FM_CHECK_SHIM_LABEL=
FM_CHECK_SHIM_WRITE_TMP=
FM_CHECK_SHIM_BACKUP=

fm_check_shim_path() { printf '%s/%s.check.sh\n' "$STATE" "$FM_CHECK_SHIM_ID"; }
fm_check_shim_trust_path() { printf '%s/%s.check-trust\n' "$STATE" "$FM_CHECK_SHIM_ID"; }

# fm_check_shim_content <home> <argv...>
# The exact bytes of the shim. The home is embedded already resolved, because
# the watcher runs the shim from its own working directory and a relative
# spelling would send the check to a different home, or to none at all.
fm_check_shim_content() {
  local home=$1 quoted='' arg
  shift
  for arg in "$@"; do
    quoted="$quoted $(printf '%q' "$arg")"
  done
  printf '%s\n' \
    '#!/usr/bin/env bash' \
    "# Auto-generated by ${FM_CHECK_SHIM_LABEL} - poll shim." \
    '# The watcher validates these bytes, then dispatches the trusted check script.' \
    "export FM_HOME=$(printf '%q' "$home")" \
    "exec${quoted}"
}

# fm_check_shim_write <wanted-bytes>
# Guards run before anything is written, so a symlink at the shim path is
# refused instead of followed, and the bytes arrive by rename so the watcher
# never reads a half-written shim and rejects it as unauthenticated.
fm_check_shim_write() {
  local want=$1 device tmp shim
  shim=$(fm_check_shim_path)
  [ -d "$STATE" ] && [ ! -L "$STATE" ] || return 1
  device=$(fm_pr_file_device "$STATE") || return 1
  [ -n "$device" ] || return 1
  fm_pr_regular_destination_on_device_or_absent "$shim" "$device" || return 1
  if [ -e "$shim" ] && [ "$(fm_pr_file_mode "$shim")" = 700 ] \
    && [ "$(cat "$shim" 2>/dev/null)" = "$want" ]; then
    return 0
  fi
  tmp=$(umask 077; mktemp "$STATE/.fm-check-shim.XXXXXX" 2>/dev/null) || return 1
  FM_CHECK_SHIM_WRITE_TMP=$tmp
  if ! printf '%s\n' "$want" > "$tmp" \
    || ! chmod 0700 "$tmp" \
    || ! fm_pr_private_file_valid "$tmp" 700 "$device"; then
    rm -f -- "$tmp"
    FM_CHECK_SHIM_WRITE_TMP=
    return 1
  fi
  if ! fm_pr_regular_destination_on_device_or_absent "$shim" "$device" \
    || ! mv -f -- "$tmp" "$shim"; then
    rm -f -- "$tmp"
    FM_CHECK_SHIM_WRITE_TMP=
    return 1
  fi
  FM_CHECK_SHIM_WRITE_TMP=
  fm_pr_private_file_valid "$shim" 700 "$device"
}

fm_check_shim_backup() {
  local device tmp shim
  shim=$(fm_check_shim_path)
  device=$(fm_pr_file_device "$STATE") || return 1
  [ -n "$device" ] || return 1
  tmp=$(umask 077; mktemp "$STATE/.fm-check-shim.XXXXXX" 2>/dev/null) || return 1
  if ! cat "$shim" > "$tmp" 2>/dev/null \
    || ! chmod 0700 "$tmp" \
    || ! fm_pr_private_file_valid "$tmp" 700 "$device"; then
    rm -f -- "$tmp"
    return 1
  fi
  printf '%s\n' "$tmp"
}

fm_check_shim_rollback() {
  local shim
  shim=$(fm_check_shim_path)
  [ -z "$FM_CHECK_SHIM_WRITE_TMP" ] || rm -f -- "$FM_CHECK_SHIM_WRITE_TMP"
  FM_CHECK_SHIM_WRITE_TMP=
  if [ -n "$FM_CHECK_SHIM_BACKUP" ]; then
    mv -f -- "$FM_CHECK_SHIM_BACKUP" "$shim" 2>/dev/null || rm -f -- "$FM_CHECK_SHIM_BACKUP"
    FM_CHECK_SHIM_BACKUP=
    if fm_custom_check_registered "$STATE" "$FM_CHECK_SHIM_ID"; then
      return 0
    fi
  fi
  rm -f -- "$shim"
}

# shellcheck disable=SC2329  # Registered by fm_check_shim_arm's signal trap.
fm_check_shim_interrupted() {
  fm_check_shim_rollback
  printf '%s: arming was interrupted, so state/%s.check.sh is not armed\n' \
    "$FM_CHECK_SHIM_LABEL" "$FM_CHECK_SHIM_ID" >&2
  exit 1
}

# fm_check_shim_arm <fm-home> <argv...>
# Write the shim for <argv...> and bind its bytes. Prints its own failures.
fm_check_shim_arm() {
  local home=$1 want shim
  shift
  shim=$(fm_check_shim_path)
  mkdir -p "$STATE" || return 1
  case "$home" in
    /*) ;;
    *)
      home=$(CDPATH='' cd -- "$home" 2>/dev/null && pwd -P) || {
        printf '%s: cannot resolve FM_HOME\n' "$FM_CHECK_SHIM_LABEL" >&2
        return 1
      }
      ;;
  esac
  want=$(fm_check_shim_content "$home" "$@")
  FM_CHECK_SHIM_BACKUP=
  if [ -f "$shim" ] && [ ! -L "$shim" ]; then
    FM_CHECK_SHIM_BACKUP=$(fm_check_shim_backup) || {
      printf '%s: could not save the existing %s\n' "$FM_CHECK_SHIM_LABEL" "$shim" >&2
      return 1
    }
  fi
  # The shim exists unbound from the rename until the register returns, so a
  # signal in that window rolls back the same way a failure does.
  trap fm_check_shim_interrupted HUP INT TERM
  if ! fm_check_shim_write "$want"; then
    trap - HUP INT TERM
    fm_check_shim_rollback
    printf '%s: could not write %s\n' "$FM_CHECK_SHIM_LABEL" "$shim" >&2
    return 1
  fi
  if ! FM_HOME="$home" "$SCRIPT_DIR/fm-check-register.sh" "$FM_CHECK_SHIM_ID" >/dev/null; then
    trap - HUP INT TERM
    fm_check_shim_rollback
    printf '%s: could not register %s\n' "$FM_CHECK_SHIM_LABEL" "$shim" >&2
    return 1
  fi
  trap - HUP INT TERM
  [ -z "$FM_CHECK_SHIM_BACKUP" ] || rm -f -- "$FM_CHECK_SHIM_BACKUP"
  FM_CHECK_SHIM_BACKUP=
  return 0
}

# fm_check_shim_disarm [extra-path...]
# Remove the shim, its trust binding, and any per-feature record named by the
# caller. Idempotent, so a disarm of something never armed is a clean no-op.
fm_check_shim_disarm() {
  rm -f -- "$(fm_check_shim_path)" "$(fm_check_shim_trust_path)" "$@"
}

# fm_check_shim_armed
# Exit 0 when this home currently holds a registered shim for this id.
fm_check_shim_armed() {
  [ -f "$(fm_check_shim_path)" ] || return 1
  fm_custom_check_registered "$STATE" "$FM_CHECK_SHIM_ID"
}
