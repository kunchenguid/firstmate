#!/usr/bin/env bash
# fm-register.sh - the captain register as a DERIVED VIEW of the backlog
# (plan v3 U1.5): the register stops being a second, hand-fed truth (L04/L09/
# L23 - 217 of 259 hand-kept lines were stale when measured) and becomes a
# render of data/backlog.md, with every line keyed to its backlog id and the
# captain's ten-per-area cap enforced by the machine, not by discipline.
#
# Usage:
#   fm-register.sh render            print the derived register to stdout
#   fm-register.sh write             atomically write data/captain-auftraege.md;
#                                    REFUSES to overwrite a file that does not
#                                    carry the GENERATED banner (the hand-kept
#                                    register holds prose not yet migrated -
#                                    it is never silently clobbered)
#   fm-register.sh write --uebernehmen --archiv <path>
#                                    one-time takeover: archive the hand-kept
#                                    file to <path> first, then write the render
#   fm-register.sh check             one line when the written register differs
#                                    from the current render (hand edit or
#                                    backlog moved); silent when fresh. It also
#                                    reports the three register invariants
#                                    (ziel:-Feld, Eigner, Planlos-Alter) - owner
#                                    and wording: bin/fm-register-invarianten-lib.sh
#   fm-register.sh dead-edges [--file <path>]
#                                    print one "dead-edge: <carrier> -> <target>"
#                                    line per blocked-by edge whose target has no
#                                    open entry in the same backlog file; silent
#                                    when clean. Exit: 0 clean, 1 findings,
#                                    2 error. Default file: <home>/data/backlog.md
#   fm-register.sh --help
#
# Source and shape:
#   Source is the canonical backlog file data/backlog.md (schema owner:
#   .tasks.toml + `tasks-axi render`), sections "In flight" and "Queued"; Done
#   never renders. The output keeps the 6-column contract the fleet board
#   parses: "| Datum | Projekt | Offener Faden | Stand | Wo | Wer |" under
#   "## <Bereich>" headings, state markers UPPERCASE (LAEUFT/WARTET/OFFEN).
#   The "Wo" column carries the backlog key as "id:<task-id>" - the register
#   line's one link back to its owning record.
#
# Dead edges (register-hygiene signal): a blocked-by edge is read ONLY from the
# structured field on an open task head line ("- [ ] <id> ... blocked-by:
# <target>"). Prose citations of the same syntax inside an entry's body never
# count - entries quote each other constantly, and every quote was a false
# hit for the whole-file grep this subcommand replaces. Truth source is the
# canonical backlog FILE itself, not tasks-axi's runtime view (the runtime
# prunes edges that live on in data/backlog.md); each backlog file resolves
# its own edges against itself only.
#
# Area mapping (deposit form): config/register-bereiche - LOCAL, gitignored;
# lines "<Bereich-Titel>\t<repo> [<repo>...]". A repo with no line groups
# under its own name; repo "-" groups under "Betrieb".
#
# Ten cap: per area, at most 10 rows render (captain's order 22.08.:
# "hoechstens 10 sichtbare Punkte je Repo"); precedence held-for-captain,
# then in flight, then newest first; the remainder collapses into one
# disclosed overflow row naming its ids - never silently dropped.
#
# Two-phase closure and evidence freshness (hardening 15) ride on the backlog
# body during the U3 migration; this tool renders, it never edits tasks.
set -u
export LC_ALL=C

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FM_ROOT="${FM_ROOT_OVERRIDE:-$(cd "$SCRIPT_DIR/.." && pwd)}"
FM_HOME="${FM_HOME:-$FM_ROOT}"
DATA="$FM_HOME/data"
CONFIG="${FM_CONFIG_OVERRIDE:-$FM_HOME/config}"
BACKLOG="$DATA/backlog.md"
REGISTER="$DATA/captain-auftraege.md"
BEREICHE="$CONFIG/register-bereiche"
BANNER='<!-- GENERATED by bin/fm-register.sh - ABGELEITETE SICHT, NICHT von Hand pflegen; Quelle: data/backlog.md, Schluessel je Zeile: id:<task-id> in Spalte Wo -->'
CAP=10
TAB=$(printf '\t')

usage() { sed -n '2,60p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; }

area_of() { # <repo> -> Bereich title
  local repo=$1 title repos r
  if [ -f "$BEREICHE" ]; then
    while IFS="$TAB" read -r title repos; do
      case "$title" in ''|'#'*) continue ;; esac
      for r in $repos; do
        [ "$r" = "$repo" ] && { printf '%s' "$title"; return 0; }
      done
    done < "$BEREICHE"
  fi
  if [ "$repo" = "-" ] || [ -z "$repo" ]; then printf 'Betrieb'; else printf '%s' "$repo"; fi
}

# extract_tasks: canonical backlog -> TSV, priority first so the ten-cap cuts
# by importance, never by arrival order:
#   prio \t section \t id \t title \t repo \t since \t holdkind \t hold
#   prio: 0 held-for-captain, 1 in flight, 2 waiting, 3 plain queued
extract_tasks() {
  [ -f "$BACKLOG" ] || return 0
  awk '
    /^## In flight/ { sec="inflight"; next }
    /^## Queued/    { sec="queued"; next }
    /^## /          { sec="other"; next }
    sec != "inflight" && sec != "queued" { next }
    /^- \[ \] / {
      line = substr($0, 7)
      id = line; sub(/ - .*/, "", id)
      rest = substr(line, length(id) + 4)
      title = rest
      if (match(title, / \(repo: /)) title = substr(title, 1, RSTART - 1)
      else if (match(title, / \(kind: /)) title = substr(title, 1, RSTART - 1)
      else if (match(title, / \(since /)) title = substr(title, 1, RSTART - 1)
      repo = "-"
      if (match(rest, /\(repo: [^)]*\)/)) repo = substr(rest, RSTART + 7, RLENGTH - 8)
      since = ""
      if (match(rest, /\(since [^)]*\)/)) since = substr(rest, RSTART + 7, RLENGTH - 8)
      holduntil = ""
      if (match(rest, / \(hold-until: [^)]*\)$/)) {
        holduntil = substr(rest, RSTART + 14, RLENGTH - 15)
        rest = substr(rest, 1, RSTART - 1)
      }
      holdkind = ""
      if (match(rest, /\(hold-kind: [^)]*\)$/)) holdkind = substr(rest, RSTART + 12, RLENGTH - 13)
      hold = ""
      if (match(rest, /\(hold: /)) {
        hold = substr(rest, RSTART + 7)
        if (match(hold, /\) \(hold-kind: /)) hold = substr(hold, 1, RSTART - 1)
        else sub(/\)$/, "", hold)
      }
      if (holduntil != "") hold = (hold != "" ? hold " - " : "") "Wiedervorlage " holduntil
      gsub(/\|/, "/", title); gsub(/\|/, "/", hold)
      gsub(/\t/, " ", title); gsub(/\t/, " ", hold)
      if (length(hold) > 260) hold = substr(hold, 1, 257) "..."
      prio = 3
      if (holdkind == "captain") prio = 0
      else if (sec == "inflight") prio = 1
      else if (hold != "") prio = 2
      printf "%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n", prio, sec, id, title, repo, since, holdkind, hold
    }
  ' "$BACKLOG"
}

# dead_edges_in <file>: print every dead blocked-by edge in a canonical backlog
# file as "dead-edge: <carrier-id> -> <target-id>", exit 1 when any found.
# Field-only: tokens on "- [ ]" head lines are edges; prose never is. A target
# counts as alive only when its own open head line exists in the same file;
# done ("- [x]"), archived, and absent targets leave the edge dead, and edges
# carried by done entries are inert.
dead_edges_in() {
  awk '
    /^- \[ \] / {
      line = substr($0, 7)
      id = line; sub(/ - .*/, "", id)
      open[id] = 1
      rest = line
      while (match(rest, /blocked-by: [a-z0-9-]+/)) {
        tgt = substr(rest, RSTART + 12, RLENGTH - 12)
        key = id SUBSEP tgt
        if (!(key in seen)) { seen[key] = 1; order[++n] = key }
        rest = substr(rest, RSTART + RLENGTH)
      }
    }
    END {
      bad = 0
      for (i = 1; i <= n; i++) {
        split(order[i], p, SUBSEP)
        if (!(p[2] in open)) { print "dead-edge: " p[1] " -> " p[2]; bad = 1 }
      }
      exit bad
    }
  ' "$1"
}

render_register() {
  local prio sec id title repo since holdkind hold area datum stand wer
  declare -A rows counts overflow_ids
  local order=""
  while IFS="$TAB" read -r prio sec id title repo since holdkind hold; do
    [ -n "$id" ] || continue
    area=$(area_of "$repo")
    case "$order" in *"|$area|"*) ;; *) order="$order|$area|" ;; esac
    datum=""
    if [ -n "$since" ]; then
      datum="${since:8:2}.${since:5:2}."
    fi
    if [ "$holdkind" = "captain" ]; then
      stand="WARTET auf dein Wort: ${hold:-Entscheid offen}"
      wer="Captain"
    elif [ "$sec" = "inflight" ]; then
      stand="LAEUFT (in Arbeit)"
      wer="Crew"
    elif [ "$holdkind" = "external" ]; then
      stand="WARTET extern: ${hold:-Bedingung offen}"
      wer="Firstmate"
    elif [ -n "$hold" ]; then
      stand="WARTET: $hold"
      wer="Firstmate"
    else
      stand="OFFEN (eingereiht)"
      wer="Firstmate"
    fi
    counts[$area]=$(( ${counts[$area]:-0} + 1 ))
    if [ "${counts[$area]}" -le "$CAP" ]; then
      rows[$area]="${rows[$area]:-}$prio$TAB| ${datum:--} | $repo | $title | $stand | id:$id | $wer |
"
    else
      overflow_ids[$area]="${overflow_ids[$area]:-}$id "
    fi
  done < <(extract_tasks | sort -t"$TAB" -k1,1n -k6,6r)

  printf '# Captain-Auftraege - ABGELEITETE SICHT aus dem Backlog\n%s\n\n' "$BANNER"
  printf 'Jede Zeile ist ein Backlog-Eintrag; Schluessel in Spalte Wo (id:<task-id>), Details: tasks-axi show <id> --full.\n'
  printf 'REGISTER-DECKEL (Captain 22.08.): hoechstens %s Zeilen je Bereich, mechanisch erzwungen; Rest als ausgewiesene Sammelzeile.\n\n' "$CAP"
  printf 'Spalten: Datum | Projekt | Offener Faden | Stand | Wo | Wer\n'
  local a
  while IFS= read -r a; do
    [ -n "$a" ] || continue
    printf '\n## %s\n' "$a"
    printf '| Datum | Projekt | Offener Faden | Stand | Wo | Wer |\n|---|---|---|---|---|---|\n'
    printf '%s' "${rows[$a]:-}" | sort -t"$TAB" -k1,1n | cut -f2-
    if [ -n "${overflow_ids[$a]:-}" ]; then
      printf '| - | %s | WEITERE %s Faeden (Zehner-Deckel) | OFFEN - vollstaendig im Backlog | ids: %s| - |\n' \
        "$a" $(( ${counts[$a]} - CAP )) "${overflow_ids[$a]}"
    fi
  done < <(printf '%s' "$order" | tr '|' '\n' | awk 'NF' | awk '!seen[$0]++')
}

cmd="${1:-render}"
case "$cmd" in
  render)
    render_register
    ;;
  write)
    shift || true
    uebernehmen="no" archiv=""
    while [ $# -gt 0 ]; do
      case "$1" in
        --uebernehmen) uebernehmen="yes"; shift ;;
        --archiv) archiv="${2:-}"; shift 2 ;;
        *) echo "error: unknown argument '$1' for write" >&2; exit 2 ;;
      esac
    done
    if [ -f "$REGISTER" ] && ! grep -qF 'GENERATED by bin/fm-register.sh' "$REGISTER"; then
      if [ "$uebernehmen" != "yes" ] || [ -z "$archiv" ]; then
        echo "REFUSED: $REGISTER is still the hand-kept register (no GENERATED banner) and may hold prose the backlog does not - take it over explicitly: fm-register.sh write --uebernehmen --archiv <path>" >&2
        exit 3
      fi
      if [ -e "$archiv" ]; then
        echo "error: archive target $archiv already exists - refusing to overwrite it" >&2
        exit 3
      fi
      cp -p "$REGISTER" "$archiv" || { echo "error: could not archive to $archiv" >&2; exit 1; }
      echo "archived the hand-kept register to $archiv"
    fi
    mkdir -p "$DATA"
    tmp="$REGISTER.tmp.$$"
    render_register > "$tmp"
    mv -f "$tmp" "$REGISTER"
    echo "written: $REGISTER (derived view)"
    ;;
  check)
    # --- EINHAK: Register-Invarianten -------------------------------------
    # Freshness of the derived view and health of the records it derives FROM
    # are two different questions, and check answers both. The three
    # invariants (ziel:-Feld, Eigner, Planlos-Alter) are owned entirely by
    # bin/fm-register-invarianten-lib.sh; this block only prefixes its lines
    # with the report format check already speaks and never re-derives a rule.
    # It runs before the freshness comparison so a stale register cannot hide
    # a record finding, and it never changes check's exit code: a finding here
    # is a report to the firstmate, not a gate that stops a caller.
    if [ -f "$SCRIPT_DIR/fm-register-invarianten-lib.sh" ]; then
      # shellcheck source=bin/fm-register-invarianten-lib.sh
      # shellcheck disable=SC1091
      . "$SCRIPT_DIR/fm-register-invarianten-lib.sh"
      if [ -f "$BACKLOG" ]; then
        while IFS= read -r invariante_zeile; do
          printf 'REGISTER: %s\n' "$invariante_zeile"
        done < <(fm_register_invarianten "$BACKLOG" "$FM_HOME" || true)
      fi
    fi
    # --- ENDE EINHAK -------------------------------------------------------
    if [ ! -f "$REGISTER" ]; then
      echo "REGISTER: no written register at $REGISTER (render it: bin/fm-register.sh write)"
      exit 0
    fi
    if ! grep -qF 'GENERATED by bin/fm-register.sh' "$REGISTER"; then
      exit 0
    fi
    if ! diff -q <(render_register) "$REGISTER" >/dev/null 2>&1; then
      echo "REGISTER: written view is stale or hand-edited - refresh it: bin/fm-register.sh write"
    fi
    exit 0
    ;;
  dead-edges)
    shift || true
    case $# in
      0) file="" ;;
      2) [ "$1" = "--file" ] || { echo "error: unknown argument '$1' for dead-edges" >&2; exit 2; }
         file=$2 ;;
      *) echo "error: usage: dead-edges [--file <path>]" >&2; exit 2 ;;
    esac
    [ -n "$file" ] || file=$BACKLOG
    [ -f "$file" ] || { echo "error: no backlog file at $file" >&2; exit 2; }
    dead_edges_in "$file"
    ;;
  --help|-h|help)
    usage
    ;;
  *)
    usage >&2
    exit 2
    ;;
esac
