#!/usr/bin/env bash
# shellcheck shell=bash
# Shared resolution for the operational alert inbox watch.
# Sourced by bin/fm-ops-inbox-poll.sh (the trusted standing poll) and
# fm-bootstrap.sh (the arming sweep). This file is sourced, never executed.
#
# The watched inbox is an append-only JSONL alert spool written by an external
# operations runtime, plus a separate acknowledgement log and a periodic receipt
# that runtime generates. Firstmate only ever READS those three paths; it never
# writes, rotates, or acknowledges them.
#
# It defines:
#   fm_ops_inbox_shim_content <home> <root>   - the generated standing check body
#   fm_ops_inbox_config_load <config-dir>     - resolve FM_OPS_INBOX_* settings;
#                                               returns 1 and sets
#                                               FM_OPS_INBOX_CONFIG_ERROR on a
#                                               malformed config
#   fm_ops_inbox_watch_expected [<home>]      - 0 when that home should keep the
#                                               standing check armed
#   fm_ops_inbox_scan <spool> <acks> [<max-lines>]
#                                             - unacked-critical count, oldest
#                                               timestamp, per-class counts, and
#                                               whether the read hit its cap
#   fm_ops_inbox_receipt_count <receipt>      - the receipt's own unacked count
#   fm_ops_inbox_epoch_of_iso <iso8601-Z>     - epoch seconds for a spool timestamp
#   fm_ops_inbox_age_label <seconds>          - compact "13d"/"9h"/"7m" age text
#   fm_ops_inbox_sidecar_read <path>          - last recorded wake, for dedupe
#   fm_ops_inbox_sidecar_write <path> <epoch> <count> <state> <classes>
#
# The check id is the reserved `ops-watch`, so the armed artifacts are
# state/ops-watch.check.sh and its state/ops-watch.check-trust binding.
# docs/ops-inbox-wake.md#exit-dispositions owns the wake contract and exit table;
# this header owns the mechanics.

FM_OPS_INBOX_SIDECAR_VERSION=fm-ops-inbox-wake-v1
FM_OPS_INBOX_NUMBER_MAX=999999999999

fm_ops_inbox_canonical_number() {  # <value>
  local value=$1
  case "$value" in
    ''|*[!0-9]*) return 1 ;;
  esac
  while [ "${value#0}" != "$value" ]; do
    value=${value#0}
  done
  [ -n "$value" ] || value=0
  [ "${#value}" -le 12 ] || return 1
  printf '%s' "$value"
}

# Accepted residuals: the overflow probe and parsed tail are separate append-only spool snapshots; blank complete records do not count toward the cap; a sidecar truncated after its state line reads with an empty class list; and control-character rejection covers only code points below 32, not DEL or C1.
# Each requires pathological configuration or precisely timed concurrency, the worst case is one suppressed or delayed poll, and the 24-hour re-remind bounds all four.

fm_ops_inbox_set_number() {  # <config-key> <var-name> <value>
  local key=$1 var=$2 value=$3
  if ! value=$(fm_ops_inbox_canonical_number "$value"); then
    FM_OPS_INBOX_CONFIG_ERROR="config/ops-inbox.json $key must be a non-negative integer no greater than $FM_OPS_INBOX_NUMBER_MAX"
    return 1
  fi
  printf -v "$var" '%s' "$value"
}

fm_ops_inbox_shim_content() {
  local home=$1 root=$2
  printf '%s\n' \
    '#!/usr/bin/env bash' \
    '# Auto-generated by fm-bootstrap.sh - operational alert inbox poll shim.' \
    '# Registered by bin/fm-check-register.sh; the watcher runs the bound bytes' \
    '# and turns any output into one check: wake.' \
    "export FM_HOME=$(printf '%q' "$home")" \
    "exec $(printf '%q' "$root/bin/fm-ops-inbox-poll.sh")"
}

# Resolve the watch settings from optional <config-dir>/ops-inbox.json.
# An absent config disables the optional integration, so one home's external
# operations runtime can never become another install's implicit default.
# A present config defaults to auto mode and must name its watched state_dir or
# all three paths explicitly. A malformed config is preserved as an error rather
# than silently defaulted.
# shellcheck disable=SC2034 # Result globals read by callers after this returns.
fm_ops_inbox_config_load() {
  local config_dir=$1 file raw
  FM_OPS_INBOX_CONFIG_ERROR=
  FM_OPS_INBOX_ENABLED=false
  FM_OPS_INBOX_STATE_DIR=
  FM_OPS_INBOX_SPOOL=
  FM_OPS_INBOX_ACKS=
  FM_OPS_INBOX_RECEIPT=
  FM_OPS_INBOX_AGE_HOURS=6
  FM_OPS_INBOX_COUNT=25
  FM_OPS_INBOX_REMIND_HOURS=24
  FM_OPS_INBOX_GROWTH=10
  FM_OPS_INBOX_RECEIPT_STALE_HOURS=3
  FM_OPS_INBOX_MAX_LINES=20000

  file="$config_dir/ops-inbox.json"
  if [ -e "$file" ] || [ -L "$file" ]; then
    FM_OPS_INBOX_ENABLED=auto
    if [ ! -f "$file" ] || [ -L "$file" ]; then
      FM_OPS_INBOX_CONFIG_ERROR="config/ops-inbox.json is not an ordinary file"
      return 1
    fi
    if ! command -v jq >/dev/null 2>&1; then
      FM_OPS_INBOX_CONFIG_ERROR="jq is required to read config/ops-inbox.json"
      return 1
    fi
    if ! jq -e 'type == "object"' "$file" >/dev/null 2>&1; then
      FM_OPS_INBOX_CONFIG_ERROR="config/ops-inbox.json is not a JSON object"
      return 1
    fi
    if ! jq -e '
      [
        "enabled", "state_dir", "spool", "acks", "receipt", "age_hours",
        "count", "remind_hours", "growth", "receipt_stale_hours", "max_lines"
      ] as $allowed
      | all(keys_unsorted[]; . as $key | ($allowed | index($key)) != null)
    ' "$file" >/dev/null 2>&1; then
      FM_OPS_INBOX_CONFIG_ERROR="config/ops-inbox.json has an unrecognized setting"
      # Configuration errors fail closed through the poll's config-error wake.
      return 1
    fi
    if ! jq -e '
      . as $config
      | (
          all(["state_dir", "spool", "acks", "receipt"][];
            . as $key
            | $config[$key] == null
              or (
                ($config[$key] | type) == "string"
                and ($config[$key] | length) > 0
              )
          )
          and all($config | to_entries[];
            .value as $value
            | ($value | type) != "string"
              or ($value | explode | all(. >= 32))
          )
        )
    ' "$file" >/dev/null 2>&1; then
      FM_OPS_INBOX_CONFIG_ERROR="config/ops-inbox.json has an invalid path or control character"
      return 1
    fi
    # Recognized null settings stay absent so their initialized defaults survive.
    raw=$(jq -r 'to_entries[] | select(.value != null) | .key + "=" + (.value | tostring)' \
      "$file" 2>/dev/null) || {
      FM_OPS_INBOX_CONFIG_ERROR="config/ops-inbox.json could not be read"
      return 1
    }
    # One key=value line per non-null recognized setting.
    local line key value
    while IFS= read -r line; do
      [ -n "$line" ] || continue
      key=${line%%=*}
      value=${line#*=}
      case "$key" in
        enabled)
          case "$value" in
            true|on|1) FM_OPS_INBOX_ENABLED=true ;;
            false|off|0) FM_OPS_INBOX_ENABLED=false ;;
            auto) FM_OPS_INBOX_ENABLED=auto ;;
            *)
              FM_OPS_INBOX_CONFIG_ERROR="config/ops-inbox.json enabled must be true, false, or auto"
              return 1
              ;;
          esac
          ;;
        state_dir) FM_OPS_INBOX_STATE_DIR=$value ;;
        spool) FM_OPS_INBOX_SPOOL=$value ;;
        acks) FM_OPS_INBOX_ACKS=$value ;;
        receipt) FM_OPS_INBOX_RECEIPT=$value ;;
        age_hours) fm_ops_inbox_set_number age_hours FM_OPS_INBOX_AGE_HOURS "$value" || return 1 ;;
        count) fm_ops_inbox_set_number count FM_OPS_INBOX_COUNT "$value" || return 1 ;;
        remind_hours) fm_ops_inbox_set_number remind_hours FM_OPS_INBOX_REMIND_HOURS "$value" || return 1 ;;
        growth) fm_ops_inbox_set_number growth FM_OPS_INBOX_GROWTH "$value" || return 1 ;;
        receipt_stale_hours)
          fm_ops_inbox_set_number receipt_stale_hours FM_OPS_INBOX_RECEIPT_STALE_HOURS "$value" || return 1
          ;;
        max_lines)
          fm_ops_inbox_set_number max_lines FM_OPS_INBOX_MAX_LINES "$value" || return 1
          if [ "$FM_OPS_INBOX_MAX_LINES" -eq 0 ]; then
            FM_OPS_INBOX_CONFIG_ERROR="config/ops-inbox.json max_lines must be greater than zero"
            return 1
          fi
          ;;
        *)
          FM_OPS_INBOX_CONFIG_ERROR="config/ops-inbox.json has an unrecognized setting: $key"
          return 1
          ;;
      esac
    done <<EOF
$raw
EOF
  fi

  if [ "$FM_OPS_INBOX_ENABLED" != false ] \
    && [ -z "$FM_OPS_INBOX_STATE_DIR" ] \
    && { [ -z "$FM_OPS_INBOX_SPOOL" ] || [ -z "$FM_OPS_INBOX_ACKS" ] || [ -z "$FM_OPS_INBOX_RECEIPT" ]; }; then
    FM_OPS_INBOX_CONFIG_ERROR="config/ops-inbox.json must set state_dir or all of spool, acks, and receipt when enabled"
    return 1
  fi
  if [ -n "$FM_OPS_INBOX_STATE_DIR" ]; then
    [ -n "$FM_OPS_INBOX_SPOOL" ] || FM_OPS_INBOX_SPOOL="$FM_OPS_INBOX_STATE_DIR/ops-inbox.jsonl"
    [ -n "$FM_OPS_INBOX_ACKS" ] || FM_OPS_INBOX_ACKS="$FM_OPS_INBOX_STATE_DIR/ops-inbox-acks.jsonl"
    [ -n "$FM_OPS_INBOX_RECEIPT" ] || FM_OPS_INBOX_RECEIPT="$FM_OPS_INBOX_STATE_DIR/ops-inbox-receipt.json"
  fi
  [ "$FM_OPS_INBOX_GROWTH" -ge 1 ] || FM_OPS_INBOX_GROWTH=1
}

# 0 when the home at <home> should keep the standing check armed. `true` arms
# unconditionally, `false` never arms, and `auto` arms only when the configured
# alert spool exists AND this is not a secondmate home. One machine has one alert
# inbox, so auto-arming every secondmate home would raise the same backlog once
# per home; the primary owns the machine's alert watch, and a secondmate that
# genuinely should watch it says so with an explicit `enabled: true`.
fm_ops_inbox_watch_expected() {
  local home=${1-}
  case "$FM_OPS_INBOX_ENABLED" in
    true) return 0 ;;
    false) return 1 ;;
    *)
      [ -z "$home" ] || [ ! -f "$home/.fm-secondmate-home" ] || return 1
      [ -f "$FM_OPS_INBOX_SPOOL" ]
      ;;
  esac
}

# Count unacked critical alerts and summarize them by class.
# Sets FM_OPS_INBOX_SCAN_COUNT, FM_OPS_INBOX_SCAN_OLDEST (an ISO-8601 Z string, or
# empty), FM_OPS_INBOX_SCAN_TOP (up to three "<count> <class>" lines, busiest
# first), FM_OPS_INBOX_SCAN_CLASSES (every class name, sorted, space-joined), and
# FM_OPS_INBOX_SCAN_TRUNCATED when the spool is longer than <max-lines>.
# Unacked means exactly what the spool's own reader means: a critical event with
# an inline false ack flag and no entry in the acknowledgement log.
# Samples at most <max-lines + 1> spool lines to detect overflow, then parses only
# the most recent <max-lines> of each input so this stays well inside the watcher's
# per-check timeout no matter how large the spool grows. Hitting that cap is
# reported rather than hidden: a capped read understates the total and the oldest
# age, and the spool needs rotating or triaging.
# A valid non-terminated final record is included, while a malformed final fragment
# is treated as a momentary append in progress.
# Every malformed complete input line fails the scan so the caller wakes fail-closed.
# shellcheck disable=SC2034 # Result globals read by callers after this returns.
fm_ops_inbox_scan() {
  local spool=$1 acks=$2 max_lines=${3:-20000} scan classes sample
  local ack_stream alert_stream unacked_stream validated_stream
  FM_OPS_INBOX_SCAN_COUNT=0
  FM_OPS_INBOX_SCAN_OLDEST=
  FM_OPS_INBOX_SCAN_TOP=
  FM_OPS_INBOX_SCAN_CLASSES=
  FM_OPS_INBOX_SCAN_TRUNCATED=0
  if [ ! -f "$spool" ]; then
    # An active scan fails closed; auto mode exits silently before calling it.
    return 1
  fi
  command -v jq >/dev/null 2>&1 || return 1
  case "$max_lines" in
    ''|*[!0-9]*|0) max_lines=20000 ;;
  esac
  sample=$(
    set -o pipefail
    head -n "$((max_lines + 1))" "$spool" 2>/dev/null \
      | jq -Rrs '
          (endswith("\n")) as $terminated
          | (split("\n") | map(select(test("\\S")))) as $records
          | if (
              ($terminated | not)
              and ($records | length) > 0
              and (try ($records[-1] | fromjson | false) catch true)
            )
            then ($records | length) - 1
            else ($records | length)
            end
        ' 2>/dev/null
  ) || return 1
  case "$sample" in
    ''|*[!0-9]*) return 1 ;;
  esac
  [ "$sample" -le "$max_lines" ] || FM_OPS_INBOX_SCAN_TRUNCATED=1
  ack_stream=
  if [ -f "$acks" ]; then
    ack_stream=$(
      set -o pipefail
      tail -n "$max_lines" "$acks" 2>/dev/null \
        | jq -r 'select(has("event_id")) | ["A", (.event_id | tostring)] | @tsv' 2>/dev/null
    ) || return 1
  fi
  alert_stream=$(
    set -o pipefail
    # @tsv, not hand-built tabs: an alert field carrying a tab or newline would
    # otherwise forge extra columns in this stream.
    tail -n "$((max_lines + 1))" "$spool" 2>/dev/null \
      | jq -Rrs --argjson max "$max_lines" '
        def decoded:
          try {valid: true, value: fromjson} catch {valid: false};
        (endswith("\n")) as $terminated
        | (split("\n") | map(select(test("\\S")))) as $records
        | (
            if (($terminated | not) and ($records | length) > 0) then
              ($records[-1] | decoded) as $last
              | if $last.valid then $records else $records[:-1] end
            else
              $records
            end
          )
        | if length > $max then .[-$max:] else . end
        | .[]
        | fromjson
        | select(.severity == "critical" and .ack == false)
        | ["E", ((.id // "") | tostring), ((.ts // "") | tostring), ((.source // "") | tostring)]
        | @tsv
      ' 2>/dev/null
  ) || return 1
  unacked_stream=$(awk -F'\t' '
      $1 == "A" { acked[$2] = 1; next }
      $1 == "E" {
        if ($2 != "" && ($2 in acked)) next
        print
      }
    ' <<EOF
$ack_stream
$alert_stream
EOF
  ) || return 1
  validated_stream=$(
    set -o pipefail
    printf '%s\n' "$unacked_stream" \
      | jq -Rr '
          select(length > 0)
          | split("\t") as $fields
          | $fields[2] as $ts
          | if (
              ($fields | length) == 4
              and ($ts | test("^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}Z$"))
              and (try ($ts | fromdateiso8601 | strftime("%Y-%m-%dT%H:%M:%SZ") == $ts) catch false)
            )
            then .
            else error("invalid critical alert timestamp")
            end
        ' 2>/dev/null
  ) || return 1
  scan=$(awk -F'\t' '
      $1 == "E" {
        count++
        ts = $3
        # Fixed-format validation above makes this lexicographic minimum sound.
        if (ts != "" && (oldest == "" || ts < oldest)) oldest = ts
        src = $4
        gsub(/[^A-Za-z0-9._:@\/-]/, "_", src)
        if (src == "") src = "unknown"
        if (length(src) > 48) src = substr(src, 1, 48)
        n[src]++
      }
      END {
        printf "%d\t%s\n", count + 0, oldest
        for (c in n) printf "%d\t%s\n", n[c], c
      }
    ' <<EOF
$validated_stream
EOF
  ) || return 1
  IFS=$(printf '\t') read -r FM_OPS_INBOX_SCAN_COUNT FM_OPS_INBOX_SCAN_OLDEST <<EOF
$scan
EOF
  case "$FM_OPS_INBOX_SCAN_COUNT" in
    ''|*[!0-9]*) return 1 ;;
  esac
  FM_OPS_INBOX_SCAN_TOP=$(
    set -o pipefail
    printf '%s\n' "$scan" | tail -n +2 | sort -k1,1nr -k2,2 | sed -n '1,3p'
  ) || return 1
  classes=$(
    set -o pipefail
    printf '%s\n' "$scan" | tail -n +2 | cut -f2 | sort -u | tr '\n' ' '
  ) || return 1
  FM_OPS_INBOX_SCAN_CLASSES=${classes% }
}

# Print the receipt's own unacked critical count, or nothing when the receipt is
# absent, unreadable, or carries no usable count.
fm_ops_inbox_receipt_count() {
  local receipt=$1 value
  [ -f "$receipt" ] || return 1
  command -v jq >/dev/null 2>&1 || return 1
  value=$(jq -r '.unacked_critical_count // empty' "$receipt" 2>/dev/null) || return 1
  value=$(fm_ops_inbox_canonical_number "$value") || return 1
  printf '%s' "$value"
}

# Epoch seconds for one fixed-format spool timestamp. Rejects anything else
# rather than guessing, because a bad parse would fake an alert age.
fm_ops_inbox_epoch_of_iso() {
  local iso=$1 epoch normalized
  case "$iso" in
    [0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9]T[0-9][0-9]:[0-9][0-9]:[0-9][0-9]Z) ;;
    *) return 1 ;;
  esac
  if [ "$(uname)" = Darwin ]; then
    epoch=$(date -u -j -f '%Y-%m-%dT%H:%M:%SZ' "$iso" +%s 2>/dev/null) || return 1
    normalized=$(date -u -r "$epoch" +%Y-%m-%dT%H:%M:%SZ 2>/dev/null) || return 1
  else
    epoch=$(date -u -d "$iso" +%s 2>/dev/null) || return 1
    normalized=$(date -u -d "@$epoch" +%Y-%m-%dT%H:%M:%SZ 2>/dev/null) || return 1
  fi
  [ "$normalized" = "$iso" ] || return 1
  printf '%s' "$epoch"
}

fm_ops_inbox_age_label() {
  local s=${1:-0}
  case "$s" in
    ''|*[!0-9]*) s=0 ;;
  esac
  if [ "$s" -ge 86400 ]; then
    printf '%dd' $((s / 86400))
  elif [ "$s" -ge 3600 ]; then
    printf '%dh' $((s / 3600))
  elif [ "$s" -ge 60 ]; then
    printf '%dm' $((s / 60))
  else
    printf '%ds' "$s"
  fi
}

fm_ops_inbox_stat_mtime() {
  if [ "$(uname)" = Darwin ]; then
    stat -f %m "$1" 2>/dev/null
  else
    stat -c %Y "$1" 2>/dev/null
  fi
}

# Read the last recorded wake into FM_OPS_INBOX_LAST_EPOCH, _LAST_COUNT,
# _LAST_STATE, and _LAST_CLASSES. A missing, malformed, or version-mismatched
# sidecar reads as "no prior wake", which makes the next qualifying condition
# wake rather than stay silent.
# shellcheck disable=SC2034 # Result globals read by callers after this returns.
fm_ops_inbox_sidecar_read() {
  local path=$1 version epoch count state classes
  FM_OPS_INBOX_LAST_EPOCH=
  FM_OPS_INBOX_LAST_COUNT=
  FM_OPS_INBOX_LAST_STATE=
  FM_OPS_INBOX_LAST_CLASSES=
  [ -f "$path" ] && [ ! -L "$path" ] || return 1
  exec 8< "$path" || return 1
  IFS= read -r version <&8 || { exec 8<&-; return 1; }
  IFS= read -r epoch <&8 || { exec 8<&-; return 1; }
  IFS= read -r count <&8 || { exec 8<&-; return 1; }
  IFS= read -r state <&8 || { exec 8<&-; return 1; }
  IFS= read -r classes <&8 || classes=
  exec 8<&-
  [ "$version" = "$FM_OPS_INBOX_SIDECAR_VERSION" ] || return 1
  epoch=$(fm_ops_inbox_canonical_number "$epoch") || return 1
  count=$(fm_ops_inbox_canonical_number "$count") || return 1
  [ -n "$state" ] || return 1
  FM_OPS_INBOX_LAST_EPOCH=$epoch
  FM_OPS_INBOX_LAST_COUNT=$count
  FM_OPS_INBOX_LAST_STATE=$state
  FM_OPS_INBOX_LAST_CLASSES=$classes
}

# Record this wake atomically and privately. A failed write is reported to the
# caller instead of being ignored, because a sidecar that never advances would
# repeat the same wake on every poll.
fm_ops_inbox_sidecar_write() {
  local path=$1 epoch=$2 count=$3 state=$4 classes=$5 dir tmp
  dir=${path%/*}
  [ -d "$dir" ] && [ ! -L "$dir" ] || return 1
  if [ -e "$path" ] || [ -L "$path" ]; then
    [ -f "$path" ] && [ ! -L "$path" ] || return 1
  fi
  tmp=$(umask 077; mktemp "$dir/.fm-ops-inbox-wake.XXXXXX") || return 1
  {
    printf '%s\n' "$FM_OPS_INBOX_SIDECAR_VERSION" "$epoch" "$count" "$state" "$classes"
  } > "$tmp" || { rm -f -- "$tmp"; return 1; }
  chmod 0600 "$tmp" || { rm -f -- "$tmp"; return 1; }
  mv -f -- "$tmp" "$path" || { rm -f -- "$tmp"; return 1; }
}
