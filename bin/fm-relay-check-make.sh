#!/usr/bin/env bash
# fm-relay-check-make.sh - arm the wake path for a task running on a relay host.
#
# Usage: fm-relay-check-make.sh <task-id>
#
# A remote crewmate's status file lives on ITS machine, so this home's signal
# scan (which watches state/*.status and state/*.turn-ended) can never see it.
# The watcher's slow custom-check hook is the one path that can: it runs
# state/<id>.check.sh every FM_CHECK_INTERVAL, treats one line of output as a
# wake, and executes only a check whose exact bytes were registered through
# bin/fm-check-register.sh. This script writes that check and registers it.
#
# The generated file carries per-task parameters and ONE call into
# bin/fm-relay-lib.sh. Nothing rewrites an armed check, so any judgement inlined
# here would be frozen at the moment of arming; keeping it in the library means a
# later fix reaches checks armed before the fix existed.
#
# The cost of this wake path, stated plainly: a remote task does not get the
# turn-end hook's immediate wake, because that hook writes a file on the host.
# Wake latency is therefore 0..FM_CHECK_INTERVAL (300 s by default), which is the
# deliberate Phase 1 trade recorded in docs/relay-host.md.
set -eu

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FM_ROOT="${FM_ROOT_OVERRIDE:-$(cd "$SCRIPT_DIR/.." && pwd)}"
FM_HOME="${FM_HOME:-${FM_ROOT_OVERRIDE:-$FM_ROOT}}"
STATE="${FM_STATE_OVERRIDE:-$FM_HOME/state}"

usage() {
  sed -n '2,21p' "$0" | sed 's/^# \{0,1\}//'
}

case "${1:-}" in
  -h|--help|'') usage; exit 0 ;;
esac

# shellcheck source=bin/fm-relay-lib.sh
. "$SCRIPT_DIR/fm-relay-lib.sh"

ID=$1
fm_relay_id_valid "$ID" || { echo "error: invalid task id '$ID'" >&2; exit 2; }
META="$STATE/$ID.meta"
[ -f "$META" ] || { echo "error: no metadata for task $ID at $META" >&2; exit 1; }
HOST=$(fm_relay_meta_host "$META")
[ -n "$HOST" ] || { echo "error: task $ID has no host= line; it is not a relay task" >&2; exit 1; }
fm_relay_host_load "$FM_HOME" "$HOST" || exit 1

CHECK="$STATE/$ID.check.sh"
if [ -e "$CHECK" ] || [ -L "$CHECK" ]; then
  echo "error: $CHECK already exists; remove it deliberately before re-arming" >&2
  exit 1
fi

umask 077
TMP=$(mktemp "$STATE/.fm-relay-check.XXXXXX")
trap '[ -z "${TMP:-}" ] || rm -f -- "$TMP"' EXIT HUP INT TERM
cat > "$TMP" <<EOF
#!/usr/bin/env bash
# Generated by bin/fm-relay-check-make.sh for relay task $ID on host $HOST.
# Per-task parameters plus one library call; every judgement lives in
# bin/fm-relay-lib.sh so a later fix reaches checks armed before it.
set -u
. "$FM_ROOT/bin/fm-relay-lib.sh"
fm_relay_check_emit "$FM_HOME" "$ID"
EOF
chmod 0700 "$TMP"
mv -f -- "$TMP" "$CHECK"
TMP=

FM_HOME="$FM_HOME" FM_STATE_OVERRIDE="$STATE" "$SCRIPT_DIR/fm-check-register.sh" "$ID"
printf 'armed: relay wake check for %s on %s\n' "$ID" "$HOST"
