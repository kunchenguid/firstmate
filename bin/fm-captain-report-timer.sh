#!/usr/bin/env bash
# fm-captain-report-timer.sh - arm, inspect, and disarm the repeating
# captain-report timer used by the `updatethecaptain` skill.
#
# Usage:
#   fm-captain-report-timer.sh arm [--interval <seconds>]
#   fm-captain-report-timer.sh disarm
#   fm-captain-report-timer.sh status
#
# arm      Write the timer check, stamp it with the current time, and bind its
#          bytes through bin/fm-check-register.sh so the existing watcher will
#          dispatch it. Idempotent: re-arming rewrites the check, resets the
#          stamp, and re-registers, so the next report is a full interval away.
#          Default interval 600 seconds; accepted range 60 to 86400.
# disarm   Remove the timer check, its trust binding, and its stamp. Idempotent
#          and harmless when nothing is armed; exits 0 either way.
# status   Report whether the timer is armed, its interval, and the seconds
#          remaining before its next line. Exits 0 either way.
#
# The timer rides the watcher's existing authenticated custom-check dispatch
# rather than a shell background job, a detached process, or a second watcher.
# A registered check is copied to a private snapshot, byte-validated against its
# trust binding, and executed by the one supervision cycle that is already
# running, so the timer survives the captain sending messages, needs nothing
# from the captain to stay alive, and stops with the home rather than outliving
# it. It also means the timer only fires while a supervision cycle is live,
# which is exactly the window in which there is worker progress to report.
#
# Artifacts, all private to this home's state directory:
#   <state>/captain-report.check.sh    the generated timer check, mode 0700
#   <state>/captain-report.check-trust its trust binding, written by
#                                      bin/fm-check-register.sh
#   <state>/.captain-report-timer      the last-fired stamp, mode 0600, holding
#                                      one epoch-seconds line
#
# The check advances its own stamp before printing, so one elapsed interval
# produces exactly one wake even when the report is written later. The wake
# queue is durable, so a tick is never lost by a slow reply. Watcher sweep
# granularity bounds precision: the line lands on the first sweep at or after
# the interval, never before it.
set -u

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FM_ROOT="${FM_ROOT_OVERRIDE:-$(cd "$SCRIPT_DIR/.." && pwd)}"
FM_HOME="${FM_HOME:-${FM_ROOT_OVERRIDE:-$FM_ROOT}}"
STATE="${FM_STATE_OVERRIDE:-$FM_HOME/state}"

# shellcheck source=bin/fm-pr-lib.sh
. "$SCRIPT_DIR/fm-pr-lib.sh"
# shellcheck source=bin/fm-check-lib.sh
. "$SCRIPT_DIR/fm-check-lib.sh"

ID=captain-report
CHECK="$STATE/$ID.check.sh"
TRUST="$STATE/$ID.check-trust"
STAMP="$STATE/.$ID-timer"
DEFAULT_INTERVAL=600
MIN_INTERVAL=60
MAX_INTERVAL=86400

die() { printf 'error: %s\n' "$1" >&2; exit 1; }
usage() { sed -n '2,20p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 2; }

# The generated check embeds its stamp path as a single-quoted literal, so a
# path carrying a quote or a newline would break out of that literal. Refuse
# such a home rather than writing a check whose meaning depends on the path.
state_path_embeddable() {
  case "$STATE" in
    *"'"*|*$'\n'*) return 1 ;;
  esac
  case "$STATE" in
    /*) return 0 ;;
    *) return 1 ;;
  esac
}

interval_valid() {
  local value=$1
  case "$value" in
    ''|*[!0-9]*) return 1 ;;
  esac
  [ "$value" -ge "$MIN_INTERVAL" ] && [ "$value" -le "$MAX_INTERVAL" ]
}

state_dir_usable() {
  [ -d "$STATE" ] && [ ! -L "$STATE" ]
}

# Atomically publish <content> at <dest> with <mode>, refusing a destination
# that is a symlink, a hard link, or on another device.
publish_private_file() {
  local dest=$1 content=$2 mode=$3 device tmp
  device=$(fm_pr_file_device "$STATE") || return 1
  fm_pr_regular_destination_on_device_or_absent "$dest" "$device" || return 1
  tmp=$(umask 077; mktemp "$STATE/.fm-captain-report.XXXXXX") || return 1
  if ! printf '%s\n' "$content" > "$tmp" || ! chmod "$mode" "$tmp"; then
    rm -f -- "$tmp"
    return 1
  fi
  if ! fm_pr_regular_destination_on_device_or_absent "$dest" "$device" \
    || ! mv -f -- "$tmp" "$dest"; then
    rm -f -- "$tmp"
    return 1
  fi
  fm_pr_private_file_valid "$dest" "$mode" "$device"
}

remove_artifact() {
  local path=$1
  [ -e "$path" ] || [ -L "$path" ] || return 0
  rm -f -- "$path" 2>/dev/null || return 1
  [ ! -e "$path" ] && [ ! -L "$path" ]
}

check_body() {
  local interval=$1
  cat <<EOF
#!/usr/bin/env bash
# Generated by bin/fm-captain-report-timer.sh - repeating captain-report timer.
# Prints one line when the interval has elapsed and nothing otherwise, then
# advances its own stamp so one elapsed interval yields exactly one wake.
set -u
stamp='$STATE/.$ID-timer'
interval=$interval
EOF
  cat <<'EOF'
last=$(cat -- "$stamp" 2>/dev/null) || exit 0
case "$last" in
  ''|*[!0-9]*) exit 0 ;;
esac
now=$(date +%s) || exit 0
[ "$((now - last))" -ge "$interval" ] || exit 0
tmp=$(umask 077; mktemp "${stamp%/*}/.fm-captain-report.XXXXXX") || exit 0
if ! printf '%s\n' "$now" > "$tmp" || ! chmod 0600 "$tmp" || ! mv -f -- "$tmp" "$stamp"; then
  rm -f -- "$tmp"
  exit 0
fi
printf 'captain report due\n'
EOF
}

stamp_read() {
  local value
  value=$(cat -- "$STAMP" 2>/dev/null) || return 1
  case "$value" in
    ''|*[!0-9]*) return 1 ;;
  esac
  printf '%s\n' "$value"
}

# Echo the armed interval by reading it back from the registered check, so
# status never reports a cadence the watcher is not actually running.
armed_interval() {
  local value
  value=$(sed -n 's/^interval=\([0-9][0-9]*\)$/\1/p' "$CHECK" 2>/dev/null | head -n 1)
  interval_valid "$value" || return 1
  printf '%s\n' "$value"
}

cmd_arm() {
  local interval=$DEFAULT_INTERVAL now
  while [ "$#" -gt 0 ]; do
    case "$1" in
      --interval)
        [ "$#" -gt 1 ] || die "--interval requires a value in seconds"
        interval=$2
        shift 2
        ;;
      -h|--help) usage ;;
      *) die "unknown argument: $1" ;;
    esac
  done
  interval_valid "$interval" \
    || die "--interval must be a whole number of seconds from $MIN_INTERVAL to $MAX_INTERVAL"
  mkdir -p "$STATE" 2>/dev/null || true
  state_dir_usable || die "state directory is unavailable"
  state_path_embeddable || die "state directory path cannot carry a timer check"
  now=$(date +%s) || die "cannot read the current time"
  publish_private_file "$CHECK" "$(check_body "$interval")" 700 \
    || die "cannot publish the timer check"
  if ! publish_private_file "$STAMP" "$now" 600; then
    remove_artifact "$CHECK" || true
    die "cannot publish the timer stamp"
  fi
  if ! FM_HOME="$FM_HOME" FM_STATE_OVERRIDE="$STATE" \
    "$SCRIPT_DIR/fm-check-register.sh" "$ID" >/dev/null; then
    remove_artifact "$CHECK" || true
    remove_artifact "$STAMP" || true
    remove_artifact "$TRUST" || true
    die "cannot register the timer check"
  fi
  fm_custom_check_registered "$STATE" "$ID" || die "the timer check did not register"
  printf 'armed: state/%s.check.sh interval=%ss\n' "$ID" "$interval"
}

cmd_disarm() {
  local removed=0 failed=0 path
  [ "$#" -eq 0 ] || usage
  if ! state_dir_usable; then
    printf 'not armed\n'
    return 0
  fi
  for path in "$CHECK" "$TRUST" "$STAMP"; do
    if [ -e "$path" ] || [ -L "$path" ]; then
      removed=1
      remove_artifact "$path" || failed=1
    fi
  done
  if [ "$failed" -ne 0 ]; then
    die "cannot remove the timer artifacts"
  fi
  if [ "$removed" -eq 0 ]; then
    printf 'not armed\n'
  else
    printf 'disarmed\n'
  fi
}

cmd_status() {
  local interval last now due
  [ "$#" -eq 0 ] || usage
  if ! state_dir_usable || ! fm_custom_check_registered "$STATE" "$ID"; then
    printf 'not armed\n'
    return 0
  fi
  interval=$(armed_interval) || { printf 'not armed\n'; return 0; }
  last=$(stamp_read) || { printf 'not armed\n'; return 0; }
  now=$(date +%s) || die "cannot read the current time"
  due=$((last + interval - now))
  [ "$due" -ge 0 ] || due=0
  printf 'armed interval=%ss due-in=%ss\n' "$interval" "$due"
}

[ "$#" -ge 1 ] || usage
COMMAND=$1
shift
case "$COMMAND" in
  arm) cmd_arm "$@" ;;
  disarm) cmd_disarm "$@" ;;
  status) cmd_status "$@" ;;
  -h|--help) usage ;;
  *) die "unknown command: $COMMAND" ;;
esac
