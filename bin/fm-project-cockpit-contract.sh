#!/usr/bin/env bash
# fm-project-cockpit-contract.sh - shared Project Cockpit schema and byte bounds.

FM_PROJECT_COCKPIT_MAX_PROJECTS=80
FM_PROJECT_COCKPIT_MAX_TASKS_PER_PROJECT=160
FM_PROJECT_COCKPIT_MAX_TOTAL_TASKS=500
FM_PROJECT_COCKPIT_MAX_DECISIONS=20
FM_PROJECT_COCKPIT_MAX_BLOCKERS=20
FM_PROJECT_COCKPIT_MAX_PARTIAL_REASONS=20
FM_PROJECT_COCKPIT_MAX_STRING=500

FM_PROJECT_COCKPIT_JSON_BYTES_PER_CHAR=6
FM_PROJECT_COCKPIT_TASK_TEXT_CHARS=$((
  128 + 128 + 160 + 128 + 40 + 40 + 20 + 20 +
  40 + 40 + 40 + 40 +
  40 + 240 + 40 + 40 +
  40 + 240 +
  500 + 40 + 500 +
  40 + 240 + 500 + 500 +
  40 + 240 + 40 + 240 + 40 + 40 +
  FM_PROJECT_COCKPIT_MAX_DECISIONS * 240 +
  FM_PROJECT_COCKPIT_MAX_BLOCKERS * 128
))
FM_PROJECT_COCKPIT_TASK_JSON_OVERHEAD=4096
FM_PROJECT_COCKPIT_PROJECT_JSON_BYTES=4096
FM_PROJECT_COCKPIT_BASE_JSON_BYTES=1048576
FM_PROJECT_COCKPIT_MODEL_MAX_BYTES=$((
  FM_PROJECT_COCKPIT_BASE_JSON_BYTES +
  FM_PROJECT_COCKPIT_MAX_PROJECTS * FM_PROJECT_COCKPIT_PROJECT_JSON_BYTES +
  FM_PROJECT_COCKPIT_MAX_TOTAL_TASKS *
    (FM_PROJECT_COCKPIT_TASK_JSON_OVERHEAD +
     FM_PROJECT_COCKPIT_TASK_TEXT_CHARS * FM_PROJECT_COCKPIT_JSON_BYTES_PER_CHAR) +
  FM_PROJECT_COCKPIT_MAX_PARTIAL_REASONS * 240 * FM_PROJECT_COCKPIT_JSON_BYTES_PER_CHAR
))
