#!/usr/bin/env bash
# Shared configuration and helpers for self-hosted Discord connector client
# (fm-discord-poll.sh and fm-discord-reply.sh).
#
# Self-hosted Discord mode is opt-in: a user drops a non-empty FM_DISCORD_BOT_TOKEN
# into the firstmate home's .env.
#
# This file is sourced, never executed directly.
#
# Sourced by bin/fm-bootstrap.sh, bin/fm-discord-poll.sh, bin/fm-discord-reply.sh.

_FM_DISCORD_LIB_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
if ! command -v fmx_env_get >/dev/null 2>&1; then
  # shellcheck source=bin/fm-env-lib.sh
  . "$_FM_DISCORD_LIB_DIR/fm-env-lib.sh"
fi
if ! command -v fmx_private_artifact_publish_stdin >/dev/null 2>&1; then
  # shellcheck source=bin/fm-x-lib.sh
  . "$_FM_DISCORD_LIB_DIR/fm-x-lib.sh"
fi

fm_discord_poll_shim_content() {
  local home=$1 root=$2
  printf '%s\n' \
    '#!/usr/bin/env bash' \
    '# Auto-generated by fm-bootstrap.sh - Self-hosted Discord connector poll shim.' \
    '# The watcher validates these bytes, then dispatches the trusted poll script.' \
    "export FM_HOME=$(printf '%q' "$home")" \
    "exec $(printf '%q' "$root/bin/fm-discord-poll.sh")"
}

fm_discord_trim() {
  local value=$1
  value=${value#"${value%%[![:space:]]*}"}
  value=${value%"${value##*[![:space:]]}"}
  printf '%s' "$value"
}

# Resolve self-hosted Discord settings.
# FM_DISCORD_BOT_TOKEN (required for active self-hosted Discord connection)
# FM_DISCORD_CHANNEL_ID or FM_DISCORD_ALLOWED_CHANNELS (optional target channel IDs)
# FM_DISCORD_EXCLUDE_CHANNELS (optional excluded channel IDs, default "1551134713727426570")
# FM_DISCORD_ALLOW_DMS (default "true")
fm_discord_load_config() {
  local env_file="${FMX_ENV_FILE:-$FM_HOME/.env}"
  # shellcheck disable=SC2034 # Output global, read by sourcing callers (fm-discord-poll.sh, fm-discord-reply.sh).
  if [ -n "${FM_DISCORD_BOT_TOKEN+x}" ]; then
    FM_DISCORD_TOKEN=${FM_DISCORD_BOT_TOKEN-}
  else
    FM_DISCORD_TOKEN=$(fmx_env_get FM_DISCORD_BOT_TOKEN "$env_file")
  fi

  if [ -n "${FM_DISCORD_CHANNEL_ID+x}" ]; then
    FM_DISCORD_CHANNELS=${FM_DISCORD_CHANNEL_ID-}
  elif [ -n "${FM_DISCORD_ALLOWED_CHANNELS+x}" ]; then
    FM_DISCORD_CHANNELS=${FM_DISCORD_ALLOWED_CHANNELS-}
  else
    FM_DISCORD_CHANNELS=$(fmx_env_get FM_DISCORD_CHANNEL_ID "$env_file")
    [ -n "$FM_DISCORD_CHANNELS" ] || FM_DISCORD_CHANNELS=$(fmx_env_get FM_DISCORD_ALLOWED_CHANNELS "$env_file")
  fi

  if [ -n "${FM_DISCORD_EXCLUDE_CHANNELS+x}" ]; then
    FM_DISCORD_EXCLUDES=${FM_DISCORD_EXCLUDE_CHANNELS-}
    FM_DISCORD_EXCLUDES_EXPLICIT=0
    [ -n "$FM_DISCORD_EXCLUDES" ] && FM_DISCORD_EXCLUDES_EXPLICIT=1
  else
    FM_DISCORD_EXCLUDES=$(fmx_env_get FM_DISCORD_EXCLUDE_CHANNELS "$env_file")
    FM_DISCORD_EXCLUDES_EXPLICIT=0
    [ -n "$FM_DISCORD_EXCLUDES" ] && FM_DISCORD_EXCLUDES_EXPLICIT=1
  fi
  # Default exclusion for collision prevention with gajae-way's channel
  [ -n "$FM_DISCORD_EXCLUDES" ] || FM_DISCORD_EXCLUDES="1551134713727426570"

  # An explicit allowlist opts its channel into polling despite the built-in
  # collision exclusion. A user-configured exclusion remains authoritative.
  if [ -n "$FM_DISCORD_CHANNELS" ]; then
    local allowed excluded keep conflict
    local -a allowed_ids excluded_ids
    IFS=',' read -r -a allowed_ids <<< "$FM_DISCORD_CHANNELS"
    IFS=',' read -r -a excluded_ids <<< "$FM_DISCORD_EXCLUDES"
    keep=
    for excluded in "${excluded_ids[@]}"; do
      excluded=${excluded//[[:space:]]/}
      [ -n "$excluded" ] || continue
      conflict=0
      for allowed in "${allowed_ids[@]}"; do
        allowed=${allowed//[[:space:]]/}
        if [ "$allowed" = "$excluded" ]; then
          conflict=1
          if [ "$FM_DISCORD_EXCLUDES_EXPLICIT" -eq 1 ]; then
            printf 'fm-discord: channel %s is allowlisted and explicitly excluded; exclusion wins\n' "$excluded" >&2
          else
            printf 'fm-discord: allowlisted Discord channel %s overrides the built-in exclusion\n' "$excluded" >&2
          fi
          break
        fi
      done
      if [ "$conflict" -eq 0 ] || [ "$FM_DISCORD_EXCLUDES_EXPLICIT" -eq 1 ]; then
        keep=${keep:+$keep,}$excluded
      fi
    done
    FM_DISCORD_EXCLUDES=$keep
  fi

  if [ -n "${FM_DISCORD_ALLOW_DMS+x}" ]; then
    FM_DISCORD_DMS=${FM_DISCORD_ALLOW_DMS-}
  else
    FM_DISCORD_DMS=$(fmx_env_get FM_DISCORD_ALLOW_DMS "$env_file")
  fi
  [ -n "$FM_DISCORD_DMS" ] || FM_DISCORD_DMS="true"

  if [ -n "${FM_DISCORD_AUTHORIZED_USER_IDS+x}" ]; then
    FM_DISCORD_AUTHORIZED_USERS=${FM_DISCORD_AUTHORIZED_USER_IDS-}
  else
    FM_DISCORD_AUTHORIZED_USERS=$(fmx_env_get FM_DISCORD_AUTHORIZED_USER_IDS "$env_file")
  fi
  export FM_DISCORD_AUTHORIZED_USERS
}

# Check if a request_id or context is from self-hosted Discord
fm_discord_is_selfhosted_request() {
  local req_id=$1 state=${2:-$STATE} ctx source
  case "$req_id" in
    discord-sh-*) return 0 ;;
  esac
  ctx=$(fmx_context_registry_get "$state" "$req_id" 2>/dev/null) || ctx=
  source=$(printf '%s' "$ctx" | jq -r '.source // ""' 2>/dev/null) || source=
  [ "$source" = "discord-selfhosted" ]
}
