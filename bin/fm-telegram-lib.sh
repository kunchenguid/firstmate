#!/usr/bin/env bash
# Private Telegram bridge primitives shared by setup, polling, request reads,
# outbound delivery, bootstrap activation, and watcher authentication.
#
# The Bot API token is read only from the owner-only local JSON config and is
# placed only in an owner-only temporary curl config file.
# It is never passed as a process argument, printed, or copied into runtime
# receipts, wake records, diagnostics, or test evidence.

FMTG_LIB_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FMTG_ROOT_DEFAULT="$(cd "$FMTG_LIB_DIR/.." && pwd)"
FM_ROOT="${FM_ROOT_OVERRIDE:-${FM_ROOT:-$FMTG_ROOT_DEFAULT}}"
FM_HOME="${FM_HOME:-${FM_ROOT_OVERRIDE:-$FM_ROOT}}"
STATE="${FM_STATE_OVERRIDE:-${STATE:-$FM_HOME/state}}"
CONFIG="${FM_CONFIG_OVERRIDE:-${CONFIG:-$FM_HOME/config}}"
FMTG_CONFIG_DIR="${FMTG_CONFIG_DIR:-$CONFIG/telegram}"
FMTG_CONFIG_FILE="${FMTG_CONFIG_FILE:-$FMTG_CONFIG_DIR/bridge.json}"
FMTG_STATE="$STATE/telegram"
FMTG_MAX_INBOUND_BYTES=${FMTG_MAX_INBOUND_BYTES:-4096}
FMTG_RETENTION_SECS=${FMTG_RETENTION_SECS:-604800}
FMTG_APPROVAL_TTL_SECS=${FMTG_APPROVAL_TTL_SECS:-86400}
FMTG_POLL_TIMEOUT=${FMTG_POLL_TIMEOUT:-10}
FMTG_CURL_TIMEOUT=${FMTG_CURL_TIMEOUT:-15}

# shellcheck source=bin/fm-private-lib.sh
. "$FMTG_LIB_DIR/fm-private-lib.sh"

fmtg_safe_slug() {
  case "$1" in
    ''|.*|*[!A-Za-z0-9._-]*) return 1 ;;
  esac
  [ "${#1}" -le "${2:-128}" ]
}

fmtg_prepare_state() {
  local dir
  fm_private_dir_prepare "$FMTG_STATE" || return 1
  for dir in inbox updates outbound rendered approvals approval-claims; do
    fm_private_dir_prepare "$FMTG_STATE/$dir" || return 1
  done
}

fmtg_json_publish() { # <dir> <base>
  local dir=$1 base=$2 tmp
  tmp=$(umask 077; mktemp "${TMPDIR:-/tmp}/fm-telegram-json.XXXXXX" 2>/dev/null) || return 1
  if ! cat > "$tmp" || ! jq -e . "$tmp" >/dev/null 2>&1; then
    rm -f -- "$tmp"
    return 1
  fi
  if ! fm_private_publish_stdin "$dir" "$base" 600 < "$tmp"; then
    rm -f -- "$tmp"
    return 1
  fi
  rm -f -- "$tmp"
}

fmtg_json_publish_once() { # <dir> <base>
  local dir=$1 base=$2 tmp rc
  tmp=$(umask 077; mktemp "${TMPDIR:-/tmp}/fm-telegram-json.XXXXXX" 2>/dev/null) || return 2
  if ! cat > "$tmp" || ! jq -e . "$tmp" >/dev/null 2>&1; then
    rm -f -- "$tmp"
    return 2
  fi
  fm_private_publish_stdin_once "$dir" "$base" 600 < "$tmp"
  rc=$?
  rm -f -- "$tmp"
  return "$rc"
}

FMTG_CONFIG_STATUS=off
FMTG_TOKEN=
FMTG_ALLOWED_USER_ID=
FMTG_ALLOWED_CHAT_ID=
fmtg_load_config() {
  local raw
  FMTG_CONFIG_STATUS=off
  FMTG_TOKEN=
  FMTG_ALLOWED_USER_ID=
  FMTG_ALLOWED_CHAT_ID=
  if [ ! -e "$FMTG_CONFIG_FILE" ] && [ ! -L "$FMTG_CONFIG_FILE" ]; then
    return 1
  fi
  raw=$(fm_private_read_file "$FMTG_CONFIG_FILE" 600) || { FMTG_CONFIG_STATUS=invalid; return 2; }
  if ! printf '%s' "$raw" | jq -e '
    type == "object"
    and (.version == 1)
    and (.enabled | type == "boolean")
    and (.bot_token | type == "string")
    and (.allowed_user_id | type == "string")
    and (.allowed_chat_id | type == "string")
    and ([keys[]] - ["allowed_chat_id","allowed_user_id","bot_token","enabled","version"] | length == 0)
  ' >/dev/null 2>&1; then
    FMTG_CONFIG_STATUS=invalid
    return 2
  fi
  if [ "$(printf '%s' "$raw" | jq -r '.enabled')" != true ]; then
    FMTG_CONFIG_STATUS=off
    return 1
  fi
  FMTG_TOKEN=$(printf '%s' "$raw" | jq -r '.bot_token')
  FMTG_ALLOWED_USER_ID=$(printf '%s' "$raw" | jq -r '.allowed_user_id')
  FMTG_ALLOWED_CHAT_ID=$(printf '%s' "$raw" | jq -r '.allowed_chat_id')
  printf '%s' "$FMTG_TOKEN" | jq -R -e 'test("^[0-9]{6,20}:[A-Za-z0-9_-]{30,110}$")' >/dev/null 2>&1 \
    || { FMTG_CONFIG_STATUS=invalid; return 2; }
  [ "${#FMTG_TOKEN}" -ge 40 ] && [ "${#FMTG_TOKEN}" -le 128 ] \
    || { FMTG_CONFIG_STATUS=invalid; return 2; }
  case "$FMTG_ALLOWED_USER_ID:$FMTG_ALLOWED_CHAT_ID" in
    *[!0-9:]*|:*|*:) FMTG_CONFIG_STATUS=invalid; return 2 ;;
  esac
  [ "$FMTG_ALLOWED_USER_ID" = "$FMTG_ALLOWED_CHAT_ID" ] \
    || { FMTG_CONFIG_STATUS=invalid; return 2; }
  [ "${#FMTG_ALLOWED_USER_ID}" -le 16 ] \
    && [ "$FMTG_ALLOWED_USER_ID" -gt 0 ] \
    && [ "$FMTG_ALLOWED_USER_ID" -le 9007199254740991 ] \
    || { FMTG_CONFIG_STATUS=invalid; return 2; }
  # shellcheck disable=SC2034 # Public result consumed by sourcing callers.
  FMTG_CONFIG_STATUS=enabled
  return 0
}

fmtg_poll_shim_content() { # <home> <root>
  local home=$1 root=$2
  printf '%s\n' \
    '#!/usr/bin/env bash' \
    '# Auto-generated by fm-bootstrap.sh - private Telegram poll identity shim.' \
    '# The watcher validates these bytes and dispatches the trusted poll script.' \
    "export FM_HOME=$(printf '%q' "$home")" \
    "exec $(printf '%q' "$root/bin/fm-telegram-poll.sh")"
}

fmtg_poll_shim_valid() { # <path> <home> <root>
  fm_private_file_valid "$1" 700 || return 1
  cmp -s "$1" <(fmtg_poll_shim_content "$2" "$3")
}

FMTG_API_HTTP=
FMTG_API_RC=0
fmtg_api_call() { # <method> <payload-file> <body-file> [max-seconds]
  local method=$1 payload=$2 body=$3 max=${4:-$FMTG_CURL_TIMEOUT} cfg code rc
  fmtg_safe_slug "$method" 64 || return 2
  fm_private_file_valid "$payload" 600 || return 2
  cfg=$(umask 077; mktemp "${TMPDIR:-/tmp}/fm-telegram-curl.XXXXXX" 2>/dev/null) || return 2
  chmod 0600 "$cfg" 2>/dev/null || { rm -f -- "$cfg"; return 2; }
  {
    printf 'url = "https://api.telegram.org/bot%s/%s"\n' "$FMTG_TOKEN" "$method"
    printf 'request = "POST"\n'
    printf 'header = "Content-Type: application/json"\n'
    printf 'silent\nshow-error\nmax-time = %s\n' "$max"
  } > "$cfg" || { rm -f -- "$cfg"; return 2; }
  fm_private_file_valid "$cfg" 600 || { rm -f -- "$cfg"; return 2; }
  if code=$(curl --config "$cfg" --data-binary "@$payload" --output "$body" --write-out '%{http_code}' 2>/dev/null); then
    rc=0
  else
    rc=$?
  fi
  rm -f -- "$cfg"
  # shellcheck disable=SC2034 # Public results consumed by sourcing callers.
  FMTG_API_RC=$rc
  # shellcheck disable=SC2034 # Public result consumed by sourcing callers.
  FMTG_API_HTTP=$code
  [ "$rc" -eq 0 ]
}

fmtg_error_once() { # <redacted-code>
  local code=$1 file current
  fmtg_safe_slug "$code" 80 || code=internal-error
  fmtg_prepare_state || return 1
  file="$FMTG_STATE/error.json"
  current=
  if fm_private_file_valid "$file" 600; then
    current=$(fm_private_read_file "$file" 600 | jq -r '.code // empty' 2>/dev/null || true)
  fi
  [ "$current" = "$code" ] && return 0
  jq -n --arg code "$code" --argjson at "$(date +%s)" \
    '{schema:"firstmate.telegram-error.v1",code:$code,recorded_at:$at}' \
    | fmtg_json_publish "$FMTG_STATE" error.json || return 1
  fm_wake_append check telegram-error "telegram-error $code" || return 1
  printf 'telegram-error %s\n' "$code"
}

fmtg_clear_error() {
  fm_private_file_valid "$FMTG_STATE/error.json" 600 || return 0
  rm -f -- "$FMTG_STATE/error.json" 2>/dev/null || true
}

fmtg_offset_read() {
  local file="$FMTG_STATE/offset" value
  if [ ! -e "$file" ] && [ ! -L "$file" ]; then
    printf '0\n'
    return 0
  fi
  value=$(fm_private_read_file "$file" 600) || return 1
  case "$value" in ''|*[!0-9]*) return 1 ;; esac
  printf '%s\n' "$value"
}

fmtg_offset_write() { # <next-update-id>
  case "$1" in ''|*[!0-9]*) return 1 ;; esac
  printf '%s\n' "$1" | fm_private_publish_stdin "$FMTG_STATE" offset 600
}

fmtg_queue_request() { # <request-id>; 0=new, 1=already queued, 2=error
  local request_id=$1 file raw queued updated status=0 wake_status=0
  fmtg_safe_slug "$request_id" 96 || return 2
  file="$FMTG_STATE/inbox/$request_id.json"
  fm_lock_acquire_wait "$FM_WAKE_QUEUE_LOCK"
  raw=$(fm_private_read_file "$file" 600) || status=2
  if [ "$status" -eq 0 ]; then
    queued=$(printf '%s' "$raw" | jq -r '.wake_queued // false' 2>/dev/null) || status=2
  fi
  if [ "$status" -eq 0 ] && [ "$queued" = true ]; then
    status=1
  elif [ "$status" -eq 0 ]; then
    fm_wake_append_locked_once check "$request_id" "telegram-request $request_id"
    wake_status=$?
    [ "$wake_status" -le 1 ] || status=2
    if [ "$status" -eq 0 ]; then
      updated=$(printf '%s' "$raw" | jq --argjson at "$(date +%s)" '.wake_queued=true | .wake_queued_at=$at') || status=2
      if [ "$status" -eq 0 ]; then
        printf '%s\n' "$updated" | fmtg_json_publish "$FMTG_STATE/inbox" "$request_id.json" || status=2
      fi
    fi
    if [ "$status" -eq 0 ] && [ "$wake_status" -eq 1 ]; then
      status=1
    fi
  fi
  fm_lock_release "$FM_WAKE_QUEUE_LOCK"
  return "$status"
}

fmtg_file_mtime() {
  if [ "$(uname)" = Darwin ]; then stat -f %m "$1" 2>/dev/null; else stat -c %Y "$1" 2>/dev/null; fi
}

fmtg_prune_dir() { # <dir> <now> <ttl>
  local dir=$1 now=$2 ttl=$3 file mtime
  [ -d "$dir" ] && [ ! -L "$dir" ] || return 0
  for file in "$dir"/*.json; do
    [ -e "$file" ] || continue
    fm_private_file_valid "$file" 600 || continue
    mtime=$(fmtg_file_mtime "$file") || continue
    [ $((now - mtime)) -gt "$ttl" ] || continue
    rm -f -- "$file" 2>/dev/null || true
  done
}

fmtg_prune() {
  local now file mtime request_id
  now=$(date +%s)
  fmtg_prepare_state || return 1
  fmtg_prune_dir "$FMTG_STATE/updates" "$now" "$FMTG_RETENTION_SECS"
  fmtg_prune_dir "$FMTG_STATE/outbound" "$now" "$FMTG_RETENTION_SECS"
  fmtg_prune_dir "$FMTG_STATE/rendered" "$now" "$FMTG_RETENTION_SECS"
  fmtg_prune_dir "$FMTG_STATE/approval-claims" "$now" "$FMTG_RETENTION_SECS"
  fmtg_prune_dir "$FMTG_STATE/approvals" "$now" "$FMTG_RETENTION_SECS"
  for file in "$FMTG_STATE/inbox"/*.json; do
    [ -e "$file" ] || continue
    fm_private_file_valid "$file" 600 || continue
    mtime=$(fmtg_file_mtime "$file") || continue
    [ $((now - mtime)) -gt "$FMTG_RETENTION_SECS" ] || continue
    request_id=$(basename "$file" .json)
    fmtg_error_once request-retention-expired >/dev/null || true
    rm -f -- "$file" 2>/dev/null || true
    fmtg_safe_slug "$request_id" 96 || true
  done
}

fmtg_approval_binding() { # <approval-id> <reply-message-id> <request-id>
  local approval_id=$1 reply_message_id=$2 request_id=$3 file raw now status expected expires claim rc
  FMTG_APPROVAL_DECISION=
  fmtg_safe_slug "$approval_id" 96 || return 1
  case "$reply_message_id" in ''|*[!0-9]*) return 1 ;; esac
  file="$FMTG_STATE/approvals/$approval_id.json"
  raw=$(fm_private_read_file "$file" 600) || return 1
  status=$(printf '%s' "$raw" | jq -r '.status // empty') || return 1
  expected=$(printf '%s' "$raw" | jq -r '.telegram_message_id // empty') || return 1
  expires=$(printf '%s' "$raw" | jq -r '.expires_at // 0') || return 1
  now=$(date +%s)
  [ "$status" = pending ] && [ "$expected" = "$reply_message_id" ] && [ "$expires" -ge "$now" ] || return 1
  case "$FMTG_INBOUND_TEXT" in
    "/approve $approval_id") FMTG_APPROVAL_DECISION=approve ;;
    "/deny $approval_id") FMTG_APPROVAL_DECISION=deny ;;
    *) return 1 ;;
  esac
  claim=$(jq -n --arg approval_id "$approval_id" --arg request_id "$request_id" \
    --arg decision "$FMTG_APPROVAL_DECISION" --argjson at "$now" \
    '{schema:"firstmate.telegram-approval-claim.v1",approval_id:$approval_id,request_id:$request_id,decision:$decision,claimed_at:$at}')
  printf '%s\n' "$claim" | fmtg_json_publish_once "$FMTG_STATE/approval-claims" "$approval_id.json"
  rc=$?
  [ "$rc" -eq 0 ]
}
