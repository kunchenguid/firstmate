#!/usr/bin/env bash
# Shared config and security helpers for Telegram mode (fm-telegram-send.sh,
# fm-telegram-poll.sh, fm-telegram-respond.sh). Telegram mode is opt-in: a home
# places non-empty FM_TELEGRAM_BOT_TOKEN and FM_TELEGRAM_CHAT_ID in its gitignored
# .env (mode 0600 recommended). Until then every client is a hard no-op.
#
# This file is sourced, never executed. It defines:
#   fmt_env_get <key> <file>     - read one KEY=VALUE from a .env-style file
#   fmt_load_config              - resolve FMT_* runtime settings
#   fmt_mode_enabled             - 0 when configured and not killed by config/off
#   fmt_poll_shim_content        - expected state/telegram-watch.check.sh body
#   fmt_poll_shim_valid          - identity check for the generated poll shim
#   fmt_audit_append <kind> ...  - append one audit line to state/telegram-audit.log
#   fmt_offset_get / fmt_offset_set - durable getUpdates offset
#   fmt_curl_url_config <url>    - 0600 curl config file keeping the URL (and
#                                  the token embedded in it) out of curl argv
#   fmt_rate_allow <bucket>      - inbound rate limit (per home)
#   fmt_dedupe_seen / fmt_dedupe_mark - command dedupe window
#   fmt_parse_command <text>     - closed grammar -> verb + args
#   fmt_fresh_enough <epoch>     - approval freshness window
#   fmt_notified_pr_record / fmt_notified_pr_seen - PR URL merge authority
#   fmt_notified_pr_recovery_record - fallback evidence after a confirmed send
#   fmt_secretish <text>         - refuse outbound that looks like secrets
#   fmt_afk_active               - state/.afk present
# Reuses the private-artifact publisher from fm-x-lib.sh when available.
# Callers must have FM_HOME set before calling fmt_load_config.

# shellcheck source=bin/fm-x-lib.sh
if [ -z "${FMX_PRIVATE_ARTIFACT_READY:-}" ]; then
  _fmt_lib_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
  # shellcheck disable=SC1091
  . "$_fmt_lib_dir/fm-x-lib.sh"
  FMX_PRIVATE_ARTIFACT_READY=1
fi

fmt_env_get() {
  fmx_env_get "$1" "$2"
}

fmt_poll_shim_content() {
  local home=$1 root=$2
  printf '%s\n' \
    '#!/usr/bin/env bash' \
    '# Auto-generated by fm-bootstrap.sh - Telegram mode poll shim.' \
    '# The watcher validates these bytes, then dispatches the trusted poll script.' \
    "export FM_HOME=$(printf '%q' "$home")" \
    "exec $(printf '%q' "$root/bin/fm-telegram-poll.sh")"
}

fmt_poll_shim_valid() {
  local file=$1 home=$2 root=$3
  fmx_poll_shim_private_identity_valid "$file" || return 1
  cmp -s "$file" <(fmt_poll_shim_content "$home" "$root")
}

# Resolve Telegram settings into FMT_TOKEN, FMT_CHAT_ID, FMT_ALLOW_FROM,
# FMT_API, FMT_DRY, FMT_ALWAYS_NOTIFY, FMT_FRESHNESS, FMT_RATE_MAX,
# FMT_RATE_WINDOW, FMT_DEDUPE_WINDOW, and FMT_KILL. Explicit environment
# variables always win over the .env file.
fmt_load_config() {
  local env_file dry always kill_file kill_raw fromraw freshrate rate_max rate_win dedupe_win
  env_file="${FM_TELEGRAM_ENV_FILE:-$FM_HOME/.env}"

  if [ -n "${FM_TELEGRAM_BOT_TOKEN+x}" ]; then
    FMT_TOKEN=${FM_TELEGRAM_BOT_TOKEN-}
  else
    FMT_TOKEN=$(fmt_env_get FM_TELEGRAM_BOT_TOKEN "$env_file")
  fi
  if [ -n "${FM_TELEGRAM_CHAT_ID+x}" ]; then
    FMT_CHAT_ID=${FM_TELEGRAM_CHAT_ID-}
  else
    FMT_CHAT_ID=$(fmt_env_get FM_TELEGRAM_CHAT_ID "$env_file")
  fi
  if [ -n "${FM_TELEGRAM_ALLOW_FROM+x}" ]; then
    fromraw=${FM_TELEGRAM_ALLOW_FROM-}
  else
    fromraw=$(fmt_env_get FM_TELEGRAM_ALLOW_FROM "$env_file")
  fi
  # Default allowlist is the chat id (1:1 private chat with the captain).
  if [ -z "$fromraw" ]; then
    fromraw=$FMT_CHAT_ID
  fi
  # shellcheck disable=SC2034
  FMT_ALLOW_FROM=$fromraw

  if [ -n "${FM_TELEGRAM_API_URL+x}" ]; then
    FMT_API=${FM_TELEGRAM_API_URL-}
  else
    FMT_API=$(fmt_env_get FM_TELEGRAM_API_URL "$env_file")
  fi
  [ -n "$FMT_API" ] || FMT_API="https://api.telegram.org"
  FMT_API=${FMT_API%/}

  if [ -n "${FM_TELEGRAM_DRY_RUN+x}" ]; then
    dry=${FM_TELEGRAM_DRY_RUN-}
  else
    dry=$(fmt_env_get FM_TELEGRAM_DRY_RUN "$env_file")
  fi
  # shellcheck disable=SC2034
  case "$(printf '%s' "$dry" | tr '[:upper:]' '[:lower:]')" in
    ''|0|false|no|off) FMT_DRY="" ;;
    *) FMT_DRY=1 ;;
  esac

  if [ -n "${FM_TELEGRAM_ALWAYS_NOTIFY+x}" ]; then
    always=${FM_TELEGRAM_ALWAYS_NOTIFY-}
  else
    always=$(fmt_env_get FM_TELEGRAM_ALWAYS_NOTIFY "$env_file")
  fi
  # shellcheck disable=SC2034
  case "$(printf '%s' "$always" | tr '[:upper:]' '[:lower:]')" in
    1|true|yes|on) FMT_ALWAYS_NOTIFY=1 ;;
    *) FMT_ALWAYS_NOTIFY="" ;;
  esac

  if [ -n "${FM_TELEGRAM_FRESHNESS_SECS+x}" ]; then
    freshrate=${FM_TELEGRAM_FRESHNESS_SECS-}
  else
    freshrate=$(fmt_env_get FM_TELEGRAM_FRESHNESS_SECS "$env_file")
  fi
  case "$freshrate" in ''|*[!0-9]*) freshrate=900 ;; esac
  # shellcheck disable=SC2034
  FMT_FRESHNESS=$freshrate

  if [ -n "${FM_TELEGRAM_RATE_MAX+x}" ]; then
    rate_max=${FM_TELEGRAM_RATE_MAX-}
  else
    rate_max=$(fmt_env_get FM_TELEGRAM_RATE_MAX "$env_file")
  fi
  case "$rate_max" in ''|*[!0-9]*) rate_max=10 ;; esac
  [ "$rate_max" -ge 1 ] 2>/dev/null || rate_max=10
  # shellcheck disable=SC2034
  FMT_RATE_MAX=$rate_max

  if [ -n "${FM_TELEGRAM_RATE_WINDOW_SECS+x}" ]; then
    rate_win=${FM_TELEGRAM_RATE_WINDOW_SECS-}
  else
    rate_win=$(fmt_env_get FM_TELEGRAM_RATE_WINDOW_SECS "$env_file")
  fi
  case "$rate_win" in ''|*[!0-9]*) rate_win=60 ;; esac
  [ "$rate_win" -ge 1 ] 2>/dev/null || rate_win=60
  # shellcheck disable=SC2034
  FMT_RATE_WINDOW=$rate_win

  if [ -n "${FM_TELEGRAM_DEDUPE_WINDOW_SECS+x}" ]; then
    dedupe_win=${FM_TELEGRAM_DEDUPE_WINDOW_SECS-}
  else
    dedupe_win=$(fmt_env_get FM_TELEGRAM_DEDUPE_WINDOW_SECS "$env_file")
  fi
  case "$dedupe_win" in ''|*[!0-9]*) dedupe_win=120 ;; esac
  [ "$dedupe_win" -ge 1 ] 2>/dev/null || dedupe_win=120
  # shellcheck disable=SC2034
  FMT_DEDUPE_WINDOW=$dedupe_win

  # Kill switch: config/telegram-mode containing a lone "off" disables the feature
  # even when tokens are present. Absent or any other content leaves presence-gated
  # .env activation in charge.
  FMT_KILL=""
  kill_file="${FM_CONFIG_OVERRIDE:-$FM_HOME/config}/telegram-mode"
  if [ -f "$kill_file" ] && [ ! -L "$kill_file" ]; then
    kill_raw=$(tr -d '[:space:]' < "$kill_file" 2>/dev/null | tr '[:upper:]' '[:lower:]') || kill_raw=
    case "$kill_raw" in
      off) FMT_KILL=1 ;;
    esac
  fi
}

# True (exit 0) when token+chat are set and the kill switch is not engaged.
fmt_mode_enabled() {
  [ -n "${FMT_TOKEN:-}" ] && [ -n "${FMT_CHAT_ID:-}" ] && [ -z "${FMT_KILL:-}" ]
}

fmt_afk_active() {
  local state=${FM_STATE_OVERRIDE:-$FM_HOME/state}
  [ -e "$state/.afk" ]
}

# Append-only audit log. Lines are tab-separated:
#   epoch  kind  verdict  detail...
# Never writes token material. Best-effort; never fails the caller.
fmt_audit_append() {
  local state=${FM_STATE_OVERRIDE:-$FM_HOME/state}
  local kind=$1
  shift
  local epoch detail line
  epoch=$(date +%s 2>/dev/null) || epoch=0
  detail=$(printf '%s' "$*" | tr '\t\n\r' '   ')
  # Strip anything that looks like the configured token if present.
  if [ -n "${FMT_TOKEN:-}" ]; then
    detail=${detail//$FMT_TOKEN/[redacted-token]}
  fi
  line=$(printf '%s\t%s\t%s' "$epoch" "$kind" "$detail")
  # Keep state private (700) so offset/inbox publishers can use the same dir.
  if [ -e "$state" ] || [ -L "$state" ]; then
    [ -d "$state" ] && [ ! -L "$state" ] || return 0
  else
    (umask 077; mkdir -p "$state" 2>/dev/null) || return 0
  fi
  chmod 700 "$state" 2>/dev/null || true
  # Append under umask so a new file is 0600; never follow a symlink.
  if [ -L "$state/telegram-audit.log" ]; then
    return 0
  fi
  (umask 077; printf '%s\n' "$line" >> "$state/telegram-audit.log") 2>/dev/null || true
  chmod 600 "$state/telegram-audit.log" 2>/dev/null || true
}

fmt_offset_path() {
  printf '%s\n' "${FM_STATE_OVERRIDE:-$FM_HOME/state}/telegram-offset"
}

fmt_offset_get() {
  local f
  f=$(fmt_offset_path)
  if [ -f "$f" ] && [ ! -L "$f" ]; then
    tr -d '[:space:]' < "$f" 2>/dev/null || true
  fi
}

fmt_offset_set() {
  local next=$1 state f
  case "$next" in
    ''|*[!0-9]*) return 1 ;;
  esac
  state=${FM_STATE_OVERRIDE:-$FM_HOME/state}
  f="$state/telegram-offset"
  printf '%s\n' "$next" | fmx_private_artifact_publish_stdin "$state" "telegram-offset" 600
}

# Write the request URL to a 0600 curl config file so the bot token embedded
# in the URL path never appears in curl's argv (visible to local users via ps).
# Prints the file path; the caller removes it.
fmt_curl_url_config() {
  local url=$1 file
  case "$url" in
    *$'\n'*|*$'\r'*|*'"'*|*\\*) return 1 ;;
  esac
  file=$(umask 077; mktemp "${TMPDIR:-/tmp}/fm-telegram-url.XXXXXX") || return 1
  chmod 600 "$file" 2>/dev/null || { rm -f "$file"; return 1; }
  printf 'url = "%s"\n' "$url" > "$file" || { rm -f "$file"; return 1; }
  printf '%s\n' "$file"
}

# True when sender id is in the allowlist (comma/space separated).
fmt_sender_allowed() {
  local sender=$1 entry list
  [ -n "$sender" ] || return 1
  list=${FMT_ALLOW_FROM:-}
  list=$(printf '%s' "$list" | tr ',' ' ')
  for entry in $list; do
    [ "$entry" = "$sender" ] && return 0
  done
  return 1
}

# True when chat id matches the configured private chat.
fmt_chat_allowed() {
  local chat=$1
  [ -n "$chat" ] && [ "$chat" = "${FMT_CHAT_ID:-}" ]
}

# Rate limit: at most FMT_RATE_MAX events of <bucket> per FMT_RATE_WINDOW seconds.
# Returns 0 when allowed (and records the event), 1 when over limit.
fmt_rate_allow() {
  local bucket=$1
  local state now file base line kept count cutoff rate_data
  state=${FM_STATE_OVERRIDE:-$FM_HOME/state}
  case "$bucket" in
    ''|.*|*/*|*[!A-Za-z0-9._-]*) return 1 ;;
  esac
  now=$(date +%s 2>/dev/null) || now=0
  cutoff=$((now - ${FMT_RATE_WINDOW:-60}))
  base="telegram-rate-$bucket.log"
  file="$state/$base"
  if [ -e "$state" ] || [ -L "$state" ]; then
    [ -d "$state" ] && [ ! -L "$state" ] || return 1
  else
    (umask 077; mkdir -p "$state" 2>/dev/null) || return 1
  fi
  chmod 700 "$state" 2>/dev/null || true
  if [ -L "$file" ]; then
    return 1
  fi
  kept=
  count=0
  if [ -e "$file" ] || [ -L "$file" ]; then
    fmx_private_artifact_file_valid "$state" "$base" 600 || return 1
    rate_data=$(cat -- "$file" 2>/dev/null) || return 1
    while IFS= read -r line || [ -n "$line" ]; do
      case "$line" in
        '') continue ;;
        *[!0-9]*) return 1 ;;
      esac
      if [ "$line" -ge "$cutoff" ] 2>/dev/null; then
        kept="${kept}${line}"$'\n'
        count=$((count + 1))
      fi
    done <<EOF
$rate_data
EOF
  fi
  if [ "$count" -ge "${FMT_RATE_MAX:-10}" ]; then
    printf '%s' "$kept" | fmx_private_artifact_publish_stdin "$state" "$base" 600 >/dev/null 2>&1 || true
    return 1
  fi
  kept="${kept}${now}"$'\n'
  printf '%s' "$kept" | fmx_private_artifact_publish_stdin "$state" "$base" 600 >/dev/null 2>&1 || return 1
  return 0
}

# Dedupe: true (0) if <fingerprint> was already seen within the dedupe window.
fmt_dedupe_seen() {
  local fingerprint=$1
  local state now file line ts fp cutoff
  state=${FM_STATE_OVERRIDE:-$FM_HOME/state}
  now=$(date +%s 2>/dev/null) || now=0
  cutoff=$((now - ${FMT_DEDUPE_WINDOW:-120}))
  file="$state/telegram-dedupe.log"
  [ -f "$file" ] && [ ! -L "$file" ] || return 1
  while IFS=$'\t' read -r ts fp || [ -n "$ts" ]; do
    case "$ts" in
      ''|*[!0-9]*) continue ;;
    esac
    [ "$ts" -ge "$cutoff" ] 2>/dev/null || continue
    [ "$fp" = "$fingerprint" ] && return 0
  done < "$file"
  return 1
}

# Marking also rewrites the log with only in-window entries so it stays
# bounded (mirrors fmt_rate_allow's prune-on-write).
fmt_dedupe_mark() {
  local fingerprint=$1
  local state now file cutoff ts fp kept
  state=${FM_STATE_OVERRIDE:-$FM_HOME/state}
  now=$(date +%s 2>/dev/null) || now=0
  cutoff=$((now - ${FMT_DEDUPE_WINDOW:-120}))
  file="$state/telegram-dedupe.log"
  if [ -e "$state" ] || [ -L "$state" ]; then
    [ -d "$state" ] && [ ! -L "$state" ] || return 0
  else
    (umask 077; mkdir -p "$state" 2>/dev/null) || return 0
  fi
  chmod 700 "$state" 2>/dev/null || true
  if [ -L "$file" ]; then
    return 0
  fi
  kept=
  if [ -f "$file" ]; then
    while IFS=$'\t' read -r ts fp || [ -n "$ts" ]; do
      case "$ts" in
        ''|*[!0-9]*) continue ;;
      esac
      [ "$ts" -ge "$cutoff" ] 2>/dev/null || continue
      kept="${kept}${ts}"$'\t'"${fp}"$'\n'
    done < "$file"
  fi
  kept="${kept}${now}"$'\t'"${fingerprint}"$'\n'
  (umask 077; printf '%s' "$kept" > "$file") 2>/dev/null || true
  chmod 600 "$file" 2>/dev/null || true
}

# Closed Stage-2 grammar. Prints "verb\targ1\targ2..." or fails.
# Verbs: status | approve | deny | merge | refuse
fmt_parse_command() {
  local text=$1
  local norm verb rest key reason url
  # Collapse whitespace, strip leading slash bot commands (/status@bot -> status).
  norm=$(printf '%s' "$text" | tr '\n\r\t' '   ')
  norm=${norm#"${norm%%[![:space:]]*}"}
  norm=${norm%"${norm##*[![:space:]]}"}
  # Strip optional leading /
  case "$norm" in
    /*) norm=${norm#/} ;;
  esac
  # Drop @botname suffix on the first token only.
  verb=${norm%% *}
  rest=${norm#"$verb"}
  rest=${rest#"${rest%%[![:space:]]*}"}
  case "$verb" in
    *@*) verb=${verb%%@*} ;;
  esac
  verb=$(printf '%s' "$verb" | tr '[:upper:]' '[:lower:]')

  case "$verb" in
    status)
      [ -z "$rest" ] || { printf 'refuse\tunknown-args\n'; return 1; }
      printf 'status\n'
      return 0
      ;;
    approve)
      key=${rest%% *}
      [ -n "$key" ] || { printf 'refuse\tmissing-key\n'; return 1; }
      case "$key" in
        *[!A-Za-z0-9._-]*) printf 'refuse\tbad-key\n'; return 1 ;;
      esac
      [ "$key" = "$rest" ] || { printf 'refuse\textra-args\n'; return 1; }
      printf 'approve\t%s\n' "$key"
      return 0
      ;;
    deny)
      key=${rest%% *}
      [ -n "$key" ] || { printf 'refuse\tmissing-key\n'; return 1; }
      case "$key" in
        *[!A-Za-z0-9._-]*) printf 'refuse\tbad-key\n'; return 1 ;;
      esac
      if [ "$key" = "$rest" ]; then
        reason=
      else
        reason=${rest#"$key"}
        reason=${reason#"${reason%%[![:space:]]*}"}
      fi
      printf 'deny\t%s\t%s\n' "$key" "$reason"
      return 0
      ;;
    merge)
      url=$rest
      [ -n "$url" ] || { printf 'refuse\tmissing-pr\n'; return 1; }
      url=${url%%[[:space:]]*}
      while [ -n "$url" ]; do
        last=$(printf '%s' "$url" | tail -c 1)
        case "$last" in
          ')'|'>'|'.'|','|';') url=${url%?} ;;
          *) break ;;
        esac
      done
      if fmt_github_pr_parts "$url" >/dev/null; then
        printf 'merge\t%s\n' "$url"
        return 0
      fi
      printf 'refuse\tunnamed-or-invalid-pr\n'
      return 1
      ;;
    *)
      printf 'refuse\tunknown-command\n'
      return 1
      ;;
  esac
}

fmt_github_pr_parts() {
  local url=$1 rest owner repo marker number
  case "$url" in
    https://github.com/*/*/pull/*) ;;
    *) return 1 ;;
  esac
  rest=${url#https://github.com/}
  owner=${rest%%/*}
  rest=${rest#*/}
  repo=${rest%%/*}
  rest=${rest#*/}
  marker=${rest%%/*}
  number=${rest#*/}
  [ -n "$owner" ] && [ -n "$repo" ] && [ "$marker" = pull ] || return 1
  case "$number" in
    ''|*[!0-9]*) return 1 ;;
  esac
  printf '%s\t%s\t%s\n' "$owner" "$repo" "$number"
}

# Approvals older than FMT_FRESHNESS seconds are not executed.
fmt_fresh_enough() {
  local msg_epoch=$1 now age
  case "$msg_epoch" in
    ''|*[!0-9]*) return 1 ;;
  esac
  now=$(date +%s 2>/dev/null) || now=0
  age=$((now - msg_epoch))
  [ "$age" -ge 0 ] 2>/dev/null || return 1
  [ "$age" -le "${FMT_FRESHNESS:-900}" ]
}

# Record a full PR URL that was outbound-notified to the Telegram chat.
fmt_notified_pr_record() {
  local url=$1
  local state file
  state=${FM_STATE_OVERRIDE:-$FM_HOME/state}
  fmt_github_pr_parts "$url" >/dev/null || return 1
  [ -n "${FMT_CHAT_ID:-}" ] || return 1
  file="$state/telegram-notified-prs.log"
  if [ -e "$state" ] || [ -L "$state" ]; then
    [ -d "$state" ] && [ ! -L "$state" ] || return 1
  else
    (umask 077; mkdir -p "$state" 2>/dev/null) || return 1
  fi
  chmod 700 "$state" 2>/dev/null || true
  if [ -L "$file" ]; then
    return 1
  fi
  (umask 077; printf '%s\t%s\t%s\n' "$(date +%s 2>/dev/null || echo 0)" "$FMT_CHAT_ID" "$url" >> "$file") 2>/dev/null || return 1
  chmod 600 "$file" 2>/dev/null || true
  return 0
}

fmt_notified_pr_recovery_record() {
  local url=$1 ordinal=$2
  local state dir base epoch
  state=${FM_STATE_OVERRIDE:-$FM_HOME/state}
  fmt_github_pr_parts "$url" >/dev/null || return 1
  [ -n "${FMT_CHAT_ID:-}" ] || return 1
  case "$ordinal" in
    ''|*[!0-9]*) return 1 ;;
  esac
  epoch=$(date +%s 2>/dev/null || echo 0)
  dir="$state/telegram-notified-pr-recovery"
  base="authority-$epoch-$$-$ordinal.tsv"
  printf '%s\t%s\t%s\n' "$epoch" "$FMT_CHAT_ID" "$url" \
    | fmx_private_artifact_publish_stdin "$dir" "$base" 600
}

fmt_notified_pr_seen() {
  local url=$1
  local state file recovery f base ts chat recorded
  state=${FM_STATE_OVERRIDE:-$FM_HOME/state}
  file="$state/telegram-notified-prs.log"
  if [ -f "$file" ] && [ ! -L "$file" ]; then
    while IFS=$'\t' read -r ts chat recorded || [ -n "$ts" ]; do
      [ "$chat" = "${FMT_CHAT_ID:-}" ] && [ "$recorded" = "$url" ] && return 0
    done < "$file"
  fi
  recovery="$state/telegram-notified-pr-recovery"
  for f in "$recovery"/*.tsv; do
    [ -f "$f" ] || continue
    base=${f##*/}
    fmx_private_artifact_file_valid "$recovery" "$base" 600 || continue
    IFS=$'\t' read -r ts chat recorded < "$f" || continue
    [ "$chat" = "${FMT_CHAT_ID:-}" ] && [ "$recorded" = "$url" ] && return 0
  done
  return 1
}

# Heuristic: refuse to send text that looks like secrets/credentials.
# Returns 0 when the text looks secretish (should NOT be sent).
fmt_secretish() {
  local text=$1
  case "$text" in
    *FM_TELEGRAM_BOT_TOKEN=*|*FMX_PAIRING_TOKEN=*|*Authorization:\ Bearer*|*BEGIN\ *PRIVATE\ KEY*)
      return 0
      ;;
  esac
  # Long base64-ish blob after a keyword.
  if printf '%s' "$text" | grep -Eiq \
    '(password|passwd|secret|api[_-]?key|token|credential)\s*[:=]\s*\S{12,}'; then
    return 0
  fi
  # Never echo the live bot token.
  if [ -n "${FMT_TOKEN:-}" ] && [ "${#FMT_TOKEN}" -ge 8 ]; then
    case "$text" in
      *"$FMT_TOKEN"*) return 0 ;;
    esac
  fi
  return 1
}

# Extract GitHub PR URLs from free text (one per line).
fmt_extract_pr_urls() {
  local text=$1
  printf '%s' "$text" \
    | grep -Eo 'https://github\.com/[^[:space:]/]+/[^[:space:]/]+/pull/[0-9]+' \
    | sort -u || true
}

# Build a short status summary from local fleet records (no network).
fmt_status_summary() {
  local state data backlog n meta f open key verb note decisions blockers
  state=${FM_STATE_OVERRIDE:-$FM_HOME/state}
  data=${FM_DATA_OVERRIDE:-$FM_HOME/data}
  backlog="$data/backlog.md"
  printf 'Current overview\n'
  if [ -e "$state/.afk" ]; then
    printf 'You are marked as away.\n'
  else
    printf 'You are marked as present.\n'
  fi
  n=0
  for meta in "$state"/*.meta; do
    [ -f "$meta" ] || continue
    [ "$(fmx_meta_get "$meta" kind)" = secondmate ] && continue
    n=$((n + 1))
  done
  if [ "$n" -eq 0 ]; then
    printf 'No work under way.\n'
  elif [ "$n" -eq 1 ]; then
    printf 'Work under way: 1 item.\n'
  else
    printf 'Work under way: %s items.\n' "$n"
  fi
  decisions=0
  blockers=0
  # shellcheck source=bin/fm-classify-lib.sh disable=SC1091
  . "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/fm-classify-lib.sh"
  for f in "$state"/*.status; do
    [ -f "$f" ] || continue
    open=$(status_open_decisions "$f")
    [ -n "$open" ] || continue
    while IFS=$'\t' read -r key verb note || [ -n "$key" ]; do
      case "$verb" in
        needs-decision) decisions=$((decisions + 1)) ;;
        blocked) blockers=$((blockers + 1)) ;;
      esac
    done <<EOF
$open
EOF
  done
  [ "$decisions" -eq 0 ] || printf 'Decisions awaiting your input: %s.\n' "$decisions"
  [ "$blockers" -eq 0 ] || printf 'Reported blockers awaiting attention: %s.\n' "$blockers"
  if [ -f "$backlog" ]; then
    printf 'More planned work is available locally.\n'
  else
    printf 'No additional planned work is recorded.\n'
  fi
}

# Scan all state/*.status for an open decision key. Prints "task_id\tverb\tnote" or nothing.
fmt_open_decision_lookup() {
  local key=$1
  local state f id open line k verb note
  state=${FM_STATE_OVERRIDE:-$FM_HOME/state}
  # shellcheck source=bin/fm-classify-lib.sh disable=SC1091
  . "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/fm-classify-lib.sh"
  for f in "$state"/*.status; do
    [ -f "$f" ] || continue
    id=$(basename "$f" .status)
    open=$(status_open_decisions "$f")
    [ -n "$open" ] || continue
    while IFS=$'\t' read -r k verb note || [ -n "$k" ]; do
      [ -n "$k" ] || continue
      if [ "$k" = "$key" ]; then
        printf '%s\t%s\t%s\n' "$id" "$verb" "$note"
        return 0
      fi
    done <<EOF
$open
EOF
  done
  return 1
}

# Write a durable action record for firstmate to apply (approve/deny/merge).
# Prints the action file path on success.
fmt_action_write() {
  local update_id=$1 action=$2
  shift 2
  local state dir payload
  state=${FM_STATE_OVERRIDE:-$FM_HOME/state}
  dir="$state/telegram-actions"
  case "$update_id" in
    ''|.*|*/*|*[!A-Za-z0-9._-]*) return 1 ;;
  esac
  payload=$(jq -cn \
    --arg id "$update_id" \
    --arg action "$action" \
    --argjson args "$(printf '%s\n' "$@" | jq -R . | jq -s -c .)" \
    --arg ts "$(date +%s 2>/dev/null || echo 0)" \
    '{update_id:$id, action:$action, args:$args, recorded_at:($ts|tonumber)}' 2>/dev/null) || return 1
  printf '%s\n' "$payload" | fmx_private_artifact_publish_stdin "$dir" "$update_id.json" 600 || return 1
  printf '%s\n' "$dir/$update_id.json"
}
