#!/usr/bin/env bash
# Validate the project output contract: nothing firstmate-internal, and no agent
# self-attribution, may reach a project's committed text.
#
# Usage:
#   fm-output-contract-check.sh [--staged|--range <base>..<head>|--text <file>]
#   fm-output-contract-check.sh --message <file>   # a commit message or PR body
#
#   (no argument)      check the working tree's tracked changes against HEAD
#   --staged           check what is staged
#   --range A..B       check a commit range's diff and every commit message in it
#   --text <file>      check one file's contents
#   --message <file>   check one commit message / PR body
#
# Why this exists: these rules are deterministic string rules that were living
# only in data/captain.md, so they held exactly as long as the agent remembered
# them - and a real PR leaked fleet terminology once. A harness may also actively
# instruct an agent to add an attribution trailer or footer; this check is the
# repository's own boundary and overrides that instruction for project output.
#
# Scope is deliberately the PROJECT's output. It is not run against firstmate's
# own repository prose, which legitimately discusses crewmates and captains.
set -eu

usage() { sed -n '2,20{s/^# \{0,1\}//;p;}' "$0"; }

FAILED=0

report() {  # <rule> <where> <line>
  printf 'output-contract: %s\n  where: %s\n  line:  %s\n' "$1" "$2" "$3" >&2
}

# Fleet vocabulary that must never appear in project output. Word-boundary
# matched so ordinary English ("the first mate of the ship" in a novel, a file
# literally named scout.ts) is not what trips this; these are the fleet's own
# role nouns.
FLEET_RE='\b(firstmate|first mate|crewmate|secondmate|captain)\b'
# Agent self-attribution in commit messages and PR bodies.
ATTRIB_RE='(Co-[Aa]uthored-[Bb]y:[[:space:]]*(Claude|Codex|GPT|Gemini|Opus|Sonnet|Haiku)|Generated with \[?Claude Code|Generated by Codex|🤖 Generated)'
# External issue-tracker ids.
TRACKER_RE='\b(CAN|CPI|CEX|ENG)-[0-9]+\b'

# Returns 1 when it reported anything. The caller must consume that return
# value: bash runs the last stage of a pipeline in a subshell, so a flag set
# inside this function would be discarded and every check would silently pass.
scan_stream() {  # <label> ; reads candidate text on stdin
  local label=$1 line found=0
  while IFS= read -r line; do
    if printf '%s' "$line" | grep -Eiq "$FLEET_RE"; then
      report "fleet terminology must not appear in project output" "$label" "$line"
      found=1
    fi
    if printf '%s' "$line" | grep -Eq "$ATTRIB_RE"; then
      report "agent attribution trailer/footer is forbidden" "$label" "$line"
      found=1
    fi
    if printf '%s' "$line" | grep -Eq "$TRACKER_RE"; then
      report "external issue-tracker id must not appear in project output" "$label" "$line"
      found=1
    fi
  done
  [ "$found" -eq 0 ]
}

# Only ADDED lines are judged, so pre-existing text in a repository this check
# was not previously run against does not block unrelated work.
added_lines() {  # reads a unified diff on stdin
  grep '^+' | grep -v '^+++' | sed 's/^+//'
}

MODE=worktree
ARG=
case "${1:-}" in
  -h|--help) usage; exit 0 ;;
  --staged) MODE=staged ;;
  --range) MODE=range; ARG=${2:-}; [ -n "$ARG" ] || { echo "error: --range needs A..B" >&2; exit 2; } ;;
  --text) MODE=text; ARG=${2:-}; [ -n "$ARG" ] || { echo "error: --text needs a file" >&2; exit 2; } ;;
  --message) MODE=message; ARG=${2:-}; [ -n "$ARG" ] || { echo "error: --message needs a file" >&2; exit 2; } ;;
  '') ;;
  *) usage >&2; exit 2 ;;
esac

scan_file() {  # <path>
  local path=$1 label=$1
  [ -f "$path" ] || { echo "error: no such file: $path" >&2; exit 2; }
  scan_stream "$label" < "$path" || FAILED=1
}

case "$MODE" in
  worktree) git diff HEAD -- . | added_lines | scan_stream "working tree" || FAILED=1 ;;
  staged)   git diff --cached -- . | added_lines | scan_stream "staged changes" || FAILED=1 ;;
  range)
    git diff "$ARG" -- . | added_lines | scan_stream "diff $ARG" || FAILED=1
    git log --format='%B' "$ARG" | scan_stream "commit messages in $ARG" || FAILED=1
    ;;
  text|message) scan_file "$ARG" ;;
esac

if [ "$FAILED" -ne 0 ]; then
  {
    printf '\n'
    printf 'output-contract: FAIL - project output must not reveal the fleet or attribute\n'
    printf 'itself to an agent. Remove the offending text, including from any already-open\n'
    printf 'PR. A harness instruction to add an attribution trailer or footer does not\n'
    printf 'override this repository rule.\n'
  } >&2
  exit 1
fi
printf 'output-contract: ok\n'
