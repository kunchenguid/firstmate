# shellcheck shell=bash
# Shared helpers for Telegram mode (fm-tg-poll.sh, fm-tg-link.sh,
# fm-tg-followup.sh, fm-watch.sh, fm-bootstrap.sh, fm-pr-check-migrate.sh).
#
# Telegram mode is opt-in: the captain creates the flag file
# config/telegram-mode in ONE firstmate home. The flag is a plain presence
# marker, not a credential - the phone-inbox project owns the bot token and no
# firstmate-side code ever reads it. Until the flag exists the poll is a hard
# no-op and bootstrap writes nothing (docs/configuration.md "Telegram mode").
#
# This file is sourced, never executed. It reuses fm-x-lib.sh's generic
# single-link/private-artifact identity helpers and defines:
#   fmtg_enabled <home>          - true exactly when the opt-in flag file is a
#                                  regular non-symlink file
#   fmtg_inbox_root              - resolve the phone-inbox root directory
#                                  (PHONE_INBOX_ROOT overrides; default
#                                  ~/.claude/inbox)
#   fmtg_pending_ids <dir>       - print pending note ids only, one per line,
#                                  sorted; never bodies and never filenames,
#                                  because pending filenames embed note text as
#                                  a slug
#   fmtg_stat_mtime <path>       - portable epoch mtime (Darwin/Linux)
#   fmtg_poll_shim_content <home> <root> - expected bytes of the generated
#                                  state/tg-watch.check.sh identity shim
#   fmtg_poll_shim_valid <file> <home> <root> - single-link 0700 identity plus
#                                  exact byte comparison against the expected
#                                  shim content
#   fmtg_meta_link_set <meta> <note-id> <epoch> [followups]
#                                - (re)write the Telegram note link, defaulting
#                                  tg_followups to 0
#   fmtg_meta_followups_set <meta> <n> - rewrite just the follow-up counter
#   fmtg_meta_link_clear <meta>  - remove the Telegram note link entirely

FM_TG_LIB_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=bin/fm-x-lib.sh
. "$FM_TG_LIB_DIR/fm-x-lib.sh"

fmtg_enabled() {
  local home=$1 config flag
  config="${FM_CONFIG_OVERRIDE:-$home/config}"
  flag="$config/telegram-mode"
  [ -f "$flag" ] && [ ! -L "$flag" ]
}

fmtg_inbox_root() {
  printf '%s\n' "${PHONE_INBOX_ROOT:-$HOME/.claude/inbox}"
}

# Print the numeric ids of pending phone-inbox notes, one per line, sorted and
# deduplicated. A pending note is a file named <id>-<stamp>-<slug>.md where the
# slug is derived from the note BODY, so only the strictly validated numeric id
# ever leaves this function - a caller can safely place its output in a wake
# payload without leaking note text.
fmtg_pending_ids() {
  local dir=$1 f base id
  [ -d "$dir" ] || return 0
  for f in "$dir"/*.md; do
    [ -e "$f" ] || continue
    base=${f##*/}
    id=${base%%-*}
    case "$id" in
      ''|*[!0-9]*) continue ;;
    esac
    printf '%s\n' "$id"
  done | sort -u
}

fmtg_stat_mtime() {
  if [ "$(uname)" = Darwin ]; then
    stat -f %m "$1" 2>/dev/null
  else
    stat -c %Y "$1" 2>/dev/null
  fi
}

fmtg_poll_shim_content() {
  local home=$1 root=$2
  printf '%s\n' \
    '#!/usr/bin/env bash' \
    '# Auto-generated by fm-bootstrap.sh - Telegram mode inbox poll shim.' \
    '# The watcher validates these bytes, then dispatches the trusted poll script.' \
    "export FM_HOME=$(printf '%q' "$home")" \
    "exec $(printf '%q' "$root/bin/fm-tg-poll.sh")"
}

fmtg_poll_shim_valid() {
  local file=$1 home=$2 root=$3
  fmx_poll_shim_private_identity_valid "$file" || return 1
  cmp -s "$file" <(fmtg_poll_shim_content "$home" "$root")
}

fmtg_meta_link_set() {
  local meta=$1 nid=$2 ts=$3 followups=${4:-0} tmp
  [ -f "$meta" ] || return 1
  tmp=$(fmx_meta_tmp "$meta") || return 1
  if ! { grep -vE '^tg_note=|^tg_note_ts=|^tg_followups=' "$meta" || true; } > "$tmp"; then
    rm -f "$tmp"; return 1
  fi
  printf 'tg_note=%s\n' "$nid" >> "$tmp" || { rm -f "$tmp"; return 1; }
  printf 'tg_note_ts=%s\n' "$ts" >> "$tmp" || { rm -f "$tmp"; return 1; }
  printf 'tg_followups=%s\n' "$followups" >> "$tmp" || { rm -f "$tmp"; return 1; }
  mv -f "$tmp" "$meta" || { rm -f "$tmp"; return 1; }
}

fmtg_meta_followups_set() {
  local meta=$1 n=$2 tmp
  [ -f "$meta" ] || return 1
  tmp=$(fmx_meta_tmp "$meta") || return 1
  if ! { grep -vE '^tg_followups=' "$meta" || true; } > "$tmp"; then
    rm -f "$tmp"; return 1
  fi
  printf 'tg_followups=%s\n' "$n" >> "$tmp" || { rm -f "$tmp"; return 1; }
  mv -f "$tmp" "$meta" || { rm -f "$tmp"; return 1; }
}

fmtg_meta_link_clear() {
  local meta=$1 tmp
  [ -f "$meta" ] || return 1
  tmp=$(fmx_meta_tmp "$meta") || return 1
  if ! { grep -vE '^tg_note=|^tg_note_ts=|^tg_followups=' "$meta" || true; } > "$tmp"; then
    rm -f "$tmp"; return 1
  fi
  mv -f "$tmp" "$meta" || { rm -f "$tmp"; return 1; }
}
