#!/usr/bin/env bash
# fm-commit-trailer-lib.sh - agent co-author trailer refusal for a task worktree.
#
# The captain's standing rule is that no commit carries an agent name as a
# co-author. Every supported worker harness injects its own attribution into the
# agent's session instructions, so a sentence in the launch brief competes with
# the harness and loses: workers wrote 'Co-Authored-By: Claude Opus 5 ...' and
# 'Claude-Session: ...' trailers into commits whose brief forbade them. This
# library is the enforcement layer the brief cannot be: a commit-msg hook in the
# worktree the worker commits in, which strips those lines from the message
# before the commit object is written. It sits in git, below every harness, so
# it holds identically whether the worker runs git itself or through a tool, and
# for every harness in AGENTS.md section 4 without a per-harness case.
#
# WHY PER-WORKTREE. core.hooksPath in the repository's shared config would reach
# the captain's own checkout of the same repository and every other worktree of
# it, and a hook file dropped in the shared .git/hooks directory would do the
# same. Git reads a per-worktree config file (.git/worktrees/<id>/config.worktree)
# when extensions.worktreeConfig is enabled, so the hooks path is set there and
# binds only the disposable task worktree. Nothing tracked in the project is
# touched: the hook lives in firstmate's own state directory, not in the tree.
#
# WHY IT CHAINS. A project that already sets core.hooksPath, or that ships a
# commit-msg hook in the repository hooks directory, keeps that hook: the
# generated hook runs the inherited commit-msg first and propagates its exit
# status, then strips agent trailers from whatever message survives. The
# inherited hook is never replaced and never skipped, and it is resolved at run
# time, so a hook added after the spawn is still honoured.
#
# WHAT IT DOES NOT COVER. Git runs commit-msg for `git commit` (an --amend
# included), so a worker's own commits are covered whether it runs git directly
# or through a tool. It is not run for a message replayed by rebase or
# cherry-pick, and `git commit --no-verify` skips every hook, which is why the
# launch brief keeps stating the rule as the discovery layer rather than relying
# on this hook alone.
#
# WHAT IS STRIPPED. Only 'Co-Authored-By:' lines naming one of the agent
# products in FM_COMMIT_TRAILER_AGENTS, and '<Agent>-Session:' lines for the
# same list. A co-author line naming a human survives untouched, as does every
# other line of the message.
#
# Functions:
#   fm_commit_trailer_hook_install <worktree> <hook-dir>
#   fm_commit_trailer_hook_remove  <worktree> <hook-dir>
#
# Both are idempotent. Install refuses (non-zero, diagnostic on stderr) rather
# than half-installing; the one case it cannot make safe is a repository whose
# shared config sets core.worktree or core.bare=true and has not enabled
# extensions.worktreeConfig yet, because enabling it would change where those
# two shared settings apply (git-worktree(1), CONFIGURATION FILE). The refusal
# names the two commands that migrate them. Remove restores whatever
# worktree-scoped hooks path was recorded at install time, and only when the
# current value is still the one this library set; extensions.worktreeConfig is
# left enabled, since disabling it would change the meaning of any other
# per-worktree setting the repository has since gained.

# The single owned list of agent products whose attribution is refused.
# Lower-case alternation, matched case-insensitively with a word boundary on
# each side, so a human named in the same line is not caught by a substring.
FM_COMMIT_TRAILER_AGENTS='claude|codex|copilot|chatgpt|gemini|kimi|grok|cursor'

# Marker file written into a generated hook directory. Its presence is how an
# install tells its own previous hooks path from a project's, so a reused pool
# worktree chains to the project's hook rather than to a retired task's.
FM_COMMIT_TRAILER_MARKER=fm-managed

fm_commit_trailer_hook_body() {  # <chain-dir>
  local chain=$1
  printf '%s\n' \
    '#!/usr/bin/env bash' \
    '# Generated by bin/fm-commit-trailer-lib.sh for one firstmate task worktree.' \
    '# Runs the inherited commit-msg hook, then removes agent attribution trailers.' \
    'set -u'
  printf 'chain_dir=%q\n' "$chain"
  printf 'agents=%q\n' "$FM_COMMIT_TRAILER_AGENTS"
  cat <<'HOOK'

msg=${1:-}
[ -n "$msg" ] && [ -f "$msg" ] || exit 0

if [ -n "$chain_dir" ] && [ -x "$chain_dir/commit-msg" ]; then
  "$chain_dir/commit-msg" "$@" || exit $?
fi

re_coauthor='^[[:space:]]*co-authored-by:[[:space:]]'
re_agent="(^|[^a-z0-9])($agents)([^a-z0-9]|\$)"
re_session="^[[:space:]]*($agents)-session:"

lines=()
shopt -s nocasematch
while IFS= read -r line || [ -n "$line" ]; do
  if [[ $line =~ $re_coauthor ]] && [[ $line =~ $re_agent ]]; then
    continue
  fi
  if [[ $line =~ $re_session ]]; then
    continue
  fi
  lines+=("$line")
done < "$msg"
shopt -u nocasematch

# Drop the blank lines a removed trailer block left dangling at the end.
while [ ${#lines[@]} -gt 0 ]; do
  case "${lines[$((${#lines[@]} - 1))]}" in
    *[![:space:]]*) break ;;
  esac
  unset "lines[$((${#lines[@]} - 1))]"
done

tmp="$msg.fm-trailer.$$"
if [ ${#lines[@]} -gt 0 ]; then
  printf '%s\n' "${lines[@]}" > "$tmp" || exit 1
else
  : > "$tmp" || exit 1
fi
mv -- "$tmp" "$msg" || exit 1
exit 0
HOOK
}

# Effective hooks directory a commit in <worktree> would use today, ignoring one
# this library generated. Empty when the repository has no hooks path of its own.
fm_commit_trailer_chain_dir() {  # <worktree>
  local wt=$1 configured common top resolved
  configured=$(git -C "$wt" config --get core.hooksPath 2>/dev/null) || configured=
  if [ -n "$configured" ]; then
    case "$configured" in
      /*) resolved=$configured ;;
      *)
        top=$(git -C "$wt" rev-parse --show-toplevel 2>/dev/null) || top=
        [ -n "$top" ] || return 1
        resolved="$top/$configured"
        ;;
    esac
    if [ -e "$resolved/$FM_COMMIT_TRAILER_MARKER" ]; then
      resolved=
    fi
  else
    common=$(git -C "$wt" rev-parse --path-format=absolute --git-common-dir 2>/dev/null) || return 1
    resolved="$common/hooks"
  fi
  printf '%s\n' "$resolved"
}

fm_commit_trailer_enable_worktree_config() {  # <worktree>
  local wt=$1 common enabled bare worktree_path
  enabled=$(git -C "$wt" config --get extensions.worktreeConfig 2>/dev/null) || enabled=
  [ "$enabled" = true ] && return 0
  common=$(git -C "$wt" rev-parse --path-format=absolute --git-common-dir 2>/dev/null) || {
    echo "error: could not resolve the repository directory for $wt" >&2
    return 1
  }
  bare=$(git config --file "$common/config" --get core.bare 2>/dev/null) || bare=
  worktree_path=$(git config --file "$common/config" --get core.worktree 2>/dev/null) || worktree_path=
  if [ "$bare" = true ] || [ -n "$worktree_path" ]; then
    echo "error: $wt's repository sets core.bare or core.worktree in its shared config, so firstmate will not enable per-worktree config under it; move those settings to the main worktree first (git -C <main-worktree> config --unset core.bare; git -C <main-worktree> config --worktree core.bare true)" >&2
    return 1
  fi
  git -C "$wt" config extensions.worktreeConfig true || {
    echo "error: could not enable per-worktree git config in $wt" >&2
    return 1
  }
}

fm_commit_trailer_hook_install() {  # <worktree> <hook-dir>
  local wt=${1:-} dir=${2:-} chain prior
  if [ -z "$wt" ] || [ -z "$dir" ]; then
    echo "error: commit-trailer hook install needs a worktree and a hook directory" >&2
    return 2
  fi
  if ! git -C "$wt" rev-parse --is-inside-work-tree >/dev/null 2>&1; then
    echo "error: $wt is not a git worktree; refusing to install the commit-trailer hook" >&2
    return 1
  fi
  fm_commit_trailer_enable_worktree_config "$wt" || return 1
  chain=$(fm_commit_trailer_chain_dir "$wt") || {
    echo "error: could not resolve the inherited hooks path for $wt" >&2
    return 1
  }
  # A worktree-scoped hooks path this library did not write is the worktree's
  # own; record it so removal restores it instead of dropping it.
  prior=$(git -C "$wt" config --worktree --get core.hooksPath 2>/dev/null) || prior=
  if [ "$prior" = "$dir" ] || { [ -n "$prior" ] && [ -e "$prior/$FM_COMMIT_TRAILER_MARKER" ]; }; then
    prior=
  fi
  mkdir -p "$dir" || {
    echo "error: could not create the commit-trailer hook directory $dir" >&2
    return 1
  }
  fm_commit_trailer_hook_body "$chain" > "$dir/commit-msg" || {
    echo "error: could not write the commit-trailer hook in $dir" >&2
    return 1
  }
  chmod 0755 "$dir/commit-msg" || return 1
  printf '%s\n' "$prior" > "$dir/$FM_COMMIT_TRAILER_MARKER" || return 1
  git -C "$wt" config --worktree core.hooksPath "$dir" || {
    echo "error: could not point $wt at the commit-trailer hook" >&2
    return 1
  }
}

fm_commit_trailer_hook_remove() {  # <worktree> <hook-dir>
  local wt=${1:-} dir=${2:-} current prior
  if [ -z "$dir" ]; then
    echo "error: commit-trailer hook removal needs a hook directory" >&2
    return 2
  fi
  if [ -n "$wt" ] && git -C "$wt" rev-parse --is-inside-work-tree >/dev/null 2>&1; then
    current=$(git -C "$wt" config --worktree --get core.hooksPath 2>/dev/null) || current=
    if [ "$current" = "$dir" ]; then
      prior=$(sed -n '1p' "$dir/$FM_COMMIT_TRAILER_MARKER" 2>/dev/null) || prior=
      if [ -n "$prior" ]; then
        git -C "$wt" config --worktree core.hooksPath "$prior" || return 1
      else
        git -C "$wt" config --worktree --unset core.hooksPath 2>/dev/null || true
      fi
    fi
  fi
  rm -rf -- "$dir" || return 1
}
