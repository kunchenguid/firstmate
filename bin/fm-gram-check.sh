#!/usr/bin/env bash
# fm-gram-check.sh - recurring Gram intake poll as a standing watcher check.
#
# Usage:
#   fm-gram-check.sh [check]
#   fm-gram-check.sh arm
#   fm-gram-check.sh disarm
#   fm-gram-check.sh --help
#
# `check` runs bin/fm-gram.sh poll from this home. It composes with the existing
# watcher state-check contract instead of carrying a schedule of its own: a
# printed line becomes a `check:` wake, and the durable `check: captain inbox
# note <id>` rows the poll queued through bin/fm-inbox.sh are what firstmate
# then drains and acts on.
#
# `arm` writes state/gram.check.sh and binds its bytes with
# fm-check-register.sh, so the watcher dispatches it on its normal
# FM_CHECK_INTERVAL cadence. `disarm` removes the shim, its trust binding, and
# the report record. Arming needs no configuration: the poll resolves its
# audience from the ambient HERDR_PANE_ID and says so when there is none.
#
# Reporting. New messages always doorbell, because that is the news. A
# diagnostic line doorbells only when it differs from the last one reported
# (state/.gram-check is the news key), so a Herdr server that stays unreachable,
# or a home that is simply not running inside a Herdr pane, reports once instead
# of on every cycle. A silent poll prints nothing.
#
# The poll must finish inside the watcher's per-check bound (FM_CHECK_TIMEOUT,
# default 30, read from this check's own environment because the watcher runs it
# as a direct child). FM_GRAM_BUDGET is cut down to whatever fits inside that
# bound before the poll starts, and a poll that does not finish reports one line
# naming the budget rather than leaving the check silent.
set -u
export LC_ALL=C

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FM_HOME="${FM_HOME:-${FM_ROOT_OVERRIDE:-$(cd "$SCRIPT_DIR/.." && pwd)}}"
STATE="${FM_STATE_OVERRIDE:-$FM_HOME/state}"
RECORD="$STATE/.gram-check"
CHECK_ID=gram
CHECK_SHIM="$STATE/$CHECK_ID.check.sh"
CHECK_TRUST="$STATE/$CHECK_ID.check-trust"
GRAM_BIN="$SCRIPT_DIR/fm-gram.sh"
REGISTER_BIN="$SCRIPT_DIR/fm-check-register.sh"
RECORD_SCHEMA=fm-gram-check-v1
MAX_LINE=240

# shellcheck source=bin/fm-timeout-lib.sh
. "$SCRIPT_DIR/fm-timeout-lib.sh"
# shellcheck source=bin/fm-pr-lib.sh
. "$SCRIPT_DIR/fm-pr-lib.sh"
# shellcheck source=bin/fm-line-cap-lib.sh
. "$SCRIPT_DIR/fm-line-cap-lib.sh"
# shellcheck source=bin/fm-check-lib.sh
. "$SCRIPT_DIR/fm-check-lib.sh"

usage() {
  cat <<'EOF'
Usage:
  fm-gram-check.sh [check]   run the Gram intake poll; wake line unless the poll is a proven no-op
  fm-gram-check.sh arm       write and register state/gram.check.sh
  fm-gram-check.sh disarm    remove the check shim, its trust binding, and the record
  fm-gram-check.sh --help    print this help

The poll itself is bin/fm-gram.sh; see its header for eligibility, identity,
routing, and the duplicate boundary.
EOF
}

CHECK_TIMEOUT=${FM_CHECK_TIMEOUT:-30}
case "$CHECK_TIMEOUT" in
  ''|*[!0-9]*|0) CHECK_TIMEOUT=30 ;;
esac
BUDGET_SECS=${FM_GRAM_BUDGET:-10}
case "$BUDGET_SECS" in
  ''|*[!0-9]*|0) BUDGET_SECS=10 ;;
esac
BUDGET_MAX=$((CHECK_TIMEOUT - 5))
[ "$BUDGET_MAX" -ge 1 ] || BUDGET_MAX=1
if [ "$BUDGET_SECS" -gt "$BUDGET_MAX" ]; then
  BUDGET_SECS=$BUDGET_MAX
fi

record_read() {
  local line first=1
  RECORD_REPORTED=
  [ -f "$RECORD" ] || return 0
  while IFS= read -r line; do
    if [ "$first" = 1 ]; then
      first=0
      [ "$line" = "$RECORD_SCHEMA" ] || return 0
      continue
    fi
    case "$line" in
      reported=*) RECORD_REPORTED=${line#reported=} ;;
    esac
  done < "$RECORD"
  return 0
}

record_write() {
  local reported=$1 tmp
  tmp=$(mktemp "$RECORD.XXXXXX" 2>/dev/null) || return 1
  chmod 0600 "$tmp" 2>/dev/null || { rm -f -- "$tmp"; return 1; }
  {
    printf '%s\n' "$RECORD_SCHEMA"
    printf 'epoch=%s\n' "$(date +%s)"
    printf 'reported=%s\n' "$reported"
  } > "$tmp" || { rm -f -- "$tmp"; return 1; }
  mv -f -- "$tmp" "$RECORD" || { rm -f -- "$tmp"; return 1; }
  return 0
}

action_check() {
  local out rc line news=0
  mkdir -p "$STATE" || return 1
  out=$(FM_HOME="$FM_HOME" FM_GRAM_BUDGET="$BUDGET_SECS" \
    fm_run_timed "$CHECK_TIMEOUT" "$GRAM_BIN" poll 2>&1)
  rc=$?
  if [ "$rc" -eq 124 ]; then
    line="Gram intake did not finish inside ${CHECK_TIMEOUT}s"
  else
    line=$(printf '%s\n' "$out" | sed -n 's/^fm-gram: //p' | head -n 1)
  fi
  [ -n "$line" ] || return 0

  # New mail from the owner is always news; a repeated diagnostic is not.
  case "$line" in
    *'new Gram message'*) news=1 ;;
  esac
  if [ "$news" -eq 0 ]; then
    record_read
    [ "$line" = "${RECORD_REPORTED:-}" ] && return 0
  fi
  record_write "$line" || true
  fm_cap_line_var "gram: $line" "$MAX_LINE"
  printf '%s\n' "$FM_LINE_CAP_LINE"
  return 0
}

shim_content() {
  local home=$1
  printf '%s\n' \
    '#!/usr/bin/env bash' \
    '# Auto-generated by fm-gram-check.sh - Gram intake poll shim.' \
    '# The watcher validates these bytes, then dispatches the trusted check script.' \
    "export FM_HOME=$(printf '%q' "$home")" \
    "exec $(printf '%q' "$SCRIPT_DIR/fm-gram-check.sh") check"
}

SHIM_WRITE_TMP=

shim_write() {
  local want=$1 device tmp
  [ -d "$STATE" ] && [ ! -L "$STATE" ] || return 1
  device=$(fm_pr_file_device "$STATE") || return 1
  [ -n "$device" ] || return 1
  fm_pr_regular_destination_on_device_or_absent "$CHECK_SHIM" "$device" || return 1
  if [ -e "$CHECK_SHIM" ] && [ "$(fm_pr_file_mode "$CHECK_SHIM")" = 700 ] \
    && [ "$(cat "$CHECK_SHIM" 2>/dev/null)" = "$want" ]; then
    return 0
  fi
  tmp=$(umask 077; mktemp "$STATE/.fm-gram-check.XXXXXX" 2>/dev/null) || return 1
  SHIM_WRITE_TMP=$tmp
  if ! printf '%s\n' "$want" > "$tmp" \
    || ! chmod 0700 "$tmp" \
    || ! fm_pr_private_file_valid "$tmp" 700 "$device"; then
    rm -f -- "$tmp"
    SHIM_WRITE_TMP=
    return 1
  fi
  if ! fm_pr_regular_destination_on_device_or_absent "$CHECK_SHIM" "$device" \
    || ! mv -f -- "$tmp" "$CHECK_SHIM"; then
    rm -f -- "$tmp"
    SHIM_WRITE_TMP=
    return 1
  fi
  SHIM_WRITE_TMP=
  fm_pr_private_file_valid "$CHECK_SHIM" 700 "$device"
}

shim_backup() {
  local device tmp
  device=$(fm_pr_file_device "$STATE") || return 1
  [ -n "$device" ] || return 1
  tmp=$(umask 077; mktemp "$STATE/.fm-gram-check.XXXXXX" 2>/dev/null) || return 1
  if ! cat "$CHECK_SHIM" > "$tmp" 2>/dev/null \
    || ! chmod 0700 "$tmp" \
    || ! fm_pr_private_file_valid "$tmp" 700 "$device"; then
    rm -f -- "$tmp"
    return 1
  fi
  printf '%s\n' "$tmp"
}

ARM_BACKUP=

# An unregistered shim is not inert: the watcher rejects it every cycle and
# wakes firstmate about unauthenticated state checks. So after a failed or
# interrupted arm the home never holds a shim without a matching binding.
arm_rollback() {
  [ -z "$SHIM_WRITE_TMP" ] || rm -f -- "$SHIM_WRITE_TMP"
  SHIM_WRITE_TMP=
  if [ -n "$ARM_BACKUP" ]; then
    mv -f -- "$ARM_BACKUP" "$CHECK_SHIM" 2>/dev/null || rm -f -- "$ARM_BACKUP"
    ARM_BACKUP=
    if fm_custom_check_registered "$STATE" "$CHECK_ID"; then
      return 0
    fi
  fi
  rm -f -- "$CHECK_SHIM"
}

# shellcheck disable=SC2329  # Registered by action_arm's signal trap.
arm_interrupted() {
  arm_rollback
  printf 'fm-gram-check: arming was interrupted, so state/%s.check.sh is not armed\n' "$CHECK_ID" >&2
  exit 1
}

action_arm() {
  local want home
  if [ ! -x "$GRAM_BIN" ]; then
    printf 'fm-gram-check: the Gram poll is missing at %s; cannot arm\n' "$GRAM_BIN" >&2
    return 1
  fi
  mkdir -p "$STATE" || return 1
  case "$FM_HOME" in
    /*) home=$FM_HOME ;;
    *)
      home=$(CDPATH='' cd -- "$FM_HOME" 2>/dev/null && pwd -P) || {
        printf 'fm-gram-check: cannot resolve FM_HOME %s\n' "$FM_HOME" >&2
        return 1
      }
      ;;
  esac
  want=$(shim_content "$home")
  ARM_BACKUP=
  if [ -f "$CHECK_SHIM" ] && [ ! -L "$CHECK_SHIM" ]; then
    ARM_BACKUP=$(shim_backup) || {
      printf 'fm-gram-check: could not save the existing %s\n' "$CHECK_SHIM" >&2
      return 1
    }
  fi
  trap arm_interrupted HUP INT TERM
  if ! shim_write "$want"; then
    trap - HUP INT TERM
    arm_rollback
    printf 'fm-gram-check: could not write %s\n' "$CHECK_SHIM" >&2
    return 1
  fi
  if ! FM_HOME="$home" "$REGISTER_BIN" "$CHECK_ID" >/dev/null; then
    trap - HUP INT TERM
    arm_rollback
    printf 'fm-gram-check: could not register %s\n' "$CHECK_SHIM" >&2
    return 1
  fi
  trap - HUP INT TERM
  [ -z "$ARM_BACKUP" ] || rm -f -- "$ARM_BACKUP"
  ARM_BACKUP=
  printf 'armed: state/%s.check.sh\n' "$CHECK_ID"
  return 0
}

action_disarm() {
  rm -f -- "$CHECK_SHIM" "$CHECK_TRUST" "$RECORD"
  printf 'disarmed: state/%s.check.sh\n' "$CHECK_ID"
  return 0
}

case "${1:-check}" in
  check) action_check ;;
  arm) action_arm ;;
  disarm) action_disarm ;;
  -h|--help) usage ;;
  *)
    printf 'fm-gram-check: unknown action: %s\n' "$1" >&2
    usage >&2
    exit 2
    ;;
esac
