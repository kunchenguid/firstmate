#!/usr/bin/env bash
# Shared config, channel enforcement, and Slack Web API helpers for the captain
# channel poll (fm-slack-poll.sh) and post client (fm-slack-post.sh).
# Slack is opt-in: a non-empty FM_SLACK_BOT_TOKEN in the home .env plus a
# configured channel id in config/slack-captain-channel. Without both the poll is
# a hard no-op. Never enumerate conversations; every read and post path takes the
# configured channel id and refuses a mismatch.
#
# This file is sourced, never executed.
# shellcheck source=bin/fm-x-lib.sh
. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/fm-x-lib.sh"

fms_channel_id_valid() {
  local id=$1
  case "$id" in
    C[A-Z0-9][A-Z0-9][A-Z0-9][A-Z0-9][A-Z0-9][A-Z0-9][A-Z0-9][A-Z0-9][A-Z0-9]*) return 0 ;;
    G[A-Z0-9][A-Z0-9][A-Z0-9][A-Z0-9][A-Z0-9][A-Z0-9][A-Z0-9][A-Z0-9][A-Z0-9]*) return 0 ;;
    *) return 1 ;;
  esac
}

fms_channel_configured() {
  [ -n "${FMS_CHANNEL_ID:-}" ] || return 1
  fms_channel_id_valid "$FMS_CHANNEL_ID"
}

fms_require_configured_channel() {
  local channel=$1
  fms_channel_configured || return 1
  fms_channel_id_valid "$channel" || return 1
  [ "$channel" = "$FMS_CHANNEL_ID" ]
}

fms_poll_shim_content() {
  local home=$1 root=$2
  printf '%s\n' \
    '#!/usr/bin/env bash' \
    '# Auto-generated by fm-bootstrap.sh - Slack captain channel poll shim.' \
    '# The watcher validates these bytes, then dispatches the trusted poll script.' \
    "export FM_HOME=$(printf '%q' "$home")" \
    "exec $(printf '%q' "$root/bin/fm-slack-poll.sh")"
}

fms_poll_shim_valid() {
  local file=$1 home=$2 root=$3
  fmx_poll_shim_private_identity_valid "$file" || return 1
  cmp -s "$file" <(fms_poll_shim_content "$home" "$root")
}

fms_config_channel_read() {
  local file=$1 line
  [ -f "$file" ] || return 0
  line=$(grep -Ev '^[[:space:]]*(#|$)' "$file" 2>/dev/null | head -1) || return 0
  line=${line#"${line%%[![:space:]]*}"}
  line=${line%"${line##*[![:space:]]}"}
  printf '%s' "$line"
}

# Resolve FMS_TOKEN, FMS_CHANNEL_ID, and FMS_API (default https://slack.com/api).
# Env wins over files. Missing token or channel leaves both empty.
fms_load_config() {
  local env_file="${FMS_ENV_FILE:-$FM_HOME/.env}" channel_file
  channel_file="${FM_CONFIG_OVERRIDE:-$FM_HOME/config}/slack-captain-channel"
  if [ -n "${FM_SLACK_BOT_TOKEN+x}" ]; then
    FMS_TOKEN=${FM_SLACK_BOT_TOKEN-}
  else
    FMS_TOKEN=$(fmx_env_get FM_SLACK_BOT_TOKEN "$env_file")
  fi
  if [ -n "${FM_SLACK_CAPTAIN_CHANNEL_ID+x}" ]; then
    FMS_CHANNEL_ID=${FM_SLACK_CAPTAIN_CHANNEL_ID-}
  else
    FMS_CHANNEL_ID=$(fms_config_channel_read "$channel_file")
  fi
  if [ -n "${FM_SLACK_API_URL+x}" ]; then
    FMS_API=${FM_SLACK_API_URL-}
  else
    FMS_API=$(fmx_env_get FM_SLACK_API_URL "$env_file")
  fi
  [ -n "$FMS_API" ] || FMS_API=https://slack.com/api
  FMS_API=${FMS_API%/}
}

fms_configured() {
  [ -n "${FMS_TOKEN:-}" ] && [ -n "${FMS_CHANNEL_ID:-}" ] \
    && fms_channel_id_valid "$FMS_CHANNEL_ID"
}

fms_auth_header_file() {
  local tmp token=${FMS_TOKEN:-}
  [ -n "$token" ] || return 1
  case "$token" in
    *$'\n'*|*'"'*|*"'"*) return 1 ;;
  esac
  tmp=$(mktemp "${TMPDIR:-/tmp}/fm-slack-auth.XXXXXX") || return 1
  printf 'Authorization: Bearer %s\n' "$token" > "$tmp" || { rm -f -- "$tmp"; return 1; }
  chmod 0600 "$tmp" || { rm -f -- "$tmp"; return 1; }
  printf '%s\n' "$tmp"
}

fms_auth_header_release() {
  local auth_header=$1
  [ -n "$auth_header" ] || return 0
  rm -f -- "$auth_header" 2>/dev/null || true
}

# POST application/x-www-form-urlencoded to one Slack method.
# Prints the response body to stdout; returns curl's exit code.
# FM_SLACK_CURL_LOG may record argv summaries for tests.
fms_api_post() {
  local method=$1 data=$2 ofile=$3 auth_header curl_bin=${FM_SLACK_CURL_BIN:-curl} rc
  case "$method" in
    auth.test|chat.postMessage|chat.update|conversations.history|conversations.replies) ;;
    *) return 1 ;;
  esac
  command -v "$curl_bin" >/dev/null 2>&1 || return 1
  auth_header=$(fms_auth_header_file) || return 1
  trap 'fms_auth_header_release "$auth_header"' INT TERM HUP
  if [ -n "${FM_SLACK_CURL_LOG:-}" ]; then
    printf 'method=%s data=%s\n' "$method" "$data" >> "$FM_SLACK_CURL_LOG"
  fi
  "$curl_bin" -m 10 -sS -o "${ofile:-/dev/stdout}" \
    -H "@$auth_header" \
    -H 'Content-Type: application/x-www-form-urlencoded; charset=utf-8' \
    --data "$data" \
    "${FMS_API}/${method}" 2>/dev/null
  rc=$?
  fms_auth_header_release "$auth_header"
  trap - INT TERM HUP
  return "$rc"
}

fms_api_json_ok() {
  local file=$1
  command -v jq >/dev/null 2>&1 || return 1
  [ -s "$file" ] || return 1
  [ "$(jq -r '.ok // false' "$file" 2>/dev/null)" = true ]
}

fms_api_response_channel_ok() {
  local file=$1
  local channel
  channel=$(jq -r '.channel // empty' "$file" 2>/dev/null) || return 1
  [ -n "$channel" ] || return 0
  fms_require_configured_channel "$channel"
}

fms_bot_user_id_load() {
  local state=$1 cache body_file
  FMS_BOT_USER_ID=
  cache="$state/slack-bot-user"
  if fmx_private_artifact_file_valid "$state" "slack-bot-user" 600 2>/dev/null; then
    FMS_BOT_USER_ID=$(cat "$cache" 2>/dev/null) || FMS_BOT_USER_ID=
    [ -n "$FMS_BOT_USER_ID" ] && return 0
  fi
  body_file=$(mktemp "${TMPDIR:-/tmp}/fm-slack-auth.XXXXXX") || return 1
  if ! fms_api_post auth.test '' "$body_file"; then
    rm -f -- "$body_file"
    return 1
  fi
  if ! fms_api_json_ok "$body_file"; then
    rm -f -- "$body_file"
    return 1
  fi
  FMS_BOT_USER_ID=$(jq -r '.user_id // empty' "$body_file" 2>/dev/null) || FMS_BOT_USER_ID=
  rm -f -- "$body_file"
  [ -n "$FMS_BOT_USER_ID" ] || return 1
  printf '%s\n' "$FMS_BOT_USER_ID" \
    | fmx_private_artifact_publish_stdin "$state" "slack-bot-user" 600 >/dev/null 2>&1 || true
  return 0
}

fms_message_ts_valid() {
  case "$1" in
    ''|.*|*/*|*[!0-9.]*|*.*.*.*) return 1 ;;
    [0-9]*.[0-9]*) return 0 ;;
    *) return 1 ;;
  esac
}

fms_is_non_captain_message() {
  local file=$1 bot_user=$2
  jq -e --arg bot "$bot_user" '
    (.subtype? // "") as $sub |
    ($sub != "") or (.bot_id? != null) or
    ((.user? // "") != "" and (.user == $bot))
  ' "$file" >/dev/null 2>&1
}

fms_message_has_text() {
  local file=$1 text
  text=$(jq -r '(.text // "") | gsub("[[:space:]]+"; " ") | gsub("^ +| +$"; "")' "$file" 2>/dev/null) || return 1
  [ -n "$text" ]
}

# Fixed, contentless acknowledgement posted by the poll check before waking firstmate.
fms_ack_text() {
  printf '%s' 'On it.'
}

fms_message_text_oneline() {
  local file=$1
  jq -r '(.text // "") | gsub("\t"; " ") | gsub("\r?\n"; " ") | gsub("[[:space:]]+"; " ") | gsub("^ +| +$"; "")' "$file" 2>/dev/null
}

fms_post_ack() {
  local message_ts=$1 body_file=${2:-} data text
  fms_message_ts_valid "$message_ts" || return 1
  fms_channel_configured || return 1
  text=$(fms_ack_text)
  [ -n "$text" ] || return 1
  if [ -z "$body_file" ]; then
    body_file=$(mktemp "${TMPDIR:-/tmp}/fm-slack-ack.XXXXXX") || return 1
  fi
  data="channel=$(printf '%s' "$FMS_CHANNEL_ID" | jq -sRr @uri)"
  data="${data}&text=$(printf '%s' "$text" | jq -sRr @uri)"
  data="${data}&thread_ts=$(printf '%s' "$message_ts" | jq -sRr @uri)"
  fms_api_post chat.postMessage "$data" "$body_file" || return 1
  fms_api_json_ok "$body_file" || return 1
  fms_api_response_channel_ok "$body_file" || return 1
  return 0
}

fms_ack_claim() {
  local state=$1 ts=$2 dir
  fms_message_ts_valid "$ts" || return 2
  dir="$state/slack-acked"
  printf '%s\n' "$ts" | fmx_private_artifact_publish_stdin_once "$dir" "$ts" 600
}

fms_ack_claim_release() {
  local state=$1 ts=$2
  fms_message_ts_valid "$ts" || return 1
  rm -f -- "$state/slack-acked/$ts" 2>/dev/null
}

fms_wake_line() {
  local ts=$1 text=$2
  fms_message_ts_valid "$ts" || return 1
  [ -n "$text" ] || return 1
  printf 'slack-captain-message %s\t%s\n' "$ts" "$text"
}

fms_offer_path() {
  local state=$1 ts=$2
  printf '%s/slack-offered/%s' "$state" "$ts"
}

fms_offer_claim() {
  local state=$1 ts=$2 dir
  fms_message_ts_valid "$ts" || return 2
  dir="$state/slack-offered"
  printf '%s\n' "$ts" | fmx_private_artifact_publish_stdin_once "$dir" "$ts" 600
}

fms_inbox_publish() {
  local state=$1 ts=$2 payload_file=$3 dir
  fms_message_ts_valid "$ts" || return 1
  dir="$state/slack-inbox"
  jq '.' "$payload_file" 2>/dev/null \
    | fmx_private_artifact_publish_stdin "$dir" "${ts}.json" 600 >/dev/null 2>&1
}

fms_poll_cursor_read() {
  local state=$1 cursor
  cursor="$state/slack-poll.cursor"
  if fmx_private_artifact_file_valid "$state" "slack-poll.cursor" 600 2>/dev/null; then
    cat "$cursor" 2>/dev/null
    return 0
  fi
  printf '0'
}

fms_poll_cursor_write() {
  :
}
