#!/usr/bin/env bash
# Shared config, channel enforcement, and Slack Web API helpers for the captain
# channel poll, Socket Mode consumer, and post client.
# Slack is opt-in: a non-empty FM_SLACK_BOT_TOKEN in the home .env plus a
# configured channel id in config/slack-captain-channel. Without both the poll is
# a hard no-op. Never enumerate conversations; every read and post path takes the
# configured channel id and refuses a mismatch.
#
# This file is sourced, never executed.
# shellcheck source=bin/fm-x-lib.sh
. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/fm-x-lib.sh"

fms_channel_id_valid() {
  local id=$1
  case "$id" in
    C[A-Z0-9][A-Z0-9][A-Z0-9][A-Z0-9][A-Z0-9][A-Z0-9][A-Z0-9][A-Z0-9][A-Z0-9]*) return 0 ;;
    G[A-Z0-9][A-Z0-9][A-Z0-9][A-Z0-9][A-Z0-9][A-Z0-9][A-Z0-9][A-Z0-9][A-Z0-9]*) return 0 ;;
    *) return 1 ;;
  esac
}

fms_user_id_valid() {
  case "$1" in
    U[A-Z0-9][A-Z0-9][A-Z0-9][A-Z0-9][A-Z0-9][A-Z0-9][A-Z0-9][A-Z0-9]*) return 0 ;;
    *) return 1 ;;
  esac
}

fms_channel_configured() {
  [ -n "${FMS_CHANNEL_ID:-}" ] || return 1
  fms_channel_id_valid "$FMS_CHANNEL_ID"
}

fms_require_configured_channel() {
  local channel=$1
  fms_channel_configured || return 1
  fms_channel_id_valid "$channel" || return 1
  [ "$channel" = "$FMS_CHANNEL_ID" ]
}

fms_poll_shim_content() {
  local home=$1 root=$2
  printf '%s\n' \
    '#!/usr/bin/env bash' \
    '# Auto-generated by fm-bootstrap.sh - Slack captain channel poll shim.' \
    '# The watcher validates these bytes, then dispatches the trusted poll script.' \
    "export FM_HOME=$(printf '%q' "$home")" \
    "exec $(printf '%q' "$root/bin/fm-slack-poll.sh")"
}

fms_poll_shim_valid() {
  local file=$1 home=$2 root=$3
  fmx_poll_shim_private_identity_valid "$file" || return 1
  cmp -s "$file" <(fms_poll_shim_content "$home" "$root")
}

# Read a single value from an operator-owned config file: the first non-comment
# line, trimmed, or empty when the file is absent or holds nothing. This is the
# single owner of the one-value-per-file operator config read; the captain
# channel and user ids read it raw, and fms_positive_int_config_read layers the
# positive-integer contract on top of it.
fms_config_value_read() {
  local file=$1 line
  [ -f "$file" ] || return 0
  line=$(grep -Ev '^[[:space:]]*(#|$)' "$file" 2>/dev/null | head -1) || return 0
  line=${line#"${line%%[![:space:]]*}"}
  line=${line%"${line##*[![:space:]]}"}
  printf '%s' "$line"
}

# Validate and emit a positive integer held in an operator-owned config file.
# Empty, non-numeric, or zero input emits nothing so the caller falls back to
# its built-in default. This is the single owner of that format check; the
# operator-owned source readers, the captain comms caps, and the one-time
# adoption from a pre-convention generated file all route through it.
fms_positive_int_emit() {
  local v=$1
  case "$v" in
    ''|*[!0-9]*) return 0 ;;
  esac
  [ "$v" -gt 0 ] 2>/dev/null || return 0
  printf '%s' "$v"
}

# The shared operator-config read constrained to a positive integer: empty when
# the file is absent or holds no valid integer, so the caller falls back to its
# built-in default. The captain poll cadence (config/slack-captain-cadence, which
# bootstrap reads but never overwrites so an operator's choice survives
# regeneration) and the captain comms caps both route through it.
fms_positive_int_config_read() {
  fms_positive_int_emit "$(fms_config_value_read "$1")"
}

# Resolve the watcher's poll and check intervals from the operator-owned env files.
# This function owns the config-load and effective-interval logic. Production
# initialization evaluates its output from bin/fm-watch.sh, while the regression
# tests call it directly. Its current body does not branch on caller mode.
# The specific predicate [ "${BASH_SOURCE[0]}" != "$0" ] is true in both measured
# call contexts because BASH_SOURCE[0] is this library and differs from $0 in
# both. That fact is predicate-specific, not a claim that every mutation inside
# this function is mode-insensitive: $0 identifies the bash -c test shell in the
# sourced regression path and bin/fm-watch.sh in executed production.
# The regression therefore does not close the sourced-versus-executed dimension.
# At the top-level eval in bin/fm-watch.sh, BASH_SOURCE[0] is fm-watch.sh in both
# modes while $0 identifies different callers, so the same predicate distinguishes
# sourced from executed mode and can leave the sourced suite green while executed
# production falls back to the default. The PARTIAL GATE notes in bin/fm-watch.sh
# and tests/fm-slack-captain-channel.test.sh state what is and is not closed.
# It sources config/x-mode.env then config/slack-captain.env when each file exists
# (both may export FM_CHECK_INTERVAL and/or FM_SLACK_CHECK_INTERVAL), then emits
# eval-able POLL/CHECK_INTERVAL/SLACK_CHECK_INTERVAL assignments using the same
# defaults fm-watch.sh used inline. fm-watch.sh evaluates the output to set the
# shell globals; tests source the same function under a fixture env and read
# SLACK_CHECK_INTERVAL from the emitted assignments. Callers capture stdout under
# the same FM_HOME / FM_STATE_OVERRIDE / FM_CONFIG_OVERRIDE / FM_ROOT_OVERRIDE
# that fm-watch.sh top-level honors.
fm_watch_intervals() {
  local home config
  home="${FM_HOME:-${FM_ROOT_OVERRIDE:-$FM_ROOT_OVERRIDE}}"
  config="${FM_CONFIG_OVERRIDE:-$home/config}"
  # shellcheck disable=SC1091
  [ -f "$config/x-mode.env" ] && . "$config/x-mode.env"
  # shellcheck disable=SC1091
  [ -f "$config/slack-captain.env" ] && . "$config/slack-captain.env"
  printf 'POLL=%q\nCHECK_INTERVAL=%q\nSLACK_CHECK_INTERVAL=%q\n' \
    "${FM_POLL:-15}" "${FM_CHECK_INTERVAL:-300}" "${FM_SLACK_CHECK_INTERVAL:-${FM_POLL:-15}}"
}

# Resolve Slack credentials and pinned captain-channel identities.
# Env wins over files. Missing token or channel leaves both empty.
fms_load_config() {
  local env_file="${FMS_ENV_FILE:-$FM_HOME/.env}" channel_file
  channel_file="${FM_CONFIG_OVERRIDE:-$FM_HOME/config}/slack-captain-channel"
  if [ -n "${FM_SLACK_BOT_TOKEN+x}" ]; then
    FMS_TOKEN=${FM_SLACK_BOT_TOKEN-}
  else
    FMS_TOKEN=$(fmx_env_get FM_SLACK_BOT_TOKEN "$env_file")
  fi
  if [ -n "${FM_SLACK_CAPTAIN_CHANNEL_ID+x}" ]; then
    FMS_CHANNEL_ID=${FM_SLACK_CAPTAIN_CHANNEL_ID-}
  else
    FMS_CHANNEL_ID=$(fms_config_value_read "$channel_file")
  fi
  if [ -n "${FM_SLACK_APP_TOKEN+x}" ]; then
    FMS_APP_TOKEN=${FM_SLACK_APP_TOKEN-}
  else
    FMS_APP_TOKEN=$(fmx_env_get FM_SLACK_APP_TOKEN "$env_file")
  fi
  if [ -n "${FM_SLACK_CAPTAIN_USER_ID+x}" ]; then
    FMS_CAPTAIN_USER_ID=${FM_SLACK_CAPTAIN_USER_ID-}
  else
    FMS_CAPTAIN_USER_ID=$(fms_config_value_read "${FM_CONFIG_OVERRIDE:-$FM_HOME/config}/slack-captain-user")
  fi
  if [ -n "${FM_SLACK_API_URL+x}" ]; then
    FMS_API=${FM_SLACK_API_URL-}
  else
    FMS_API=$(fmx_env_get FM_SLACK_API_URL "$env_file")
  fi
  [ -n "$FMS_API" ] || FMS_API=https://slack.com/api
  FMS_API=${FMS_API%/}
}

fms_configured() {
  [ -n "${FMS_TOKEN:-}" ] && [ -n "${FMS_CHANNEL_ID:-}" ] \
    && fms_channel_id_valid "$FMS_CHANNEL_ID"
}

fms_socket_configured() {
  fms_configured && [ -n "${FMS_APP_TOKEN:-}" ] \
    && fms_user_id_valid "${FMS_CAPTAIN_USER_ID:-}"
}

fms_auth_header_file() {
  local tmp token=${FMS_TOKEN:-}
  [ -n "$token" ] || return 1
  case "$token" in
    *$'\n'*|*'"'*|*"'"*) return 1 ;;
  esac
  tmp=$(mktemp "${TMPDIR:-/tmp}/fm-slack-auth.XXXXXX") || return 1
  printf 'Authorization: Bearer %s\n' "$token" > "$tmp" || { rm -f -- "$tmp"; return 1; }
  chmod 0600 "$tmp" || { rm -f -- "$tmp"; return 1; }
  printf '%s\n' "$tmp"
}

fms_auth_header_release() {
  local auth_header=$1
  [ -n "$auth_header" ] || return 0
  rm -f -- "$auth_header" 2>/dev/null || true
}

# POST application/x-www-form-urlencoded to one Slack method.
# Prints the response body to stdout; returns curl's exit code.
# FM_SLACK_CURL_LOG may record argv summaries for tests.
fms_api_post() {
  local method=$1 data=$2 ofile=$3 auth_header curl_bin=${FM_SLACK_CURL_BIN:-curl}
  local rc attempt=1 max_attempts=3 delay=0.1
  case "$method" in
    auth.test|chat.update|conversations.history|conversations.replies|reactions.add|reactions.remove) ;;
    chat.postMessage)
      # Slack may have accepted a post before a transport error is reported.
      # This caller supplies no verified deduplication identity, so retrying
      # could create a second message and leave board metadata orphaned.
      max_attempts=1
      ;;
    *) return 1 ;;
  esac
  command -v "$curl_bin" >/dev/null 2>&1 || return 1
  auth_header=$(fms_auth_header_file) || return 1
  trap 'fms_auth_header_release "$auth_header"' INT TERM HUP
  if [ -n "${FM_SLACK_CURL_LOG:-}" ]; then
    printf 'method=%s data=%s\n' "$method" "$data" >> "$FM_SLACK_CURL_LOG"
  fi
  while :; do
    "$curl_bin" -m 7 -sS -o "${ofile:-/dev/stdout}" \
      -H "@$auth_header" \
      -H 'Content-Type: application/x-www-form-urlencoded; charset=utf-8' \
      --data "$data" \
      "${FMS_API}/${method}" 2>/dev/null
    rc=$?
    [ "$rc" -eq 0 ] && break
    [ "$attempt" -ge "$max_attempts" ] && break
    sleep "$delay"
    delay=$(LC_ALL=C awk -v value="$delay" 'BEGIN { doubled = value * 2; print (doubled > 0.5 ? 0.5 : doubled) }')
    attempt=$((attempt + 1))
  done
  fms_auth_header_release "$auth_header"
  trap - INT TERM HUP
  return "$rc"
}

fms_api_json_ok() {
  local file=$1
  command -v jq >/dev/null 2>&1 || return 1
  [ -s "$file" ] || return 1
  [ "$(jq -r '.ok // false' "$file" 2>/dev/null)" = true ]
}

fms_api_response_channel_ok() {
  local file=$1
  local channel
  channel=$(jq -r '.channel // empty' "$file" 2>/dev/null) || return 1
  [ -n "$channel" ] || return 0
  fms_require_configured_channel "$channel"
}

fms_bot_user_id_load() {
  local state=$1 cache body_file
  FMS_BOT_USER_ID=
  cache="$state/slack-bot-user/slack-bot-user"
  if fmx_private_artifact_file_valid "$state/slack-bot-user" "slack-bot-user" 600 2>/dev/null; then
    FMS_BOT_USER_ID=$(cat "$cache" 2>/dev/null) || FMS_BOT_USER_ID=
    [ -n "$FMS_BOT_USER_ID" ] && return 0
  fi
  body_file=$(mktemp "${TMPDIR:-/tmp}/fm-slack-auth.XXXXXX") || return 1
  if ! fms_api_post auth.test '' "$body_file"; then
    rm -f -- "$body_file"
    return 1
  fi
  if ! fms_api_json_ok "$body_file"; then
    rm -f -- "$body_file"
    return 1
  fi
  FMS_BOT_USER_ID=$(jq -r '.user_id // empty' "$body_file" 2>/dev/null) || FMS_BOT_USER_ID=
  rm -f -- "$body_file"
  [ -n "$FMS_BOT_USER_ID" ] || return 1
  if ! fmx_private_artifact_publish_stdin "$state/slack-bot-user" "slack-bot-user" 600 \
    <<< "$FMS_BOT_USER_ID"; then
    printf 'failed to publish private Slack bot user cache\n' >&2
    printf 'slack-captain-warning bot user cache publication failed\n'
  fi
  return 0
}

fms_message_ts_valid() {
  case "$1" in
    ''|.*|*/*|*[!0-9.]*|*.*.*.*) return 1 ;;
    [0-9]*.[0-9]*) return 0 ;;
    *) return 1 ;;
  esac
}

fms_is_non_captain_message() {
  local file=$1 bot_user=$2
  jq -e --arg bot "$bot_user" '
    (.subtype? // "") as $sub |
    ($sub != "") or (.bot_id? != null) or
    ((.user? // "") != "" and (.user == $bot))
  ' "$file" >/dev/null 2>&1
}

fms_message_has_text() {
  local file=$1 text
  text=$(jq -r '(.text // "") | gsub("[[:space:]]+"; " ") | gsub("^ +| +$"; "")' "$file" 2>/dev/null) || return 1
  [ -n "$text" ]
}

# Slack reactions used for captain-message acknowledgement and progress.
# Keep this vocabulary as data so acknowledgement and later activity updates
# cannot drift into separate state-to-emoji conditionals.
FMS_REACTION_MAP='received=eyes working=hammer_and_wrench investigating=mag done=white_check_mark failed=x waiting=hourglass'

fms_reaction_name() {
  local state=$1 entry key value
  for entry in $FMS_REACTION_MAP; do
    key=${entry%%=*}
    value=${entry#*=}
    [ "$key" = "$state" ] && { printf '%s' "$value"; return 0; }
  done
  return 1
}

fms_add_reaction() {
  local message_ts=$1 state=$2 body_file=${3:-} name data
  fms_message_ts_valid "$message_ts" || return 1
  fms_channel_configured || return 1
  name=$(fms_reaction_name "$state") || return 1
  if [ -z "$body_file" ]; then
    body_file=$(mktemp "${TMPDIR:-/tmp}/fm-slack-reaction.XXXXXX") || return 1
  fi
  data="channel=$(printf '%s' "$FMS_CHANNEL_ID" | jq -sRr @uri)"
  data="${data}&timestamp=$(printf '%s' "$message_ts" | jq -sRr @uri)"
  data="${data}&name=$(printf '%s' "$name" | jq -sRr @uri)"
  fms_api_post reactions.add "$data" "$body_file" || return 1
  fms_api_json_ok "$body_file"
}

fms_set_reaction() {
  local message_ts=$1 state=$2 target entry name data body_file
  target=$(fms_reaction_name "$state") || return 1
  fms_message_ts_valid "$message_ts" || return 1
  fms_channel_configured || return 1
  for entry in $FMS_REACTION_MAP; do
    name=${entry#*=}
    [ "$name" = "$target" ] && continue
    data="channel=$(printf '%s' "$FMS_CHANNEL_ID" | jq -sRr @uri)"
    data="${data}&timestamp=$(printf '%s' "$message_ts" | jq -sRr @uri)"
    data="${data}&name=$(printf '%s' "$name" | jq -sRr @uri)"
    body_file=$(mktemp "${TMPDIR:-/tmp}/fm-slack-reaction.XXXXXX") || return 1
    fms_api_post reactions.remove "$data" "$body_file" >/dev/null 2>&1 || true
    rm -f -- "$body_file"
  done
  fms_add_reaction "$message_ts" "$state"
}

fms_message_text_oneline() {
  local file=$1
  jq -r '(.text // "") | gsub("\t"; " ") | gsub("\r?\n"; " ") | gsub("[[:space:]]+"; " ") | gsub("^ +| +$"; "")' "$file" 2>/dev/null
}

fms_post_ack() {
  local message_ts=$1 body_file=${2:-}
  export FMS_POST_ACK_FAILED=0
  fms_message_ts_valid "$message_ts" || return 1
  fms_channel_configured || return 1
  if [ -z "$body_file" ]; then
    body_file=$(mktemp "${TMPDIR:-/tmp}/fm-slack-ack.XXXXXX") || return 1
  fi
  if ! fms_add_reaction "$message_ts" received "$body_file"; then
    if jq -e '.ok == false and .error == "already_reacted"' "$body_file" >/dev/null 2>&1; then
      return 0
    fi
    printf 'slack-captain-warning received reaction failed for %s\n' "$message_ts" >&2
    export FMS_POST_ACK_FAILED=1
  fi
  return 0
}

fms_ack_pending_record() {
  local state=$1 ts=$2 dir
  fms_message_ts_valid "$ts" || return 2
  dir="$state/slack-ack-pending"
  printf '%s\n' "$ts" | fmx_private_artifact_publish_stdin_once "$dir" "$ts" 600
}

fms_ack_pending_release() {
  local state=$1 ts=$2
  fms_message_ts_valid "$ts" || return 1
  rm -f -- "$state/slack-ack-pending/$ts" 2>/dev/null
}

fms_ack_complete() {
  local state=$1 ts=$2 dir rc
  fms_message_ts_valid "$ts" || return 2
  dir="$state/slack-acked"
  printf '%s\n' "$ts" | fmx_private_artifact_publish_stdin_once "$dir" "$ts" 600 >/dev/null 2>&1
  rc=$?
  case "$rc" in
    0|1) ;;
    *) return 2 ;;
  esac
  fms_ack_pending_release "$state" "$ts"
}

fms_ack_message() {
  local state=$1 ts=$2 body_file=${3:-} rc
  if fmx_private_artifact_file_valid "$state/slack-acked" "$ts" 600 2>/dev/null; then
    fms_ack_pending_release "$state" "$ts"
    return 0
  fi
  fms_ack_pending_record "$state" "$ts" >/dev/null 2>&1
  rc=$?
  case "$rc" in 0|1) ;; *) return 2 ;; esac
  fms_post_ack "$ts" "$body_file"
  [ "$FMS_POST_ACK_FAILED" -eq 0 ] || return 1
  fms_ack_complete "$state" "$ts"
}

