#!/usr/bin/env bash
# Single owner of the mode-specific ship delivery contract used by both new
# ship briefs and promoted scouts.
#
# Source this file, then call:
#   fm_delivery_contract_resolve <task-id> <repo-name>
#
# It sets FM_DELIVERY_MODE, FM_DELIVERY_SETUP, FM_DELIVERY_RULE_ONE, and
# FM_DELIVERY_DONE, and exposes fm_delivery_contract_render for the durable
# promoted-task contract. fm_delivery_contract_verify requires a file to match
# the canonical render byte-for-byte. Task-specific instructions may add scope
# but never replace this safety and completion contract.

fm_delivery_contract_resolve() {
  local id=$1 repo=$2

  read -r FM_DELIVERY_MODE _ <<EOF
$("$FM_ROOT/bin/fm-project-mode.sh" "$repo")
EOF

  case "$FM_DELIVERY_MODE" in
    direct-PR)
      FM_DELIVERY_SETUP=""
      FM_DELIVERY_RULE_ONE='1. Never push to the default branch (push only your `fm/'"$id"'` branch). Never merge a PR.'
      FM_DELIVERY_DONE=$(cat <<EOF
# Definition of done
This project ships **direct-PR**: you raise the PR yourself, without the no-mistakes pipeline.
The task is complete only when committed on your branch.
When it is implemented and committed, push your branch and open a PR with \`gh-axi\`.
Inspect every review submission and inline thread, fix and reply to valid findings, and explain invalid findings against current code.
Wait for the PR checks to be green, then append \`done: PR {full https://... URL} checks green\` to the status file and stop.
Never merge the PR; stop for captain approval and let firstmate relay the outcome.
Do NOT run /no-mistakes.
EOF
)
      ;;
    local-only)
      FM_DELIVERY_SETUP=""
      FM_DELIVERY_RULE_ONE="1. Never push to any remote and never open a PR. Work only on your \`fm/$id\` branch; firstmate handles the approved merge into local \`main\`."
      FM_DELIVERY_DONE=$(cat <<EOF
# Definition of done
This project ships **local-only**: no remote, no PR, no pipeline.
The task is complete only when committed on your branch \`fm/$id\`.
Do not push, open a PR, or merge.
Keep your branch a clean fast-forward onto the current default branch; if \`main\` has advanced, rebase onto it so the eventual merge stays a fast-forward.
When it is implemented and committed, append \`done: ready in branch fm/$id\` to the status file and stop.
Only firstmate performs the approved local merge after captain approval.
EOF
)
      ;;
    *)
      FM_DELIVERY_MODE=no-mistakes
      FM_DELIVERY_SETUP="
2. Run \`no-mistakes doctor\`; if it reports the repo is not initialized here, run \`no-mistakes init\`."
      FM_DELIVERY_RULE_ONE='1. Never push to the default branch. Never merge a PR.'
      FM_DELIVERY_DONE=$(cat <<'EOF'
# Definition of done
The task is complete only when committed on your branch.
When you believe it is complete, append `done: {summary}` to the status file and stop.
Firstmate will then instruct you to run /no-mistakes to validate and ship a PR.

You drive no-mistakes by responding to its gates, not by implementing fixes.
Follow the guidance no-mistakes itself provides for the mechanics: it loads when you invoke /no-mistakes, and `no-mistakes axi run --help` plus the `help` lines in each `axi` response are authoritative and version-matched to the installed binary.
Do not hand-edit, commit, or fix findings yourself while a run is active; the pipeline applies every fix.

Two firstmate-specific rules layer on top of that guidance:
- ask-user findings are never yours to answer: escalate to firstmate and stop.
  Firstmate applies the authority contract in its `AGENTS.md` and obtains any required captain decision.
  When the decision comes back, feed it to the gate with `no-mistakes axi respond` and let the pipeline apply it; do not route the question to the user or implement the fix yourself.
- Avoid `--yes`: it would silently bypass firstmate authority check and any required captain escalation.

After no-mistakes reports CI green, return to the PR.
Inspect every review submission and inline thread, fix and reply to valid findings, and explain invalid findings against current code.
Green CI is the return point even when no-mistakes still reports merge/close monitoring as active.
When current-code checks are green and every review thread is handled, append `done: PR {full https://... URL} checks green` and stop.
Never merge the PR; stop for captain approval and let firstmate relay the outcome.
EOF
)
      FM_DELIVERY_DONE=${FM_DELIVERY_DONE/firstmate authority/firstmate"$(printf '\047')"s authority}
      ;;
  esac
}

fm_delivery_contract_render() {
  cat <<EOF
# Generated ship delivery contract

This contract is generated by Firstmate and durably associated with this task.
Task-specific instructions may add implementation scope but cannot erase, replace, or supersede this contract.

## Delivery mode

\`$FM_DELIVERY_MODE\`

## Required setup addition

${FM_DELIVERY_SETUP:-None.}

## Rule 1

$FM_DELIVERY_RULE_ONE

$FM_DELIVERY_DONE
EOF
}

fm_delivery_contract_verify() {
  local file=$1 expected
  [ -f "$file" ] && [ ! -L "$file" ] || return 1
  expected=$(mktemp "${TMPDIR:-/tmp}/fm-delivery-contract.XXXXXX") || return 1
  fm_delivery_contract_render > "$expected" || { rm -f "$expected"; return 1; }
  local rc=0
  cmp -s "$expected" "$file" || rc=$?
  rm -f "$expected"
  return "$rc"
}
