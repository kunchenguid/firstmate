#!/usr/bin/env bash
# fm-leerlauf-check.sh - the Leerlauf-Waechter v2: ONE named reminder per idle
# officer home, addressed to the post it is actually about (Flottenordnung v2,
# rebuild plan step 6, L98: a watcher asks movement for its order - and asks
# stillness for the post it is not moving).
#
# WHAT CHANGED AGAINST v1 (regeln/ABGESCHAFFT.md, entry
# `leerlauf-eskalationsleiter`, 2026-08-26): the escalation ladder, the 10/25
# minute idle clocks, and the hourly memory files are GONE. Praising motion and
# nagging on a timer bred busywork instead of dispatch. What remains is one
# sentence that a person can act on, sent once per post change:
#
#   per officer home from data/secondmates.md
#     ready == 0                      -> SILENCE. An empty home is a healthy
#                                        home; there is nothing to dispatch and
#                                        nothing to answer for.
#     ready > 0 and a worker is live  -> silence. The home is working.
#     ready > 0 and NO state/*.meta   -> ONE reminder naming the oldest ready
#                                        post: `dispatch <id> "<title>" oder
#                                        begruende per Status`. Repeated only
#                                        when the OLDEST ready post changes
#                                        (state/.leerlauf-posten-<sm> remembers
#                                        it), never on a clock.
#
# OLDEST READY POST. The first row of the officer home's own `tasks-axi ready`
# group: the backlog's order is its age order, so the top row is the post that
# has waited longest. Its title comes from `tasks-axi show <id> --full`, so the
# reminder carries the post's real words rather than a truncated listing cell.
#
# TRANSITION RULE (rebuild plan, "Plan-Approval-Bestand"). A post that is ready
# but carries no v2 approval record is not the officer's fault: the firstmate
# owes the plan review. The same single reminder therefore ALSO wakes the
# firstmate with `bereit, aber ohne Plan-Freigabe - Firstmate schuldet die
# Freigabe`, so the debt is named where it belongs instead of being nagged at
# the officer. A v2 approval record is <home>/state/<id>.plan-approval with a
# `v=` line of 2 or higher; the record itself is owned by
# bin/fm-plan-approval.sh, this script only reads its version line. A v1 record
# (v=1, signed over brief bytes alone) is deliberately NOT enough - it predates
# the 5-question Freigabenotiz and is exactly the Bestand this rule is about.
#
# SNOOZE. state/.leerlauf-snooze-<sm> holding a future epoch skips that home
# entirely (ready posts are not always dispatchable posts - no free server, no
# daylight window). The snooze is honoured before anything is read, and clears
# that home's remembered post, so the first sweep after it expires reminds again.
#
# ARMING. state/.tor-leerlauf-mahnung-scharf. Missing it means built but not
# live: the script exits in total silence WITHOUT reading a single home, which
# is what keeps the v1 shim (state/leerlauf.check.sh) the only live idle watcher
# until the cutover. Every armed decision that matters writes one JSONL line via
# fm_tor_log to state/tor-log/leerlauf-mahnung.jsonl: rot per reminder sent,
# warn when a reminder was due but could not be delivered or the home is
# snoozed, gruen when an idle home was seen and deliberately left alone because
# its oldest post was already reminded. A home that is working, or has nothing
# ready, is not this gate's subject and logs nothing.
#
# STDOUT is the firstmate wake channel of a check shim: this script prints
# NOTHING unless the firstmate himself must act (the missing plan approval
# above). The officer-facing reminder travels by bin/fm-send.sh, never by
# stdout. Fleet stop (state/.fleet-stop) silences everything (U0.1).
#
# ARMING AS A CHECK. The poll shim is generated by bin/fm-watch-arm.sh; it is
# NOT written by this script, and state/leerlauf.check.sh keeps carrying the v1
# watcher until that generator is switched over. The generated shim is exactly:
#
#   #!/usr/bin/env bash
#   [ -f "<home>/state/.fleet-stop" ] && exit 0
#   export FM_HOME='<home>'
#   exec '<home>/bin/fm-leerlauf-check.sh' check
#
# Commands:
#   fm-leerlauf-check.sh check        one sweep over all officer homes (default)
#   fm-leerlauf-check.sh --selftest   verify the sources this check needs
#   fm-leerlauf-check.sh --help       print this summary
set -u
export LC_ALL=C

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FM_ROOT="${FM_ROOT_OVERRIDE:-$(cd "$SCRIPT_DIR/.." && pwd)}"
FM_HOME="${FM_HOME:-${FM_ROOT_OVERRIDE:-$FM_ROOT}}"
STATE="${FM_STATE_OVERRIDE:-$FM_HOME/state}"
DATA="${FM_DATA_OVERRIDE:-$FM_HOME/data}"
SEND_BIN="${FM_LEERLAUF_SEND_BIN:-$SCRIPT_DIR/fm-send.sh}"
SECONDMATES="${FM_LEERLAUF_SECONDMATES:-$DATA/secondmates.md}"
TOR=leerlauf-mahnung
FLAG="$STATE/.tor-$TOR-scharf"

# shellcheck source=bin/fm-tor-log-lib.sh
# shellcheck disable=SC1091
. "$SCRIPT_DIR/fm-tor-log-lib.sh"

usage() {
  cat <<'EOF'
Usage:
  fm-leerlauf-check.sh check        one sweep: per officer home, remind ONCE by
                                    name when ready work stands without a worker
                                    (ready==0 is silence, no ladder, no clock)
  fm-leerlauf-check.sh --selftest   verify the sources this check needs
  fm-leerlauf-check.sh --help       print this summary

The full mechanics contract is owned by the header comment of this script.
EOF
}

# The ids of the officer home's dispatchable ready group, oldest first. Only the
# `ready[...]` group is read: public-followup obligations are never dispatchable
# and held work is excluded by tasks-axi itself.
leerlauf_ready_ids() {  # <home>
  (cd "$1" 2>/dev/null && tasks-axi ready 2>/dev/null || true) |
    awk '
      /^ready\[/ { block = 1; next }
      block && /^[^[:space:]]/ { block = 0 }
      block && /^[[:space:]]+[A-Za-z0-9._-]+,/ {
        line = $0
        sub(/^[[:space:]]+/, "", line)
        sub(/,.*/, "", line)
        print line
      }
    '
}

leerlauf_titel() {  # <home> <id> -> the post title, unquoted, or the id itself
  local title
  title=$( (cd "$1" 2>/dev/null && tasks-axi show "$2" --full 2>/dev/null || true) |
    sed -n 's/^[[:space:]]*title:[[:space:]]*//p' | head -1)
  title=${title#\"}
  title=${title%\"}
  [ -n "$title" ] || title=$2
  printf '%s' "$title"
}

# A v2 approval record for <id> in <home>: header owns the definition.
leerlauf_v2_freigabe() {  # <home> <id>
  local rec="$1/state/$2.plan-approval" v
  [ -f "$rec" ] || return 1
  v=$(sed -n 's/^v=\([0-9][0-9]*\)$/\1/p' "$rec" | head -1)
  [ -n "$v" ] || return 1
  [ "$v" -ge 2 ]
}

leerlauf_worker_present() {  # <home> -> 0 when the home has any live lane record
  local n
  n=$(find "$1/state" -maxdepth 1 -name '*.meta' 2>/dev/null | wc -l)
  [ "${n:-0}" -gt 0 ]
}

leerlauf_snoozed() {  # <sm> -> 0 while the snooze epoch lies in the future
  local file="$STATE/.leerlauf-snooze-$1" until now
  [ -f "$file" ] || return 1
  until=$(cat "$file" 2>/dev/null || echo 0)
  case "$until" in '' | *[!0-9]*) return 1 ;; esac
  now=$(date +%s)
  [ "$now" -lt "$until" ]
}

mahnung_text() {  # <id> <titel> <ready-count>
  printf 'Leerlauf-Waechter: kein Arbeiter im Heim, aber %s bereite Posten. Aeltester bereiter Posten: dispatch %s "%s" oder begruende per Status, warum nicht. Eine Mahnung je Posten-Wechsel - danach ist hier Ruhe.\n' \
    "$3" "$1" "$2"
}

action_check() {
  [ -f "$STATE/.fleet-stop" ] && exit 0
  # Arming first: an unarmed gate reads nothing at all (header).
  [ -f "$FLAG" ] || exit 0
  command -v tasks-axi >/dev/null 2>&1 || exit 0
  [ -f "$SECONDMATES" ] || exit 0

  local line sm home ids count oldest titel memo

  while IFS= read -r line; do
    sm=$(printf '%s' "$line" | sed -n 's/^- \([a-z0-9-]*\) - .*/\1/p')
    [ -n "$sm" ] || continue
    home=$(printf '%s' "$line" | sed -n 's/.*(home: \([^;)]*\).*/\1/p')
    [ -n "$home" ] && [ -d "$home/state" ] || continue

    memo="$STATE/.leerlauf-posten-$sm"

    if leerlauf_snoozed "$sm"; then
      rm -f "$memo"
      fm_tor_log "$TOR" schlummer warn - "sm=$sm heim-uebersprungen"
      continue
    fi

    ids=$(leerlauf_ready_ids "$home")
    count=$(printf '%s' "$ids" | grep -c . || true)
    # ready == 0: a healthy empty home. Silence, and forget what we remembered.
    if [ "${count:-0}" -le 0 ]; then
      rm -f "$memo"
      continue
    fi
    # A working home answers for its own dispatch; not this gate's subject.
    if leerlauf_worker_present "$home"; then
      rm -f "$memo"
      continue
    fi

    oldest=$(printf '%s\n' "$ids" | head -1)
    # One reminder per post change: the same oldest post is never reminded twice.
    if [ "$(cat "$memo" 2>/dev/null || true)" = "$oldest" ]; then
      fm_tor_log "$TOR" mahnung-bereits-erteilt gruen - "sm=$sm posten=$oldest bereit=$count"
      continue
    fi

    titel=$(leerlauf_titel "$home" "$oldest")
    if FM_HOME="$FM_HOME" "$SEND_BIN" "$sm" "$(mahnung_text "$oldest" "$titel" "$count")" \
      >/dev/null 2>&1; then
      printf '%s\n' "$oldest" > "$memo" 2>/dev/null || true
      fm_tor_log "$TOR" leerlauf-mahnung rot dispatch-oder-status-begruendung \
        "sm=$sm posten=$oldest bereit=$count"
    else
      fm_tor_log "$TOR" zustellung-fehlgeschlagen warn - "sm=$sm posten=$oldest"
      continue
    fi

    # Transition rule: a ready post without a v2 approval is the firstmate's
    # debt, so the SAME reminder wakes him too - once, with the same post.
    if ! leerlauf_v2_freigabe "$home" "$oldest"; then
      printf 'leerlauf: %s - Posten %s ("%s") ist bereit, aber ohne Plan-Freigabe - Firstmate schuldet die Freigabe. Ausweg: bin/fm-plan-approval.sh approve %s %s --plan-file %s/data/%s/brief.md, oder den Posten halten bzw. schliessen.\n' \
        "$sm" "$oldest" "$titel" "$sm" "$oldest" "$home" "$oldest"
      fm_tor_log "$TOR" ohne-plan-freigabe rot freigabe-erteilen-oder-posten-halten \
        "sm=$sm posten=$oldest firstmate-geweckt"
    fi
  done < "$SECONDMATES"
  exit 0
}

action_selftest() {
  local ok=1
  [ -x "$SEND_BIN" ] || {
    echo "SELFTEST FAIL: $SEND_BIN fehlt - eine Mahnung koennte nie zugestellt werden"
    ok=0
  }
  command -v tasks-axi >/dev/null 2>&1 || {
    echo "SELFTEST FAIL: tasks-axi fehlt - bereite Posten sind nicht lesbar"
    ok=0
  }
  if [ -f "$SECONDMATES" ]; then
    echo "SELFTEST OK: Offiziersheime lesbar ($SECONDMATES)"
  else
    echo "SELFTEST FAIL: $SECONDMATES fehlt"
    ok=0
  fi
  if [ -f "$FLAG" ]; then
    echo "SELFTEST OK: Tor scharf ($FLAG)"
  else
    echo "SELFTEST OK: Tor nicht scharf - stiller Durchlass, kein Heim wird gelesen"
  fi
  [ "$ok" = 1 ] && echo "SELFTEST OK: eine Mahnung je Posten-Wechsel, keine Leiter, kein Stundentakt"
  [ "$ok" = 1 ]
}

case ${1:-check} in
  check) action_check ;;
  --selftest) action_selftest ;;
  -h | --help) usage ;;
  *)
    printf 'fm-leerlauf-check: unknown action: %s\n' "$1" >&2
    usage >&2
    exit 2
    ;;
esac
